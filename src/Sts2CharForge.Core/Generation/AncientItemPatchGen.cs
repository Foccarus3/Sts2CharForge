using Sts2CharForge.Core.Profile;

namespace Sts2CharForge.Core.Generation;

/// <summary>
/// V0.2.260（用户要求）：让三件**先古道具**指向本模组的卡 / 遗物。
///
/// <list type="bullet">
///   <item>「古老牙齿 ArchaicTooth」——它把角色那张**初始卡**换成一张先古卡。本体只认自己那张表
///         （打击→破击 / 中和→压制 / 释放→保护者…），自定义角色的初始卡不在表里 ⇒ 它会给你一张
///         <c>Doubt</c>（怀疑）。勾了「替换古老牙齿所替换的初始卡牌」之后，这里生成一个 Harmony 前缀，
///         轮到本模组角色时用本体自带的 <c>SetupForTests(初始卡, 这张先古卡)</c> 把两张卡直接定好。</item>
///   <item>「尘封魔典 DustyTome」——本体是从角色的卡池里**随机**挑一张先古卡
///         （还排掉古老牙齿那 5 张）；勾了「作为尘封魔典给的先古卡」就直接给这一张。</item>
///   <item>「欧洛巴斯之触 TouchOfOrobas」——它把**初始遗物**换成强化版。本体只认自己那张表，
///         自定义角色的初始遗物不在表里 ⇒ 会给「头环 Circlet」；勾了「替换欧洛巴斯之触所替换的初始遗物」
///         就换成这一只（同样走本体的 <c>SetupForTests</c>）。</item>
/// </list>
///
/// 三个前缀都只对**本模组角色**生效（`player.Character is 我们的角色`），别的角色照旧走本体 ——
/// 装了我们的 mod 但玩别的角色时，这三件道具的行为和原版完全一致。
/// </summary>
public static class AncientItemPatchGen
{
    public const string File = "AncientItemPatches";

    /// <summary>这个存档需不需要这个文件（三个勾都不勾 = 一个文件都不多，生成文本逐字不变）。</summary>
    public static bool Needs(CharacterProfile p) =>
        ToothCard(p) is not null || TomeCard(p) is not null || OrobasRelic(p) is not null;

    /// <summary>勾了「替换古老牙齿所替换的初始卡牌」的那张先古卡（没勾 / 不是先古卡 → null）。</summary>
    public static CardSpec? ToothCard(CharacterProfile p) =>
        p.AllCards.FirstOrDefault(c => c.ToothReplace && c.IsAncientCard);

    /// <summary>勾了「作为尘封魔典给的先古卡」的那张先古卡。</summary>
    public static CardSpec? TomeCard(CharacterProfile p) =>
        p.AllCards.FirstOrDefault(c => c.DustyTomeGrant && c.IsAncientCard);

    /// <summary>勾了「替换欧洛巴斯之触所替换的初始遗物」的那只遗物。</summary>
    public static RelicSpec? OrobasRelic(CharacterProfile p) =>
        p.Relics.FirstOrDefault(r => r.OrobasReplace);

    /// <summary>
    /// 古老牙齿要换掉的那张「初始卡」：
    /// <list type="number">
    ///   <item>V0.2.261（用户问「那我如何决定是哪张牌被替换呢」）：先看这张先古卡上填的
    ///         <see cref="CardSpec.ToothStarterClass"/> —— 填了就用它指定的那张牌；</item>
    ///   <item>没填 → 取**我们自己的、在初始卡组里**的第一张（卡组顺序 = 「初始卡组」那一栏自上而下）；</item>
    ///   <item>还没有 → 任何一张在初始卡组里的牌；</item>
    ///   <item>一张都没有 → null（生成时不写这个补丁，交给校验器提示）。</item>
    /// </list>
    /// </summary>
    public static CardSpec? StarterCardFor(CharacterProfile p, CardSpec? ancient = null)
    {
        string want = (ancient?.ToothStarterClass ?? "").Trim();
        if (want.Length > 0)
        {
            var n = Naming.From(p);
            var explicitCard = p.AllCards.FirstOrDefault(c => string.Equals(n.CardClassName(p, c), want, StringComparison.Ordinal));
            if (explicitCard is not null) return explicitCard;
        }
        return p.AllCards.FirstOrDefault(c => !c.IsVanillaCard && c.InStartingDeck)
            ?? p.AllCards.FirstOrDefault(c => c.InStartingDeck);
    }

    public static string Source(CharacterProfile p)
    {
        var n = Naming.From(p);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 先古道具专属：古老牙齿 / 尘封魔典 / 欧洛巴斯之触 指向本模组 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line();

        var tooth = ToothCard(p);
        var starter = StarterCardFor(p, tooth);
        if (tooth is not null && starter is not null)
        {
            string toothCls = n.CardClassName(p, tooth);
            string starterCls = n.CardClassName(p, starter);
            w.Line("/// <summary>")
             .Line($"/// 古老牙齿：本模组角色 → 初始卡「{starter.Name}」换成先古卡「{tooth.Name}」。")
             .Line("/// 不打这个补丁的话，本体那张「初始卡 → 先古卡」表里没有我们的卡，会变成「怀疑 Doubt」。")
             .Line("/// </summary>")
             .Line($"[HarmonyLib.HarmonyPatch(typeof(ArchaicTooth), nameof(ArchaicTooth.SetupForPlayer))]")
             .Open($"internal static class {n.CharClass}ArchaicToothPatch")
             .Open("private static bool Prefix(ArchaicTooth __instance, Player player, ref bool __result)")
             .Line($"if (player.Character is not {n.CharClass}) return true;   // 别的角色照本体那套")
             .Line($"CardModel starter = player.RunState.CreateCard<{starterCls}>(player);")
             .Line($"CardModel ancient = player.RunState.CreateCard<{toothCls}>(player);")
             .Line("__instance.SetupForTests(starter.ToSerializable(), ancient.ToSerializable());")
             .Line("__result = true;   // V0.2.280：本体这个方法是 bool —— 返回 false 会被当成「这件遗物对这个角色不可用」，先古之民房间里就**不显示**它")
        .Line("return false;   // 跳过本体：它会把我们的初始卡换成「怀疑」")
             .Close()
             .Close()
             .Line();
            // V0.2.263（用户报「欧罗巴斯的两个遗物都没办法正常生效」）：只改 SetupForPlayer 不够 ——
            // 真正**发效果**的是 AfterObtained，而本体那条（ArchaicTooth.cs:168）自己再查一次它那张
            // 「初始卡 → 先古卡」表（`GetTranscendenceStarterCard`）：我们的卡不在表里 → 拿到 null →
            // 那一句 CardCmd.Transform 什么都换不掉。这里直接把「换牌」这一步接过来做。
            w.Line("/// <summary>拿到古老牙齿那一刻：直接把指定初始卡变成这张先古卡（本体表里没有我们的卡）。</summary>")
             .Line("[HarmonyLib.HarmonyPatch(typeof(ArchaicTooth), nameof(ArchaicTooth.AfterObtained))]")
             .Open($"internal static class {n.CharClass}ArchaicToothObtainedPatch")
             .Open("private static bool Prefix(ArchaicTooth __instance, ref Task __result)")
             .Line($"if (__instance.Owner?.Character is not {n.CharClass}) return true;")
             .Line($"CardModel? starter = __instance.Owner.Deck.Cards.FirstOrDefault(c => c is {starterCls});")
             .Line("if (starter is null) return true;   // 牌组里没有那张初始卡：交给本体（它会换「怀疑」）")
             .Line("__result = TransformAsync(__instance, starter);")
             .Line("return false;")
             .Close()
             .Line()
             .Open("private static async Task TransformAsync(ArchaicTooth tooth, CardModel starter)")
             .Line($"CardModel ancient = tooth.Owner.RunState.CreateCard<{toothCls}>(tooth.Owner);")
             .Line("if (starter.IsUpgraded) CardCmd.Upgrade(ancient);   // 初始卡升级过 → 先古卡也跟着升级（本体同样的做法）")
             .Line("await CardCmd.Transform(starter, ancient);")
             .Close()
             .Close()
             .Line();
        }

        var tome = TomeCard(p);
        if (tome is not null)
        {
            string tomeCls = n.CardClassName(p, tome);
            w.Line("/// <summary>")
             .Line($"/// 尘封魔典：本模组角色 → 直接给先古卡「{tome.Name}」（本体是从卡池里随机挑一张先古卡）。")
             .Line("/// </summary>")
             .Line("[HarmonyLib.HarmonyPatch(typeof(DustyTome), nameof(DustyTome.SetupForPlayer))]")
             .Open($"internal static class {n.CharClass}DustyTomePatch")
             .Open("private static bool Prefix(DustyTome __instance, Player player, ref bool __result)")
             .Line($"if (player.Character is not {n.CharClass}) return true;")
             .Line($"__instance.AncientCard = ModelDb.Card<{tomeCls}>().Id;")
                .Line("__result = true;   // V0.2.280: 本体这个方法是 bool, 返回 false 会被当成不可用 -> 先古之民房间里不显示")
             .Line("return false;")
             .Close()
             .Close()
             .Line();
        }
        else if (tooth is not null)
        {
            // V0.2.263（用户报「勾选替换古老牙齿的先古反而会出现在达弗的尘封魔典里」）：
            // 本体尘封魔典是从卡池里随机挑一张先古卡，只排掉它自己那 5 张「古老牙齿换出来的卡」
            //（DustyTome.cs:53 `!ArchaicTooth.TranscendenceCards.Contains(c)`）—— 我们的先古卡不在那 5 张里，
            // 于是会被随机到。这里按本体同一套逻辑重挑一次，把我们那张「古老牙齿专用」的先古卡排掉。
            string toothCls2 = n.CardClassName(p, tooth);
            w.Line("/// <summary>")
             .Line($"/// 尘封魔典：本模组角色 → 随机挑一张先古卡，但**排掉**「古老牙齿」专用的「{tooth.Name}」")
             .Line("///（本体只排自己那 5 张，排不掉我们的）。")
             .Line("/// </summary>")
             .Line("[HarmonyLib.HarmonyPatch(typeof(DustyTome), nameof(DustyTome.SetupForPlayer))]")
             .Open($"internal static class {n.CharClass}DustyTomeExcludePatch")
             .Open("private static bool Prefix(DustyTome __instance, Player player, ref bool __result)")
             .Line($"if (player.Character is not {n.CharClass}) return true;")
             .Line("var pool = player.Character.CardPool")
             .Line("    .GetUnlockedCards(player.UnlockState, player.RunState.CardMultiplayerConstraint)")
             .Line("    .Where(c => c.Rarity == CardRarity.Ancient")
             .Line("        && !ArchaicTooth.TranscendenceCards.Contains(c)")
             .Line($"        && c is not {toothCls2})   // 我们的「古老牙齿专用」先古卡不进尘封魔典")
             .Line("    .ToList();")
             .Line("if (pool.Count == 0) return true;   // 一张都不剩就交回本体（它会自己去挑）")
             .Line("__instance.AncientCard = player.PlayerRng.Rewards.NextItem(pool).Id;")
                .Line("__result = true;   // V0.2.280: 本体这个方法是 bool, 返回 false 会被当成不可用 -> 先古之民房间里不显示")
             .Line("return false;")
             .Close()
             .Close()
             .Line();
        }

        var orobas = OrobasRelic(p);
        if (orobas is not null)
        {
            int idx = p.Relics.IndexOf(orobas);
            string relicCls = n.RelicClassName(orobas, idx);
            w.Line("/// <summary>")
             .Line($"/// 欧洛巴斯之触：本模组角色 → 初始遗物换成「{orobas.Name}」")
             .Line("/// （不打这个补丁的话，本体那张表里没有我们的初始遗物，会给「头环 Circlet」）。")
             .Line("/// </summary>")
             .Line("[HarmonyLib.HarmonyPatch(typeof(TouchOfOrobas), nameof(TouchOfOrobas.SetupForPlayer))]")
             .Open($"internal static class {n.CharClass}TouchOfOrobasPatch")
             .Open("private static bool Prefix(TouchOfOrobas __instance, Player player, ref bool __result)")
             .Line($"if (player.Character is not {n.CharClass}) return true;")
             .Line("RelicModel? starter = player.Relics.FirstOrDefault(r => r.Rarity == RelicRarity.Starter);")
             .Line("if (starter is null) return true;   // 没有初始遗物就不插手")
             .Line($"__instance.SetupForTests(starter.Id, ModelDb.Relic<{relicCls}>().Id);")
                .Line("__result = true;   // V0.2.280: 本体这个方法是 bool, 返回 false 会被当成不可用 -> 先古之民房间里不显示")
             .Line("return false;")
             .Close()
             .Close()
             .Line();
            // V0.2.263（用户报「欧罗巴斯的两个遗物都没办法正常生效」）：真正换遗物的是 AfterObtained，
            // 本体那句是 `StarterRelic ?? 牌组里第一只初始遗物` / `UpgradedRelic ?? 查表 → 头环`；
            // 表里没有我们的遗物 → 它会给「头环 Circlet」。这里直接把替换这一步接过来。
            w.Line("/// <summary>拿到欧洛巴斯之触那一刻：直接把初始遗物换成这一只（本体表里没有我们的遗物）。</summary>")
             .Line("[HarmonyLib.HarmonyPatch(typeof(TouchOfOrobas), nameof(TouchOfOrobas.AfterObtained))]")
             .Open($"internal static class {n.CharClass}TouchOfOrobasObtainedPatch")
             .Open("private static bool Prefix(TouchOfOrobas __instance, ref Task __result)")
             .Line($"if (__instance.Owner?.Character is not {n.CharClass}) return true;")
             .Line("RelicModel? starter = __instance.Owner.Relics.FirstOrDefault(r => r.Rarity == RelicRarity.Starter);")
             .Line("if (starter is null) return true;   // 没有初始遗物：交给本体")
             .Line("__result = ReplaceAsync(starter);")
             .Line("return false;")
             .Close()
             .Line()
             .Open("private static async Task ReplaceAsync(RelicModel starter)")
             .Line($"RelicModel replace = ModelDb.Relic<{relicCls}>().ToMutable();")
             .Line("await RelicCmd.Replace(starter, replace);")
             .Close()
             .Close()
             .Line();
        }

        return w.ToString();
    }
}
