using System;
using System.Collections.Generic;
using System.Linq;
using Sts2CharForge.Core.Profile;

namespace Sts2CharForge.Core.Generation;

/// <summary>
/// V0.2.289（用户要求）：四个「百分比」状态 —— 用本体的 <c>ModifyDamageMultiplicative</c>
/// （见本体 <c>VulnerablePower.cs:28</c>）把伤害乘一个系数：
/// 受到伤害 +N% / 受到伤害 −N% / 造成伤害 +N% / 造成伤害 −N%（N = 层数，50 = 50%）。
///
/// <para>只作用于「有来源的攻击」（<c>props.IsPoweredAttack()</c>），和本体易伤 / 虚弱同口径。</para>
/// </summary>
public static class PercentPowers
{
    public const string Vuln = "PercentVuln";
    public const string TakenReduce = "PercentTakenReduce";
    public const string DamageUp = "PercentDamageUp";
    public const string DamageReduce = "PercentDamageReduce";

    /// <summary>四个 Id + 中文名（下拉 / 卡面描述用）。</summary>
    public static readonly (string Id, string Zh)[] All =
    {
        (Vuln, "百分比易伤（受到伤害 +N%）"),
        (TakenReduce, "百分比减伤（受到伤害 −N%）"),
        (DamageUp, "百分比增伤（造成伤害 +N%）"),
        (DamageReduce, "百分比减弱（造成伤害 −N%）"),
    };

    /// <summary>正在生成哪个存档（深层发射器拿不到 profile 时用它拼类名前缀）。</summary>
    public static CharacterProfile? Current;

    /// <summary>四个后缀（类名去掉前缀后长这样）—— 用来把「已解析的类名」也认出来。</summary>
    private static readonly string[] ClassSuffixes =
        { "PercentVulnPower", "PercentTakenReducePower", "PercentDamageUpPower", "PercentDamageReducePower" };

    public static bool IsPercent(string? id)
    {
        string s = (id ?? "").Trim();
        if (s.Length == 0) return false;
        if (All.Any(x => string.Equals(x.Id, s, StringComparison.OrdinalIgnoreCase))) return true;
        return ClassSuffixes.Any(x => s.EndsWith(x, StringComparison.Ordinal));
    }

    /// <summary>把「别名 / 已解析的类名」都归一成别名（PercentVuln …）。</summary>
    public static string? CanonicalIdOf(string? id)
    {
        string s = (id ?? "").Trim();
        if (s.Length == 0) return null;
        foreach (var x in All)
            if (string.Equals(x.Id, s, StringComparison.OrdinalIgnoreCase)) return x.Id;
        foreach (string suf in ClassSuffixes)
            if (s.EndsWith(suf, StringComparison.Ordinal))
                return All.First(a => suf.StartsWith(a.Id, StringComparison.OrdinalIgnoreCase)
                                      || string.Equals(a.Id + "Power", suf, StringComparison.OrdinalIgnoreCase)).Id;
        return null;
    }

    public static string? ClassOf(string? id) => Current is null ? null : ClassOf(id, Current);

    public static string? ClassOf(string? id, CharacterProfile p)
    {
        string? canon = CanonicalIdOf(id);
        if (canon is null) return null;
        string prefix = Naming.From(p).CharClass;
        string key = canon;
        if (string.Equals(key, Vuln, StringComparison.OrdinalIgnoreCase)) return prefix + "PercentVulnPower";
        if (string.Equals(key, TakenReduce, StringComparison.OrdinalIgnoreCase)) return prefix + "PercentTakenReducePower";
        if (string.Equals(key, DamageUp, StringComparison.OrdinalIgnoreCase)) return prefix + "PercentDamageUpPower";
        return prefix + "PercentDamageReducePower";
    }

    /// <summary>四个状态用哪张本体图标（ArtGenerator 拿它去染紫）。</summary>
    public static string VanillaIconOf(string? id) =>
        string.Equals(id, Vuln, StringComparison.OrdinalIgnoreCase) ? "vulnerable"
        : string.Equals(id, TakenReduce, StringComparison.OrdinalIgnoreCase) ? "weak"
        : string.Equals(id, DamageUp, StringComparison.OrdinalIgnoreCase) ? "strength"
        : "dexterity";

    /// <summary>这个存档用过哪几个百分比状态（用到哪个就生成哪个类 / 哪张图）。</summary>
    /// <summary>
    /// 这个存档用过哪几个百分比状态（用到哪个就生成哪个类 / 哪张图 / 哪三条本地化）。
    ///
    /// <para>V0.2.301（用户报「自定义状态里给百分比增伤，描述变英文且不生效」）：
    /// 以前只扫卡牌 / 遗物 / 药水，**漏了自定义状态的触发效果和锻造图** —— 于是类没生成、
    /// 本地化也没写，游戏里就显示成一串英文键名。现在直接用 <see cref="CSharpCodeGen.AllEffects"/>（同一份口径）。</para>
    /// </summary>
    public static List<string> UsedIn(CharacterProfile p)
    {
        var used = new List<string>();
        foreach (var e in CSharpCodeGen.AllEffects(p))
        {
            if (e is null) continue;
            string? key = CanonicalIdOf(e.PowerId);
            if (key is not null && !used.Contains(key)) used.Add(key);
        }
        return used;
    }
    /// <summary>一个百分比状态的源码。</summary>
    public static string Source(CharacterProfile p, string id)
    {
        var n = Naming.From(p);
        string cls = ClassOf(id, p)!;
        bool isVuln = string.Equals(id, Vuln, StringComparison.OrdinalIgnoreCase);
        bool isTaken = string.Equals(id, TakenReduce, StringComparison.OrdinalIgnoreCase);
        bool isUp = string.Equals(id, DamageUp, StringComparison.OrdinalIgnoreCase);
        string who = (isVuln || isTaken) ? "target" : "dealer";
        string sign = (isVuln || isUp) ? "+" : "-";
        string zh = All.First(x => string.Equals(x.Id, id, StringComparison.OrdinalIgnoreCase)).Zh;
        string type = (isVuln || isTaken) ? "Debuff" : "Buff";
        string icon = VanillaIconOf(id);

        var w = new CodeWriter();
        w.Line($"// <auto-generated> 百分比状态：{zh} </auto-generated>");
        w.Line($"namespace {n.Namespace};");
        w.Line();
        w.Open($"public sealed class {cls} : PowerModel");
        w.Line($"public override PowerType Type => PowerType.{type};");
        w.Line();
        w.Line("public override PowerStackType StackType => PowerStackType.Counter;");
        w.Line();
        w.Line($"// 图标：本体「{icon}」染紫的那一张，由 ArtGenerator 按类名写成 images/powers/<id>.png + 图集条目（和自定义状态同一条管线）。");
        w.Line();
        w.Line("/// <summary>层数就是百分比：50 = 50%。</summary>");
        w.Line("private decimal Pct => base.Amount / 100m;");
        w.Line();
        w.Open("public override decimal ModifyDamageMultiplicative(Creature? target, decimal amount, ValueProp props, Creature? dealer, CardModel? cardSource, CardPlay? cardPlay)");
        w.Line($"if ({who} != base.Owner) return 1m;              // 只看自己{(isVuln || isTaken ? "受到" : "造成")}的");
        w.Line("if (!props.IsPoweredAttack()) return 1m;        // 和本体易伤同口径：只作用于有来源的攻击");
        w.Line($"return System.Math.Max(0m, 1m {sign} Pct);      // 50 → ×1.5；-50 → ×0.5");
        w.Close();
        w.Close();
        return w.ToString();
    }
}
