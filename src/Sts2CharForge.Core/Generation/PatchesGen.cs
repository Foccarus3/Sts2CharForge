using Sts2CharForge.Core.Profile;

namespace Sts2CharForge.Core.Generation;

/// <summary>模组入口与全部 Harmony 补丁（把踩过的坑内建成模板）。</summary>
public static class PatchesGen
{
    /// <summary>建筑师对话行数（至少 1 行，否则本体 WinRun() 会空引用）。</summary>
    public static List<string> ArchitectLines(CharacterProfile p)
    {
        var lines = (p.ArchitectDialogue ?? string.Empty)
            .Replace("\r\n", "\n")
            .Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .ToList();
        if (lines.Count == 0) lines.Add("……又是一个闯入者。");
        return lines;
    }

    /// <summary>
    /// 「先古卡」的卡框染色补丁（只在「诅咒 / 先古卡」页给先古卡设了卡框颜色时才生成）。
    ///
    /// **为什么非要有它**：先古卡（稀有度 Ancient）在卡面节点里**根本不显示普通的 Frame** ——
    /// <c>NCard.Reload()</c> 里写死了 <c>_frame.Visible = (稀有度 != Ancient)</c>，先古卡显示的是
    /// <c>AncientBorder</c> / <c>AncientTextBg</c> / <c>AncientBanner</c> 这三张先古专用贴图，
    /// 而它们**没有材质、只吃节点的 modulate**。所以「换 VisualCardPool 的卡框材质」对先古卡
    /// **一点效果都没有**（用户实测报过「改了 RRGGBB 没反应」）—— 那个材质只对诅咒这类普通卡生效。
    ///
    /// 这里在 NCard 每次 Reload 之后，把属于我们外观池的先古卡的 AncientBorder / AncientBanner
    /// 的 modulate **乘上**你填的颜色（本体自己也是这么给这两张图上色的：场景里 AncientBorder 的
    /// 默认 modulate 就是 (1, 0.978, 0.906, 0.502)）。乘的时候必须先记住「本体原本的 modulate」：
    /// Reload 会被反复调用、节点还会被复用，直接连乘会越来越暗。
    /// </summary>
    public static string StyledCardTintSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        // 染什么颜色：勾了「自定义颜色」用填的 RRGGBB；选的是本体框色名（这时 FrameColor 是空的）
        // 就用那个框色对应的种子色 —— 不然这里会生成 new Godot.Color("#")，
        // 运行时解析不出来（Godot 会往日志里报错、染色也不生效，看上去就是「改了没反应」）。
        string hex = CardColorSpec.NormalizeHex(p.AncientStyle.FrameColor);
        if (hex.Length == 0) hex = CardColorSpec.SeedColorForFrame(p.AncientStyle.Frame);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 先古卡的卡框染色补丁（先古卡不显示普通 Frame，只能改这几张图的 modulate） </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Line("/// <summary>")
         .Line("/// 先古卡在卡面节点里不显示普通的 Frame（NCard.Reload 里 _frame.Visible = 稀有度 != Ancient），")
         .Line("/// 显示的是 AncientBorder / AncientTextBg / AncientBanner 三张先古专用贴图 —— 它们没有材质、")
         .Line("/// 只吃节点的 modulate。所以「换 VisualCardPool 的卡框材质」对先古卡没有效果，")
         .Line("/// 这里把 AncientBorder / AncientBanner 的 modulate 乘上「诅咒 / 先古卡」页里填的颜色。")
         .Line("/// 诅咒不是先古卡（Frame 可见），走的是卡框材质，不在这里重复染。")
         .Line("/// 这个补丁在模组入口里**手动打**（不是 PatchAll）：打不上也只是没有染色，不影响别的功能。")
         .Line("/// </summary>")
         .Open($"internal static class {n.CharClass}StyledCardTint")
         .Line("/// <summary>每个节点「本体原本的 modulate」：Reload 会被反复调用、节点还会被复用，")
         .Line("/// 记下原色才能每次都算出同一个结果（否则乘第二次就会更暗）。</summary>")
         .Line("private static readonly System.Runtime.CompilerServices.ConditionalWeakTable<Godot.TextureRect, Godot.Color[]> Original = new();")
         .Line()
         .Open("public static void Postfix(MegaCrit.Sts2.Core.Nodes.Cards.NCard __instance)")
         .Open("try")
         .Line("CardModel? card = __instance.Model;")
         .Line($"// 只有「先古卡 + 用了我们那个外观池」才染：{"#"+hex}（颜色是生成时就写死的）")
         .Line($"Godot.Color? tint = card is {{ Rarity: CardRarity.Ancient }} && card.VisualCardPool is {n.AncientStylePoolClass}")
         .Line($"    ? new Godot.Color({Lit.Str("#" + hex)})")
         .Line("    : null;")
         .Line("Recolor(__instance, \"%AncientBorder\", tint);   // 先古卡那一圈边框")
         .Line("Recolor(__instance, \"%AncientBanner\", tint);   // 顶部那条先古横幅（含火焰动画）")
         .Close()
         .Open("catch")
         .Line("// 纯外观：出错就当没这回事，绝不能影响卡牌本身")
         .Close()
         .Close()
         .Line()
         .Line("private static void Recolor(MegaCrit.Sts2.Core.Nodes.Cards.NCard card, string nodePath, Godot.Color? tint)")
         .Open("")
         .Line("Godot.TextureRect? rect = card.GetNodeOrNull<Godot.TextureRect>(nodePath);")
         .Line("if (rect is null) return;")
         .Line("if (!Original.TryGetValue(rect, out Godot.Color[]? bas))")
         .Open("")
         .Line("bas = new[] { rect.Modulate };")
         .Line("Original.Add(rect, bas);")
         .Close()
         .Line("// 染色 = 在本体原本的颜色上乘一遍（透明度保持不变，免得把先古边框那层半透明弄没）")
         .Line("Godot.Color want = tint is { } c")
         .Line("    ? new Godot.Color(bas[0].R * c.R, bas[0].G * c.G, bas[0].B * c.B, bas[0].A)")
         .Line("    : bas[0];")
         .Line("if (!rect.Modulate.IsEqualApprox(want)) rect.Modulate = want;")
         .Close()
         .Close()
         .Line();
        return w.ToString();
    }

    /// <summary>
    /// 模组入口。第二个参数是「逐帧动画计划」：勾了动画时要把注册行（缩放 / Y 偏移 / 速度 + 每个动作的帧资源）
    /// 注入 <c>Initialize()</c> 里；不勾时传 null，生成结果与以前完全一样。
    /// </summary>
    public static string ModEntrySource(CharacterProfile p, AnimFramesGen.Plan? animPlan = null)
    {        var n = Naming.From(p);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 模组入口 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Line($"// 模组 ID：{n.ModId}")
         .Line("[ModInitializer(nameof(Initialize))]")
         .Open($"public static class {n.CharClass}ModInitializer")
         .Open("public static void Initialize()")
         .Open("try")
         .Line("// 让 Godot 检索本程序集，建立场景/脚本资源映射（模组里带场景时必须）")
         .Line("Godot.Bridge.ScriptManagerBridge.LookupScriptsInAssembly(System.Reflection.Assembly.GetExecutingAssembly());")
         .Line();

        w.Line("// 卡池/遗物池/药水池的成员统一在各自池类的 GenerateAllXxx() 里给出（含全部自有内容），")
         .Line("// 这里不再调用 ModHelper.AddModelToPool，避免同一张卡被重复登记进同一个池。")
         .Line()
         .Line($"var harmony = new HarmonyLib.Harmony({Lit.Str(n.ModId)});")
         .Line("harmony.PatchAll(System.Reflection.Assembly.GetExecutingAssembly());");

        // 无色卡（用户要求）是上面那条规矩的**唯一例外**：本体的无色卡池 ColorlessCardPool 的成员表是
        // 写死的（sealed 类里硬编码），模组只能靠 AddModelToPool 在**游戏初始化之前**登记 ——
        // 晚了本体自己会抛「it's too late! You must add content before the game is initialized.」
        //（本体 src/Core/Modding/ModHelper.cs）。模组入口就是初始化之前跑的，位置正好。
        w.Line();
        {
            var colorless = p.AllCards.Where(c => c is not null && !c.IsVanillaCard && c.IsColorless).ToList();
            if (colorless.Count > 0)
            {
                w.Line("// 无色卡（用户要求）：登记进本体的无色卡池 —— 这样它们自动用本体的无色卡框 / 能量前缀，")
                 .Line("// 而且**不进**你角色的卡池（战斗奖励抽的是你角色的卡池）。")
                 .Open("try")
                 .Line("var __colorlessPool = typeof(MegaCrit.Sts2.Core.Models.CardPools.ColorlessCardPool);")
                 .Line("var __asm = System.Reflection.Assembly.GetExecutingAssembly();");
                foreach (var c in colorless)
                {
                    string cls = n.CardClassName(p, c);
                    w.Line($"if (__asm.GetType({Lit.Str(n.Namespace + "." + cls)}) is {{ }} __t{cls})")
                     .Line($"    MegaCrit.Sts2.Core.Modding.ModHelper.AddModelToPool(__colorlessPool, __t{cls});   // 「{c.Name}」")
                     .Line($"else Log.Warn({Lit.Str("无色卡类找不到，跳过登记：" + cls)});");
                }
                w.Close()
                 .Open("catch (Exception e)")
                 .Line("Log.Error(\"无色卡登记失败（这几张卡不会出现在无色卡池里）：\" + e.Message);")
                 .Close();
            }
        }

        // 逐帧动画：把每个动作的帧资源注册进生成的 FrameAnimRegistry（不勾总开关时一行都不写）
        if (animPlan is not null)
            foreach (string line in FrameAnimGen.RegistrationLines(p, animPlan)) w.Line(line);

        // 「先古卡染色」补丁单独手动打：它是打在 NCard 的**私有方法** Reload 上的，
        // 万一本体改了方法名，绝不能连累整个模组加载（PatchAll 抛异常的话角色注册也一起没了）。
        if (p.AncientStyle.Any)
        {
            w.Line()
             .Line("// 先古卡的卡框染色（见 StyledCardTint.cs）：单独手动打，失败了只丢染色、不影响别的补丁")
             .Open("try")
             .Line("var __tintTarget = HarmonyLib.AccessTools.Method(typeof(MegaCrit.Sts2.Core.Nodes.Cards.NCard), \"Reload\");")
             .Line("if (__tintTarget is not null)")
             .Line($"    harmony.Patch(__tintTarget, postfix: new HarmonyLib.HarmonyMethod(typeof({n.CharClass}StyledCardTint), nameof({n.CharClass}StyledCardTint.Postfix)));")
             .Line("else")
             .Line($"    Log.Warn({Lit.Str("先古卡染色补丁没打上：找不到 NCard.Reload（本体的卡面节点可能改过）")});")
             .Close()
             .Open("catch (Exception e)")
             .Line($"Log.Warn({Lit.Str("先古卡染色补丁没打上：")} + e.Message);")
             .Close();
        }

        // 自定义状态的「覆盖血条」补丁也单独手动打（同一个原因：打在**私有**方法 RefreshForeground 上，
        // 本体改了名字时带特性的 PatchAll 会抛异常、整个模组加载不了）。
        //
        // ⚠ V0.2.185：用户报「覆盖血条没显示出来」时日志里一个字都没有 —— 因为生成出来的补丁
        //   成功 / 静默失败都不出声，根本分不清「没生成（存档里没填颜色）」「没打上」「打上了没触发」。
        //   所以这里加载时就把**表里有哪几条**打出来（一眼看出模组里到底有没有这个功能）。
        //
        // ⚠ V0.2.311（用户报「两个状态却有 3 个颜色」）：以前这里**两个入口都打**（RefreshForeground +
        //   它的调用方 RefreshValues），而 RefreshValues 内部会先调一次 RefreshForeground ⇒ 同一次刷新
        //   我们的 Postfix 跑两遍：第一遍把红条按覆盖条宽度缩一次，第二遍拿**已经缩过**的值再缩一次，
        //   红条右端多退了一整截、中间那截露出本体的浅红「掉血预览条」→ 2 条状态看着像 3 段颜色。
        //   现在**只打 RefreshForeground**；只有在找不到它时才退而求其次接 RefreshValues（各打一次，不并存）。
        if (HpBarOverlayGen.Needs(p))
        {
            w.Line()
             .Line("// 自定义状态覆盖血条（见 ForgeHpBarOverlay.cs）：单独手动打，失败了只丢这一截颜色、不影响别的补丁")
             .Line($"Log.Info({Lit.Str(HpBarOverlayGen.LoadSummary(p))});")
             .Open("try")
             .Line($"var __hpOverlay = {HpBarOverlayGen.ClassName}.Target;")
             .Open("if (__hpOverlay is not null)")
             .Line($"    harmony.Patch(__hpOverlay, postfix: new HarmonyLib.HarmonyMethod(typeof({HpBarOverlayGen.ClassName}), nameof({HpBarOverlayGen.ClassName}.Postfix)));")
             .Close()
             .Open("else")
             // 兜底：只接 RefreshValues 这一个入口（它内部会调 RefreshForeground，所以只跑一遍）
             .Line($"    Log.Warn({Lit.Str("自定义状态覆盖血条：找不到 NHealthBar.RefreshForeground，改接它的调用方 RefreshValues（本体的血条节点可能改过）")});")
             .Line($"    var __hpValues = {HpBarOverlayGen.ClassName}.ValuesTarget;")
             .Open("if (__hpValues is not null)")
             .Line($"        harmony.Patch(__hpValues, postfix: new HarmonyLib.HarmonyMethod(typeof({HpBarOverlayGen.ClassName}), nameof({HpBarOverlayGen.ClassName}.Postfix)));")
             .Close()
             .Open("else")
             .Line($"        Log.Warn({Lit.Str("自定义状态覆盖血条补丁没打上：两个入口都找不到（本体的血条类可能改过）")});")
             .Close()
             .Close()
             .Close()
             .Open("catch (Exception e)")
             .Line($"Log.Warn({Lit.Str("自定义状态覆盖血条补丁没打上：")} + e.Message);")
             .Close();
        }

        // 「资源不够、这张牌打不出去」那句提示（本体键里写死了「辉星」）也单独手动打：
        // 目标方法在**本体的 internal 类**里，编译期连 typeof 都写不出来（只能 AccessTools.TypeByName），
        // 所以绝不能用带特性的 PatchAll —— 找不到时只丢这一句提示，不影响别的补丁。
        if (CSharpCodeGen.HasExtraResourceUi(p) || CSharpCodeGen.NeedsStarCap(p))
        {
            w.Line()
             .Line("// 额外资源量「不够用」那句提示换成我们自己的键（见 ExtraResourceUi.cs 的 ForgeNotEnoughMessage）：单独手动打")
             .Open("try")
             .Line($"var __notEnough = {n.CharClass}ForgeNotEnoughMessage.Target;")
             .Line("if (__notEnough is not null)")
             .Line($"    harmony.Patch(__notEnough, postfix: new HarmonyLib.HarmonyMethod(typeof({n.CharClass}ForgeNotEnoughMessage), nameof({n.CharClass}ForgeNotEnoughMessage.Postfix)));")
             .Line("else")
             .Line($"    Log.Warn({Lit.Str("额外资源量：找不到本体的 UnplayableReasonExtensions.GetPlayerDialogueLine，「资源不够」那句提示保持本体原文（辉星）")});")
             .Close()
             .Open("catch (Exception e)")
             .Line($"Log.Warn({Lit.Str("额外资源量：「资源不够」提示补丁没打上：")} + e.Message);")
             .Close();
        }

        // 「被给予自定义关键词」的卡面描述 / 悬停提示（见 GivenKeywords.cs）：**逐个重载手动打**。
        // ⚠ 这两个补丁以前是带 [HarmonyPatch] 的，靠 PatchAll 打 —— 本体 v0.111 给
        //   CardModel.GetDescriptionForPile 加了第二个重载（2 参 + 3 参），只写方法名的特性补丁
        //   会让 PatchAll 抛 Harmony 的 "Ambiguous match"，而 PatchAll 一抛异常**整个初始化器就中断**
        //   ⇒ 角色 / 卡池 / 遗物全都没注册，用户实测的表现是「进游戏找不到这个角色（存档也没了）」。
        //   所以这里跟另外三处补丁同一套做法：反射拿全部重载、逐个 Patch，各自 try 一次。
        if (CSharpCodeGen.UsesGivenCustomKeyword(p))
        {
            w.Line()
             .Line("// 「被给予自定义关键词」：卡面描述 + 悬停提示（GivenKeywords.cs 里那两个 Postfix）")
             .Line("// ⚠ 手动逐个重载打：本体 GetDescriptionForPile 有 2 个重载，特性补丁会让 PatchAll 抛 \"Ambiguous match\"，")
             .Line("//   而 PatchAll 一抛异常整个初始化器就中断（角色注册一起没了）。")
             .Open("try")
             .Open("foreach (var __descMethod in typeof(MegaCrit.Sts2.Core.Models.CardModel).GetMethods(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance))")
             .Line("if (__descMethod.Name == \"GetDescriptionForPile\")")
             .Line("    harmony.Patch(__descMethod, postfix: new HarmonyLib.HarmonyMethod(typeof(GivenKeywordTextPatch), nameof(GivenKeywordTextPatch.After)));")
             .Close()
             .Close()
             .Open("catch (Exception e)")
             .Line($"Log.Warn({Lit.Str("「被给予自定义关键词」的卡面描述补丁没打上（不影响别的功能）：")} + e.Message);")
             .Close()
             .Open("try")
             .Line("var __hoverProp = typeof(MegaCrit.Sts2.Core.Models.CardModel).GetProperty(\"ExtraHoverTips\", System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance);")
             .Line("if (__hoverProp?.GetGetMethod(true) is { } __hoverGet)")
             .Line("    harmony.Patch(__hoverGet, postfix: new HarmonyLib.HarmonyMethod(typeof(GivenKeywordHoverPatch), nameof(GivenKeywordHoverPatch.After)));")
             .Line("else")
             .Line($"    Log.Warn({Lit.Str("「被给予自定义关键词」的悬停说明补丁没打上：找不到 CardModel.ExtraHoverTips（本体可能改过）")});")
             .Close()
             .Open("catch (Exception e)")
             .Line($"Log.Warn({Lit.Str("「被给予自定义关键词」的悬停说明补丁没打上（不影响别的功能）：")} + e.Message);")
             .Close();
        }

        w.Line()
         .Line($"Log.Info({Lit.Str(n.ModId + " - 加载成功!")});")
         .Close()
         .Open("catch (Exception e)")
         .Line($"Log.Error({Lit.Str(n.ModId + " - 加载失败")});")
         .Line("// ⚠ 打全量：MethodBase.Invoke 抛出来的是 TargetInvocationException，真正的原因在 InnerException 里，")
         .Line("//   只打 e.Message 会得到一句套话（或什么都没有），用户报「找不到角色/存档」时根本查不出原因。")
         .Line("var __inner = (e as System.Reflection.TargetInvocationException)?.InnerException ?? e;")
         .Line("Log.Error(__inner.GetType().Name + \": \" + __inner.Message);")
         .Line("Log.Error(__inner.ToString());")
         .Close()
         .Close()
         .Close();
        return w.ToString();
    }

    public static string PatchesSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        int lineCount = ArchitectLines(p).Count;

        var w = new CodeWriter();
        w.Line("// <auto-generated> Harmony 补丁：角色注册 / 音效与成就 / 结算保护 / 建筑师对话 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Line("// 把自定义角色加进可选角色列表（本体的 AllCharacters 是硬编码数组）")
         .Line("[HarmonyLib.HarmonyPatch(typeof(ModelDb), nameof(ModelDb.AllCharacters), HarmonyLib.MethodType.Getter)]")
         .Open($"public static class {n.CharClass}RegistrationPatch")
         .Open("static void Postfix(ref IEnumerable<CharacterModel> __result)")
         .Line($"__result = __result.Append(ModelDb.Character<{n.CharClass}>()).Distinct();")
         .Close()
         .Close()
         .Line()
         .Line("// ============================================================")
         .Line("// 卡池聚合属性（本体是 _allXxx ??= ... 的惰性缓存）：")
         .Line("// 只要别的模组/初始化流程在我们注册角色之前读过一次，缓存里就永远没有我们的卡池，")
         .Line("// 结果 ModelDb.Preload() 遍历 AllCards 时 CardModel.Pool 查不到 → ")
         .Line("// InvalidProgramException: Card CARD.XXX is not in any card pool!（卡牌无法识别）")
         .Line("// 每个 getter 都挂 postfix 追加自己的内容，这样与缓存时序无关。")
         .Line("[HarmonyLib.HarmonyPatch(typeof(ModelDb), nameof(ModelDb.AllCharacterCardPools), HarmonyLib.MethodType.Getter)]")
         .Open($"public static class {n.CharClass}CardPoolsPatch")
         .Open("static void Postfix(ref IEnumerable<CardPoolModel> __result)")
         .Line($"__result = __result.Append(ModelDb.CardPool<{n.CardPoolClass}>()).Distinct();")
         .Close()
         .Close()
         .Line()
         .Line("[HarmonyLib.HarmonyPatch(typeof(ModelDb), nameof(ModelDb.AllCardPools), HarmonyLib.MethodType.Getter)]")
         .Open($"public static class {n.CharClass}AllCardPoolsPatch")
         .Open("static void Postfix(ref IEnumerable<CardPoolModel> __result)")
         .Line($"__result = __result.Append(ModelDb.CardPool<{n.CardPoolClass}>()).Distinct();")
         .Close()
         .Close()
         .Line()
         .Line("[HarmonyLib.HarmonyPatch(typeof(ModelDb), nameof(ModelDb.AllCards), HarmonyLib.MethodType.Getter)]")
         .Open($"public static class {n.CharClass}AllCardsPatch")
         .Open("static void Postfix(ref IEnumerable<CardModel> __result)")
         .Line($"__result = __result.Concat(ModelDb.CardPool<{n.CardPoolClass}>().AllCards)")
         .Line($"    .Concat(ModelDb.Character<{n.CharClass}>().StartingDeck).Distinct();")
         .Close()
