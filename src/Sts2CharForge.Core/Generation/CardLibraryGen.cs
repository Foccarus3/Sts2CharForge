using Sts2CharForge.Core.Effects;
using Sts2CharForge.Core.Profile;

namespace Sts2CharForge.Core.Generation;

/// <summary>
/// 「卡牌图鉴」（本体 <c>NCardLibrary</c>）对 **mod 角色**的补丁。
///
/// 用户实测（BugkillerMod，`godot2026-10-15T08.25.44.log`）：
/// <code>
/// ERROR: System.Collections.Generic.KeyNotFoundException:
///        The given key 'CHARACTER.BUGKILLER (28743066)' was not present in the dictionary.
///    at MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardLibrary.OnSubmenuOpened_Patch1(...)
/// </code>
///
/// **真因（本体源码）**：<c>NCardLibrary._Ready()</c> 里那张「角色 → 卡池筛选器」的表
/// <c>Dictionary&lt;CharacterModel, NCardPoolFilter&gt; _cardPoolFilters</c> 只 Add 了**5 个官方角色**
/// （`src/Core/Nodes/Screens/CardLibrary/NCardLibrary.cs:290-294`），
/// 而 <c>OnSubmenuOpened()</c> 第 470 行直接 <c>_cardPoolFilters[characterModel]</c> ——
/// **只要这一局玩的是 mod 角色就 KeyNotFoundException**，异常抛在 `NSubmenuStack.Push()` 里，
/// 图鉴停在「打开到一半」的状态（用户看到的「点图鉴就卡死」）。
///
/// 补法：在 <c>OnSubmenuOpened</c> 之前把我方角色补进那张表，并且**给它一个真能用的筛选器按钮**：
///   · 按钮直接实例化本体的 `res://scenes/screens/card_library/library_pool_toggle.tscn`
///     （本体那 8 个筛选器就是它的实例，自带的 `%SelectionReticle` 在自己场景里，所以 `_Ready` 正常）；
///   · 头像换成本体 <c>images/ui/top_panel/character_icon_&lt;角色&gt;.png</c>（模组自己那张，没上传时是本体占位）；
///   · 卡池谓词 = <c>c.Pool is &lt;我们的卡池&gt;</c> → 图鉴打开时默认列的就是**我们自己角色的卡**
///     （以前这张表里没有我们的池，图鉴里根本看不到自己角色的卡）；
///   · 点它时的行为和本体那 8 个一模一样（接上本体私有的 <c>UpdateCardPoolFilter</c>，radio 式互斥 + 刷新）；
///   · 任何一步出岔子都退化成「挂到本体『杂项』那个筛选器上」——**少一个按钮可以，崩不行**。
/// </summary>
public static class CardLibraryGen
{
    /// <summary>生成出来的文件名 / 类名。</summary>
    public const string File = "ForgeCardLibrary";

    public const string ClassName = "ForgeCardLibraryPatch";

    /// <summary>本体那 8 个筛选器用的场景（本体的 <c>card_library.tscn</c> 里就是它的实例）。</summary>
    public const string ToggleScenePath = "res://scenes/screens/card_library/library_pool_toggle.tscn";

    /// <summary>生成 cs/ForgeCardLibrary.cs。</summary>
    public static string Source(CharacterProfile p)
    {
        var n = Naming.From(p);
        string iconPath = "res://images/ui/top_panel/character_icon_" + n.CharSlug + ".png";
        string charLocKey = n.CharEntry + ".title";

        return $$"""
// <auto-generated>由 Sts2CharForge 生成：卡牌图鉴（本体 NCardLibrary）对 mod 角色的补丁。</auto-generated>
namespace {{n.Namespace}};

/// <summary>
/// 本体卡牌图鉴的「卡池筛选器」表只给 5 个官方角色建了（<c>NCardLibrary._Ready</c> 里写死的 5 个 Add），
/// 而 <c>OnSubmenuOpened</c> 直接 <c>_cardPoolFilters[这一局的我方角色]</c> ——
/// **mod 角色一进图鉴就 KeyNotFoundException**，界面停在「打开到一半」（用户实测日志：
/// <c>KeyNotFoundException: The given key 'CHARACTER.XXX' was not present in the dictionary.</c>）。
///
/// 这里在打开图鉴之前把「我方角色 → 我们自己的卡池筛选器」补进本体那张表：
///   · 按钮实例化本体的 <c>{{ToggleScenePath}}</c>（本体那 8 个就是它的实例）；
///   · 头像换成本体的 <c>{{iconPath}}</c>（模组自己那张）；
///   · 卡池谓词 = <c>c.Pool is {{n.CardPoolClass}}</c> → 图鉴默认列出来的是我们自己角色的卡；
///   · 点它时和本体那 8 个行为一致（接上本体私有的 UpdateCardPoolFilter）；
///   · 任何一步出岔子都退化成「挂到本体『杂项』上」—— 少一个按钮可以，崩不行。
/// </summary>
[HarmonyLib.HarmonyPatch(typeof(MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardLibrary), nameof(MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardLibrary.OnSubmenuOpened))]
internal static class {{ClassName}}
{
    private const string ToggleScene = {{Lit.Str(ToggleScenePath)}};
    private const string OurIcon = {{Lit.Str(iconPath)}};
    private const string VanillaIcon = "res://images/ui/top_panel/character_icon_ironclad.png";

    [HarmonyLib.HarmonyPrefix]
    private static void Before(MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardLibrary __instance)
    {
        try { Ensure(__instance); }
        catch (Exception e)
        {
            Log.Error("卡牌图鉴：给 mod 角色补卡池筛选器失败（已忽略，图鉴可能少一个按钮）：" + e);
        }
    }

    private static void Ensure(MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardLibrary lib)
    {
        // ① 这一局玩的是不是我方角色（主菜单 / 别的角色 → 一个像素都不碰）
        CharacterModel? me = null;
        try
        {
            if (MegaCrit.Sts2.Core.Runs.RunManager.Instance.IsInProgress)
                me = MegaCrit.Sts2.Core.Context.LocalContext
                    .GetMe(MegaCrit.Sts2.Core.Runs.RunManager.Instance.DebugOnlyGetState())?.Character;
        }
        catch { }
        if (me is not {{n.CharClass}}) return;

        // ② 本体那张表（两个私有字段）
        Type t = typeof(MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardLibrary);
        var map = t.GetField("_cardPoolFilters", System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic)
            ?.GetValue(lib) as Dictionary<CharacterModel, MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter>;
        var pools = t.GetField("_poolFilters", System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic)
            ?.GetValue(lib) as Dictionary<MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter, Func<CardModel, bool>>;
        if (map is null || pools is null) return;
        if (map.ContainsKey(me)) return;      // 已经有了（本体以后自己加了 / 别的 mod 补过）→ 不重复加

        // ③ 现造一个筛选器按钮（本体那 8 个同款场景）
        MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter? filter = null;
        try
        {
            var scene = ResourceLoader.Load<PackedScene>(ToggleScene);
            if (scene is not null)
            {
                filter = scene.Instantiate<MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter>();
                if (filter is not null)
                {
                    filter.Name = {{Lit.Str(n.CharClass + "Pool")}};

                    Texture2D? icon = ResourceLoader.Load<Texture2D>(OurIcon) ?? ResourceLoader.Load<Texture2D>(VanillaIcon);
                    if (icon is not null)
                    {
                        TextureRect? img = filter.GetNodeOrNull<TextureRect>("Image");
                        if (img is not null)
                        {
                            img.Texture = icon;
                            TextureRect? shadow = img.GetNodeOrNull<TextureRect>("Shadow");
                            if (shadow is not null) shadow.Texture = icon;
                        }
                    }

                    // 悬停提示 = 我们自己角色的名字（本体那 8 个是 card_library.POOL_*_TIP）
                    if (LocString.Exists("characters", {{Lit.Str(charLocKey)}}))
                        filter.Loc = new LocString("characters", {{Lit.Str(charLocKey)}});

                    // 挂在本体里放那 8 个筛选器的同一个容器里（Sidebar/.../PoolFilters，4 列的 GridContainer）
                    Control? container = lib.GetNodeOrNull<Control>("%IroncladPool")?.GetParentOrNull<Control>();
                    if (container is null) filter = null;
                    else container.AddChild(filter);
                }
            }
        }
        catch (Exception e)
        {
            Log.Warn("卡牌图鉴：造自己的卡池筛选器失败，退化成挂在「杂项」上：" + e.Message);
            filter = null;
        }

        if (filter is not null)
        {
            try
            {
                // 点它的行为和本体那 8 个一模一样：本体私有方法 UpdateCardPoolFilter(NCardPoolFilter)
                var upd = HarmonyLib.AccessTools.Method(
                    typeof(MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardLibrary), "UpdateCardPoolFilter");
                if (upd?.CreateDelegate(
                        typeof(Action<MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter>), lib)
                    is Action<MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter> act)
                    filter.Connect(MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter.SignalName.Toggled, Callable.From(act));
                filter.Visible = true;
                pools[filter] = (CardModel c) => c.Pool is {{n.CardPoolClass}};
            }
            catch (Exception e)
            {
                Log.Warn("卡牌图鉴：自己的筛选器接不上点击事件（按钮还在，点了不切池）：" + e.Message);
            }
        }

        // ④ 退路：挂到本体的「杂项」筛选器上（只是不再抛异常；卡的列表要用户自己点筛选）
        if (filter is null)
        {
            filter = lib.GetNodeOrNull<MegaCrit.Sts2.Core.Nodes.Screens.CardLibrary.NCardPoolFilter>("%MiscPool");
            if (filter is null) return;
        }

        map[me] = filter;
    }
}
""";
    }
}
