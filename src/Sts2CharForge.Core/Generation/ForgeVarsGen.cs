using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Sts2CharForge.Core.Profile;

namespace Sts2CharForge.Core.Generation;

/// <summary>
/// 变量页的**生成端**——把 <c>profile.Variables</c> 渲染成一个静态容器类。
///
/// <para>规格（用户 2026-11-04 定稿）：</para>
/// <item>不勾「全局」= 每场战斗归零（<see cref="ResetCombat"/>）；勾上 = <b>本局内跨战斗</b>保留（<see cref="ResetRun"/>，新开一局调）。</item>
/// <item>一律 <c>int</c>；勾「允许负数」才不夹下限；<c>Max</c> 封顶。</item>
/// <item>值可以写公式（初值），公式在生成时内联成 C# 表达式（引用别的变量 → <c>XxxVars.name</c>）。</item>
/// </summary>
public static class ForgeVarsGen
{
    /// <summary>容器类名：<c>&lt;角色前缀&gt;Vars</c>（例 SparkleVars）。</summary>
    public static string ClassName(Naming n) => n.CharClass + "Vars";

    /// <summary>有没有需要生成的变量（没有时**一个字符都不写**，老存档输出逐字不变）。</summary>
    public static bool Needed(CharacterProfile? p) => p is not null && p.Variables.Any(v => v is not null && v.Name.Length > 0);

    /// <summary>渲染 <c>cs/&lt;角色&gt;Vars.cs</c>。</summary>
    public static string Source(CharacterProfile p, Naming n)
    {
        string cls = ClassName(n);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 变量页：用户自定义的可读写变量（计数器） </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public static class {cls}");

        var vars = p.Variables.Where(v => v is not null && v.Name.Length > 0).ToList();

        // 字段 + 属性（字段初值 = 初值公式能折成常数时那个数；折不出来 = 0，见 TryInitialValue）
        foreach (var v in vars)
        {
            int init = TryInitialValue(p, v, out int iv) ? iv : 0;
            w.Line($"private static int _{v.Name} = {init.ToString(CultureInfo.InvariantCulture)};")
             .Line($"/// <summary>{(string.IsNullOrWhiteSpace(v.Note) ? v.Name : v.Note)}{(v.Global ? "（本局内跨战斗保留）" : "（每场战斗归零）")}</summary>")
             .Open($"public static int {v.Name}")
             .Line($"get => _{v.Name};");
            string clamp = ClampExpr(v);
            w.Line($"set => _{v.Name} = {clamp};")
             .Close()
             .Line();
        }

        // 重置：初值公式能折成常数就用它，否则 0（UI / 校验器会说清）
        var combat = vars.Where(v => !v.Global).ToList();
        var run = vars.Where(v => v.Global).ToList();
        w.Line("/// <summary>战斗开始时调用：把「本场战斗」作用域的变量复位（全局的不动）。</summary>")
         .Open("public static void ResetCombat()")
         .Line(combat.Count == 0 ? "// 没有「本场战斗」作用域的变量" : string.Join(" ", combat.Select(ResetLine)))
         .Close()
         .Line()
         .Line("/// <summary>新开一局时调用：连同全局变量一起复位。</summary>")
         .Open("public static void ResetRun()")
         .Line(run.Count == 0
             ? "ResetCombat();"
             : string.Join(" ", run.Select(ResetLine)) + (combat.Count == 0 ? "" : " " + string.Join(" ", combat.Select(ResetLine))))
         .Close()
         .Close();

        return w.ToString();

        string ResetLine(VarSpec v) =>
            $"{v.Name} = {(TryInitialValue(p, v, out int iv) ? iv : 0).ToString(CultureInfo.InvariantCulture)};";
    }

    /// <summary>
    /// 变量重置补丁（战斗开始 + 新开一局）。
    ///
    /// <para>为什么不用「角色类里 override BeforeCombatStart」：本体 <c>Hook.BeforeCombatStart</c>
    /// 只遍历 <c>IRunState.IterateHookListeners</c> 里的模型（卡牌 / 遗物 / 药水 / 修正 / 订阅者 / 战斗内模型），
    /// <b>角色模型本身不在里面</b>（见本体 <c>RunState.cs</c> 的 IterateHookListeners）。所以必须在唯一的派发出口
    /// <c>Hook.BeforeCombatStart</c> 上打一个前缀补丁；新开一局则挂在 <c>RunManager.Launch</c>（新局 / 读档都会走它）。
    /// 两个补丁都先判断「这一局里有没有我们这个角色」，别的角色不会碰。</para>
    /// </summary>
    public static string ResetPatchSource(CharacterProfile p, Naming n)
    {
        string vars = ClassName(n);
        bool hasGlobal = p.Variables.Any(v => v is not null && v.Name.Length > 0 && v.Global);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 变量重置：战斗开始 / 新开一局 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Line("/// <summary>每场战斗开始时把「本场战斗」作用域的变量复位。</summary>")
         .Line("[HarmonyLib.HarmonyPatch(typeof(MegaCrit.Sts2.Core.Hooks.Hook), nameof(MegaCrit.Sts2.Core.Hooks.Hook.BeforeCombatStart))]")
         .Open($"public static class {n.CharClass}ForgeVarsResetCombat")
         .Open("static void Prefix(MegaCrit.Sts2.Core.Runs.IRunState runState)")
         .Open("try")
         .Line($"if (runState.Players.Any(p => p.Character is {n.CharClass})) {vars}.ResetCombat();")
         .Close()
         .Open("catch (Exception e)")
         .Line("Log.Warn(\"[变量页] 战斗开始重置变量失败：\" + e.Message);")
         .Close()
         .Close()
         .Close();

        if (hasGlobal)
        {
            w.Line()
             .Line("/// <summary>新开一局（RunManager.Launch）时连全局变量一起复位。</summary>")
             .Line("[HarmonyLib.HarmonyPatch(typeof(MegaCrit.Sts2.Core.Runs.RunManager), nameof(MegaCrit.Sts2.Core.Runs.RunManager.Launch))]")
             .Open($"public static class {n.CharClass}ForgeVarsResetRun")
             .Open("static void Postfix(MegaCrit.Sts2.Core.Runs.RunManager __instance)")
             .Open("try")
             .Line("var state = __instance.DebugOnlyGetState();")
             .Line($"if (state is not null && state.Players.Any(p => p.Character is {n.CharClass})) {vars}.ResetRun();")             .Close()
             .Open("catch (Exception e)")
             .Line("Log.Warn(\"[变量页] 新开一局重置变量失败：\" + e.Message);")
             .Close()
             .Close()
             .Close();
        }
        return w.ToString();
    }

    /// <summary>
    /// 初值公式能不能在生成时折成一个整数（只允许数字 / 其他变量的初值 / 四则与常量函数）。
    /// 用到 X / Y / 内置只读量 / 自定义参数（它们要运行时才有值）→ 返回 false，重置按 0。
    /// </summary>
    public static bool TryInitialValue(CharacterProfile p, VarSpec v, out int value)
    {
        value = 0;
        var map = p.Variables.Where(x => x is not null && x.Name.Length > 0)
            .GroupBy(x => x.Name, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        return TryVar(v, map, new HashSet<string>(StringComparer.Ordinal), out value);
    }

    private static bool TryVar(VarSpec v, IReadOnlyDictionary<string, VarSpec> map, HashSet<string> stack, out int value)
    {
        value = 0;
        if (!stack.Add(v.Name)) return false;   // 环（校验器会报错，这里只防死循环）
        try
        {
            string f = EffectSpec.FormulaText(v.Formula);
            if (f.Length == 0) return true;
            var root = ForgeFormula.TryParse(f, out _);
            if (root is null) return false;
            if (!ForgeFormula.TryEvalConst(root, id =>
                {
                    if (!map.TryGetValue(id, out var other)) return null;
                    return TryVar(other, map, stack, out int ov) ? ov : (decimal?)null;
                }, out decimal d, out _))
                return false;
            value = ClampInitial(v, d);
            return true;
        }
        finally
        {
            stack.Remove(v.Name);
        }
    }

    /// <summary>给界面用的一句话：这个变量每场战斗 / 每局开始时复位成多少。</summary>
    public static string ResetPreview(CharacterProfile p, VarSpec v)
    {
        string where = v.Global ? "新开一局时" : "每场战斗开始时";
        if (TryInitialValue(p, v, out int n))
            return $"{where}复位为 {n.ToString(CultureInfo.InvariantCulture)}。";
        return $"{where}复位为 0（初值公式里有 X / Y / 内置读数 / 参数，生成时折不出常数）。";
    }

    /// <summary>计数器的夹取表达式：不允许负数 → <c>Math.Max(0, x)</c>；有上限 → 再 <c>Math.Min(Max, x)</c>。</summary>
    private static string ClampExpr(VarSpec v)
    {
        string expr = "value";
        if (!v.AllowNegative) expr = $"Math.Max(0, {expr})";
        if (v.Max != int.MaxValue) expr = $"Math.Min({v.Max.ToString(CultureInfo.InvariantCulture)}, {expr})";
        return expr;
    }

    /// <summary>把折出来的 decimal 收到 int 允许的范围，再按「允许负数 / 上限」夹一次。</summary>
    private static int ClampInitial(VarSpec v, decimal d)
    {
        decimal r = Math.Round(d, MidpointRounding.AwayFromZero);
        if (r > int.MaxValue) r = int.MaxValue;
        if (r < int.MinValue) r = int.MinValue;
        int n = (int)r;
        if (!v.AllowNegative) n = Math.Max(0, n);
        if (v.Max != int.MaxValue) n = Math.Min(v.Max, n);
        return n;
    }
}
