using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Sts2CharForge.Core.Generation;

/// <summary>
/// V0.3.13：变量页的**生成端**——把 <c>profile.Variables</c> 渲染成一个静态容器类。
///
/// <para>规格（用户 2026-11-04 定稿）：</para>
/// <item>不勾「全局」= 每场战斗归零（<see cref="ResetCombat"/>）；勾上 = <b>本局内跨战斗</b>保留（<see cref="ResetRun"/>，新开一局调）。</item>
/// <item>一律 <c>int</c>；勾「允许负数」才不夹下限；<c>Max</c> 封顶。</item>
/// <item>值可以写公式（初值），公式在生成时内联成 C# 表达式（引用别的变量 → <c>XxxVars.name</c>）。</item>
/// </summary>
public static class ForgeVarsGen
{
    /// <summary>容器类名：<c>&lt;角色前缀&gt;Vars</c>（例 SparkleVars）。</summary>
    public static string ClassName(Naming n) => n.CharClass + "Vars";

    /// <summary>有没有需要生成的变量（没有时**一个字符都不写**，老存档输出逐字不变）。</summary>
    public static bool Needed(Profile.CharacterProfile? p) => p is not null && p.Variables.Any(v => v is not null && v.Name.Length > 0);

    /// <summary>渲染 <c>cs/&lt;角色&gt;Vars.cs</c>。</summary>
    public static string Source(Profile.CharacterProfile p, Naming n)
    {
        string cls = ClassName(n);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 变量页：用户自定义的可读写变量（计数器） </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public static class {cls}");

        var vars = p.Variables.Where(v => v is not null && v.Name.Length > 0).ToList();

        // 字段 + 属性
        foreach (var v in vars)
        {
            w.Line($"private static int _{v.Name}{(v.Global ? "" : " = 0")};")
             .Line($"/// <summary>{(string.IsNullOrWhiteSpace(v.Note) ? v.Name : v.Note)}{(v.Global ? "（本局内跨战斗保留）" : "（每场战斗归零）")}</summary>")
             .Open($"public static int {v.Name}")
             .Line($"get => _{v.Name};");
            string clamp = ClampExpr(v);
            w.Line($"set => _{v.Name} = {clamp};")
             .Close()
             .Line();
        }

        // 重置
        var combat = vars.Where(v => !v.Global).ToList();
        var run = vars.Where(v => v.Global).ToList();
        w.Line("/// <summary>战斗开始时调用：把「本场战斗」作用域的变量归零（全局的不动）。</summary>")
         .Open("public static void ResetCombat()")
         .Line(combat.Count == 0 ? "// 没有「本场战斗」作用域的变量" : string.Join(" ", combat.Select(v => $"{v.Name} = 0;")))
         .Close()
         .Line()
         .Line("/// <summary>新开一局时调用：连同全局变量一起归零。</summary>")
         .Open("public static void ResetRun()")
         .Line(run.Count == 0 ? "ResetCombat();" : string.Join(" ", run.Select(v => $"{v.Name} = 0;")) + (combat.Count == 0 ? "" : " " + string.Join(" ", combat.Select(v => $"{v.Name} = 0;"))))
         .Close()
         .Close();

        return w.ToString();
    }

    /// <summary>计数器的夹取表达式：不允许负数 → <c>Math.Max(0, x)</c>；有上限 → 再 <c>Math.Min(Max, x)</c>。</summary>
    private static string ClampExpr(Profile.VarSpec v)
    {
        string expr = "value";
        if (!v.AllowNegative) expr = $"Math.Max(0, {expr})";
        if (v.Max != int.MaxValue) expr = $"Math.Min({v.Max}, {expr})";
        return expr;
    }
}
