namespace Sts2CharForge.Core.Generation;

/// <summary>
/// 「触发链递归保护」（V0.2.342）：状态之间互相触发成环时，别把那张牌卡在出牌位。
///
/// <para><b>为什么需要</b>：本体 <c>CardModel.Play</c> 是「先等 <c>OnPlay</c> 返回，再把这牌放进结果堆」
/// （<c>await CardPileCmd.Add(this, resultLocation.pileType, …)</c>）。如果 A 给 B 叠层数、B 又给 A 叠层数
/// （或者「给某个状态 → 造成伤害 → 造成伤害时又给那个状态」）这种环存在，那条 await 链永远不结束 ——
/// 玩家看到的现象就是**打出的牌停在出牌位浮空、回合也卡住**（用户报「破解浮在空中」就是这个形态：
/// 破解一次给所有敌人上「骇入」，把每个敌人身上的「给予骇入时」状态各触发一遍，其中有的会再给骇入）。</para>
///
/// <para><b>做法</b>：只给本体的 <c>Hook.AfterPowerAmountChanged</c> 打一个 Harmony 前缀，
/// 用一个线程静态的嵌套深度计数器兜底 —— 超过 <see cref="Limit"/> 层就跳过这一次派发并写一行日志。
/// 所有「状态层数变了」的连锁都从那一处走，所以只加这一个闸门就够，生成出来的业务代码一个字都不用动。</para>
///
/// <para><b>为什么是 12 层</b>：正常配置的嵌套深度是 2~4 层（打出一张牌 → 施加状态 → 状态的触发里再给另一个状态），
/// 12 层足够宽；而环一旦形成，每一轮都会 +1，于是最多多跑 12 轮就停。</para>
/// </summary>
public static class RecursionGuardGen
{
    /// <summary>生成到工程里的文件名（<c>cs/…</c>）。</summary>
    public const string FileName = "ForgeRecursionGuard.cs";

    /// <summary>补丁类名（日志里会看到它）。</summary>
    public const string ClassName = "ForgeRecursionGuardPatch";

    /// <summary>嵌套深度上限。</summary>
    public const int Limit = 12;

    /// <summary>
    /// 要不要生成这份补丁：只有存在**启用的自定义状态**时才可能需要它
    /// （环只可能形成在「状态 ↔ 状态」之间；没有自定义状态时本体的钩子链不可能被我们的配置打环）。
    /// </summary>
    public static bool Needed(Profile.CharacterProfile p) =>
        p is not null && p.CustomPowers.Any(x => x is not null && x.Enabled);

    /// <summary>补丁源码。</summary>
    public static string Source(Profile.CharacterProfile p)
    {
        string ns = Naming.From(p).Namespace;
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// <auto-generated> 由 Sts2CharForge 生成：触发链递归保护（状态互相触发成环时不把牌卡在出牌位）</auto-generated>");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// 「状态层数变化」这条钩子的**嵌套深度闸门**。");
        sb.AppendLine("///");
        sb.AppendLine("/// <para>为什么要有它：A 给 B 叠层数、B 又给 A 叠层数（或「给状态 → 造成伤害 → 造成伤害时又给状态」）这种环，");
        sb.AppendLine("/// 每次都要 await 一整条钩子链 —— 打出那张牌的 OnPlay 就永远返回不了；本体要等 OnPlay 返回");
        sb.AppendLine("/// 才把牌放进结果堆，于是**牌停在出牌位浮空、回合卡住**。");
        sb.AppendLine("/// 这里只做一件事：嵌套超过上限就跳过这一次派发 + 写一行日志，让链自然断掉。</para>");
        sb.AppendLine("///");
        sb.AppendLine("/// <para>看到日志「触发链已经嵌套 N 层」时，请去检查那几个「每当…时」的状态：");
        sb.AppendLine("/// 是不是 A 给 B、B 又给 A（或者自己给自己）。去掉一边 / 给一边加条件即可，闸门只是兜底。</para>");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("[HarmonyLib.HarmonyPatch(typeof(MegaCrit.Sts2.Core.Hooks.Hook), nameof(MegaCrit.Sts2.Core.Hooks.Hook.AfterPowerAmountChanged))]");
        sb.AppendLine($"internal static class {ClassName}");
        sb.AppendLine("{");
        sb.AppendLine($"    private const int Limit = {Limit};");
        sb.AppendLine();
        sb.AppendLine("    // 每次派发嵌套一层；用线程静态是因为战斗结算全在主线程，但多线程读档时也不会串味");
        sb.AppendLine("    [System.ThreadStatic] private static int _depth;");
        sb.AppendLine();
        sb.AppendLine("    private static bool Prefix()");
        sb.AppendLine("    {");
        sb.AppendLine("        if (_depth >= Limit)");
        sb.AppendLine("        {");
        sb.AppendLine("            MegaCrit.Sts2.Core.Logging.Log.Warn(\"[ForgeRecursionGuard] 状态层数变化的连锁已经嵌套 \" + _depth");
        sb.AppendLine("                + \" 层，跳过这一次派发（多半是几个状态在互相触发：检查那些「每当…时」的状态，去掉一边或加条件）\");");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("        _depth++;");
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static void Postfix(ref System.Threading.Tasks.Task __result)");
        sb.AppendLine("    {");
        sb.AppendLine("        // 被前缀跳过的那一次：深度没加，这里也别减（__result 是 null）");
        sb.AppendLine("        if (__result is null) return;");
        sb.AppendLine("        __result = AwaitAndRelease(__result);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static async System.Threading.Tasks.Task AwaitAndRelease(System.Threading.Tasks.Task task)");
        sb.AppendLine("    {");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            await task;");
        sb.AppendLine("        }");
        sb.AppendLine("        finally");
        sb.AppendLine("        {");
        sb.AppendLine("            _depth = System.Math.Max(0, _depth - 1);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
