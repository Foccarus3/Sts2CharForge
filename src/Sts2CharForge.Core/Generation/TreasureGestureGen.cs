using System.Text;
using Sts2CharForge.Core.Profile;

namespace Sts2CharForge.Core.Generation;

/// <summary>
/// 多人联机宝箱房的两处自定义（「美术资源」页最下面那几项）：
///   ① **拿取**手势 —— 本体没有这张图，是我们加的；
///   ② **催促文本**（本体那句「开抢！！！」）。
///
/// 两处都只生成**一个 Postfix 补丁**，而且只在「这一局玩的是我方角色」时生效 ——
/// 本体的本地化键一个字都不动（改了的话，别的角色、百科、联机另一边的玩家会跟着一起变），
/// 联机时每个人看到的是**他自己角色模组**带的东西。
///
/// 为什么必须打补丁（对着本体源码确认过，路径见下）：
///   · 手势：<c>CharacterModel.ArmPointingTexture / ArmRockTexture / ArmPaperTexture / ArmScissorsTexture</c>
///     全是**非虚**属性，路径写死成 <c>res://images/ui/hands/multiplayer_hand_&lt;角色ID小写&gt;_&lt;手势&gt;.png</c>。
///     那四个手势我们是**换文件**（见 <see cref="ArtGenerator"/> 的 AssetMap），
///     但第五个「拿取」本体压根没有：<c>NHandImage.GrabRelic</c> 是
///     「布（伸手够过去）→ 石头（拳头攥住）」两步糊出来的
///     （私有方法 <c>NHandImage.SetTextureToFightMove</c>）。
///     所以这里给那个私有方法打 Postfix：只在私有状态 <c>_state == GrabbingRelic</c>
///     而且正要显示「石头」时，换成我们那张 <c>..._grab.png</c>。
///   · 催促文本：<c>NTreasureRoomRelicCollection._Ready</c> 里直接
///     <c>_fightLabel.Text = new LocString("gameplay_ui", "TREASURE_FIGHT_TEXT").GetFormattedText()</c>。
///     那个键是**全局**的，覆盖它 = 别的角色 / 联机另一边全跟着变，
///     所以改成在 Postfix 里只换「我方角色这一局」的这一行字。
/// </summary>
public static class TreasureGestureGen
{
    /// <summary>填了「拿取」那张图才生成手势补丁（不填 = 保持本体「布→石头」）。</summary>
    public static bool NeedsGrab(CharacterProfile p) => !string.IsNullOrWhiteSpace(p.Art.GestureGrab);

    /// <summary>填了催促文本才生成文本补丁（不填 = 沿用本体那句「开抢！！！」）。</summary>
    public static bool NeedsFightText(CharacterProfile p) =>
        !string.IsNullOrWhiteSpace((p.Art.TreasureFightText ?? "").Trim());

    public static bool HasAny(CharacterProfile p) => NeedsGrab(p) || NeedsFightText(p);

    /// <summary>cs/TreasureGesture.cs 的内容。</summary>
    public static string Source(CharacterProfile p)
    {
        var n = Naming.From(p);
        bool grab = NeedsGrab(p);
        bool text = NeedsFightText(p);
        string grabRes = ArtGenerator.GrabTextureResPath(p) ?? "";
        string fightText = (p.Art.TreasureFightText ?? "").Trim();
        string constClass = n.CharClass + "TreasureGestureConst";

        var sb = new StringBuilder();
        sb.Append("// <auto-generated> 多人联机宝箱房：自定义「拿取」手势 + 自定义催促文本 </auto-generated>\n");
        sb.Append("// 只在「这一局玩的是我方角色」时生效；本体的本地化键和别的角色一点都不动。\n");
        // 回读标记：催促文本里可能有引号 / 换行，从 C# 字面量反推容易出错 ——
        // 所以单独写一行注释标记（换行转义成 \n，见 CSharpCodeGen.EscapeMarker）。
        sb.Append($"// CET:TreasureGrab={(grab ? grabRes : "")} CET:TreasureFightText={CSharpCodeGen.EscapeMarker(fightText)}\n");
        sb.Append("using HarmonyLib;\n");
        sb.Append("using MegaCrit.Sts2.Core.Context;\n");
        if (grab) sb.Append("using MegaCrit.Sts2.Core.Entities.TreasureRelicPicking;\n");
        sb.Append("using MegaCrit.Sts2.Core.Nodes.Screens.TreasureRoomRelic;\n");
        if (text) sb.Append("using MegaCrit.Sts2.addons.mega_text;\n");
        sb.Append('\n');
        sb.Append($"namespace {n.Namespace};\n");

        sb.Append($$"""

/// <summary>宝箱房两处自定义的配置（由「美术资源」页填的东西生成；空串 = 那项没配）。</summary>
internal static class {{constClass}}
{
    /// <summary>「拿取」那张图的 res:// 路径；空串 = 没配（不换，保持本体「布→石头」）。</summary>
    internal const string GrabTexturePath = {{Lit.Str(grabRes)}};

    /// <summary>宝箱房那句催促文本要换成的话；空串 = 沿用本体的「开抢！！！」。</summary>
    internal const string FightText = {{Lit.Str(fightText)}};
}

""");

        if (grab)
        {
            sb.Append($$"""

/// <summary>
/// 宝箱房「拿取」手势：把「攥住遗物」那一下的手换成你上传的那张图。
///
/// 为什么打在这个私有方法上（<c>NHandImage.SetTextureToFightMove</c>）：
///   本体拿遗物的流程是 <c>GrabRelic</c> → 先把状态设成 GrabbingRelic → 亮「布」（伸手）
///   → 走完位移 tween → 再亮「石头」（攥住）→ 把遗物挂到手上。
///   所以「拿取」= 状态是 GrabbingRelic 时的那次「石头」。石头剪刀布亮牌、放弃时亮拳头
///   状态都不是 GrabbingRelic，保持本体表现（只换拿取那一下）。
/// </summary>
[HarmonyPatch(typeof(NHandImage), "SetTextureToFightMove")]
public static class {{n.CharClass}}TreasureGrabPatch
{
    private static Texture2D? _grab;
    private static bool _tried;

    [HarmonyPostfix]
    private static void AfterSetTexture(NHandImage __instance, RelicPickingFightMove move)
    {
        try
        {
            if (move != RelicPickingFightMove.Rock) return;                 // 只换「攥住」那一下
            if (__instance is null || __instance.Player is null) return;
            if (!LocalContext.IsMe(__instance.Player)) return;             // 对面那只手不归我管（他自己的模组说了算）
            if (!IsGrabbingRelic(__instance)) return;                       // 亮牌 / 放弃时出拳头：保持本体表现
            Texture2D? texture = LoadGrabTexture();
            if (texture is null) return;
            TextureRect? rect = __instance.GetNodeOrNull<TextureRect>("TextureRect");
            if (rect is not null) rect.Texture = texture;
        }
        catch (Exception e)
        {
            // 界面补丁出问题绝不能把联机宝箱房搞崩：只记日志，保持本体那只手
            Log.Error("宝箱房「拿取」手势：替换失败（已忽略）：" + e.Message);
        }
    }

    /// <summary>
    /// 本体此刻是不是在「拿取遗物」。
    /// 状态是私有字段（<c>private enum State { None, Frozen, GrabbingRelic }</c>），只能反射读它 ——
    /// 读不到（本体改了字段名 / 枚举名）= 当作「不是」→ 保持本体表现，
    /// 绝不会把石头剪刀布的拳头一起换掉。
    /// </summary>
    private static bool IsGrabbingRelic(NHandImage hand)
    {
        object? state = AccessTools.Field(typeof(NHandImage), "_state")?.GetValue(hand);
        return state is not null && state.ToString() == "GrabbingRelic";
    }

    /// <summary>加载「拿取」那张图（只试一次；加载不出来就一直用本体那只手）。</summary>
    private static Texture2D? LoadGrabTexture()
    {
        if (_tried) return _grab;
        _tried = true;
        if ({{constClass}}.GrabTexturePath.Length == 0) return null;
        try
        {
            // 不用 ResourceLoader.Exists 做前置判断：模组 pck 是运行时挂载的，
            // Exists 对刚挂载的资源可能返回 false —— 那样图会「静默不生效」，日志里一条错都没有。
            _grab = GD.Load<Texture2D>({{constClass}}.GrabTexturePath);
        }
        catch (Exception e)
        {
            Log.Error("宝箱房「拿取」手势：图片加载失败（已忽略）：" + e.Message);
        }
        if (_grab is null)
            Log.Warn("宝箱房「拿取」手势：图片没加载出来，拿取时仍然用本体的拳头：" + {{constClass}}.GrabTexturePath);
        return _grab;
    }
}

""");
        }

        if (text)
        {
            sb.Append($$"""

/// <summary>
/// 宝箱房那句催促文本（本体是「开抢！！！」）：只在我方角色的这一局里换成你填的那句。
///
/// 为什么不直接覆盖本地化键 <c>gameplay_ui.TREASURE_FIGHT_TEXT</c>：
/// 本地化表是**全局**的，一覆盖，别的角色、百科、联机另一边的玩家看到的都会变成你这句话。
/// 这里改成给 <c>NTreasureRoomRelicCollection._Ready</c> 打 Postfix
/// （本体就是在这个方法里把 <c>%FightLabel</c> set 成本体那句的），只换这一局的这一行字。
/// </summary>
[HarmonyPatch(typeof(NTreasureRoomRelicCollection), nameof(NTreasureRoomRelicCollection._Ready))]
public static class {{n.CharClass}}TreasureFightTextPatch
{
    [HarmonyPostfix]
    private static void AfterReady(NTreasureRoomRelicCollection __instance)
    {
        try
        {
            if (!IsMyRun()) return;                                  // 别的角色 / 主菜单：一个字都不动
            MegaLabel? label = __instance.GetNodeOrNull<MegaLabel>("%FightLabel");
            if (label is null)
            {
                Log.Warn("宝箱房催促文本：没找到 %FightLabel 节点，这行字保持本体那句");
                return;
            }
            label.Text = {{constClass}}.FightText;
        }
        catch (Exception e)
        {
            Log.Error("宝箱房催促文本：替换失败（已忽略）：" + e.Message);
        }
    }

    private static ulong _cachedFrame = ulong.MaxValue;
    private static bool _cached;

    /// <summary>
    /// 这一局玩的是不是我方角色。用本体自己的公开链（和生成的本体状态改名补丁同一套）：
    /// <c>RunManager.Instance.IsInProgress</c> → <c>DebugOnlyGetState()</c> →
    /// <c>LocalContext.GetMe(runState)?.Character</c>。主菜单 / 别的角色时给 null → 一律不动本体那句。
    /// 按帧缓存，宝箱房反复刷界面时不用每次重算。
    /// </summary>
    private static bool IsMyRun()
    {
        try
        {
            ulong frame = Engine.GetProcessFrames();
            if (frame == _cachedFrame) return _cached;
            _cachedFrame = frame;
            _cached = ComputeIsMyRun();
            return _cached;
        }
        catch { return false; }
    }

    private static bool ComputeIsMyRun()
    {
        if (!MegaCrit.Sts2.Core.Runs.RunManager.Instance.IsInProgress) return false;
        Player? me = LocalContext.GetMe(MegaCrit.Sts2.Core.Runs.RunManager.Instance.DebugOnlyGetState());
        return me?.Character is {{n.CharClass}};
    }
}

""");
        }

        return sb.ToString();
    }
}
