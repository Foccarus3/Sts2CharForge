    // ==================== 状态悬停提示（ExtraHoverTips） ====================
    //
    // 本体里「卡面 / 遗物 / 药水描述里提到某个状态」时，鼠标移上去能弹出那个状态的说明 ——
    // 靠的是模型自己声明 ExtraHoverTips（例：本体的 Abrasive 写
    // protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<DexterityPower>()]）。
    //
    // 我们生成的卡牌/遗物/药水以前没有这一段，于是：
    //   · 本体状态被改写后（改了名字和描述），悬停看不到任何说明 → 用户报了这一点；
    //   · 自定义状态（能力牌用）提到时也没有说明 → 遗物/药水同理。
    // 现在按「这条效果施加的状态 + 条件里盯的状态」自动生成这一段（下回合生效的走延迟状态类）。
    // 文本取自本体的 powers 本地化表：本体状态改写后我们覆盖了同名的键，所以弹出来的就是新名字 + 新描述。

    /// <summary>把这条效果用到的状态写成 HoverTipFactory.FromPower&lt;X&gt;(N) 调用（没有就返回空）。</summary>
    internal static List<string> HoverTipsOf(IEnumerable<EffectSpec> effects, bool isCard = false,
        CharacterProfile? owner = null)
    {
        var list = new List<string>();
        var all = effects as IList<EffectSpec> ?? effects.ToList();
        foreach (var e in all)
        {
            if (e.Kind == "ApplyPower" && !string.IsNullOrWhiteSpace(e.PowerId))
            {
                string type = e.NextTurn ? DelayedPowerClassName(e, owner) : e.PowerId!.Trim();
                // 「数值 = 层数 / X」时数量说不准，就不写数量（本体自己也有不写数量的写法）
                string amount = (e.AmountIsX || e.AmountIsStack || e.Amount <= 0)
                    ? ""
                    : ((int)e.Amount).ToString(System.Globalization.CultureInfo.InvariantCulture);
                list.Add($"MegaCrit.Sts2.Core.HoverTips.HoverTipFactory.FromPower<{type}>({amount})");
            }
            // 条件里盯的状态：「拥有破绽至少 N 层」鼠标移上去也该有说明
            if (e.Condition is not null && !e.Condition.IsNone
                && e.Condition.Kind == "HasPowerAtLeast" && !string.IsNullOrWhiteSpace(e.Condition.PowerId))
                list.Add($"MegaCrit.Sts2.Core.HoverTips.HoverTipFactory.FromPower<{e.Condition.PowerId!.Trim()}>()");
        }

        // 额外资源量（本体的「星星」计数器）：本体没有专门给卡牌用的静态提示，
        // 这里直接用计数器自己那两条文本（static_hover_tips 的 STAR_COUNT.title/description）——
        // 用户改了显示名（如「戏法」）时我们覆盖了同名键，所以弹出来就是新名字 + 新描述。
        if (all.Any(e => e.Kind == "ExtraResource"))
            list.Add("new MegaCrit.Sts2.Core.HoverTips.HoverTip(new LocString(\"static_hover_tips\", \"STAR_COUNT.title\"), new LocString(\"static_hover_tips\", \"STAR_COUNT.description\"))");

        // 获得能量：本体卡就是这么提示的（base.EnergyHoverTip）
        if (isCard && all.Any(e => e.Kind == "Energy"))
            list.Add("base.EnergyHoverTip");

        // 「获得卡牌奖励」：本体有现成的静态提示（StaticHoverTip.CardReward）
        if (all.Any(e => e.Kind == "CardReward"))
            list.Add("MegaCrit.Sts2.Core.HoverTips.HoverTipFactory.Static(MegaCrit.Sts2.Core.HoverTips.StaticHoverTip.CardReward)");

        return list.Distinct(StringComparer.Ordinal).ToList();
    }

    /// <summary>生成 ExtraHoverTips 覆写（没用到状态就返回空字符串）。isPublic = 药水（基类是 public）。</summary>
    /// <param name="extraTips">
    /// 额外的提示表达式（目前用于自定义关键词）：排在状态提示**前面**，
    /// 因为卡面上关键词也是排在描述最前面的。
    /// </param>
    internal static string HoverTipsOverride(IEnumerable<EffectSpec> effects, bool isPublic, bool isCard = false,
        IEnumerable<string>? extraTips = null, CharacterProfile? owner = null)
    {
        var tips = new List<string>();
        if (extraTips is not null) tips.AddRange(extraTips);
        tips.AddRange(HoverTipsOf(effects, isCard, owner));
        tips = tips.Distinct(StringComparer.Ordinal).ToList();
        if (tips.Count == 0) return "";
        string access = isPublic ? "public override" : "protected override";
        var w = new CodeWriter();
        w.Line();
        w.Line("    // 鼠标悬停描述里的状态时弹出的说明（文本来自本体 powers / static_hover_tips 表；本体状态被改写后就是新名字 + 新描述）");
        w.Line($"    {access} IEnumerable<MegaCrit.Sts2.Core.HoverTips.IHoverTip> ExtraHoverTips =>");
        w.Line("    [");
        for (int i = 0; i < tips.Count; i++)
            w.Line($"        {tips[i]}{(i == tips.Count - 1 ? "" : ",")}");
        w.Line("    ];");
        return w.ToString();
    }

    //
    // ==================== 本体「缓慢」：直接设百分比 ====================
    //
    // 用户报过：「施加 30 层缓慢」在游戏里只看到「缓慢」、吃不到 30 层的加成。
    // 原因在本体 SlowPower：
    //   · DisplayAmount => DynamicVars["SlowAmount"].IntValue * 10  ← 状态栏显示的是它
    //   · ModifyDamageMultiplicative => 1 + 0.1 * SlowAmount        ← 实际加伤用的也是它
    //   · AfterCardPlayed => SlowAmount++（每打出一张牌 +10%）、敌人回合开始清零
    // 也就是说「缓慢」的层数（Amount）跟它的效果完全无关，本体自己施加时也只给 1 层。
    // 所以想让敌人「当场受到伤害 +30%」，只能把 SlowAmount 直接写成 3（= 30%）。
    // 生成的是 SlowPowerHelper.SetPercent(目标, 30)，那个助手文件只在用到时才生成。

    /// <summary>这条效果是不是「直接把缓慢设成 N%」。</summary>
    internal static bool IsSlowPercentEffect(EffectSpec e) => e.SlowPercentEffective > 0 && e.IsSlowPower;

    /// <summary>这个存档里所有「直接把缓慢设成 N%」的效果（用于统计/生成助手文件）。</summary>
    internal static IEnumerable<EffectSpec> SlowPercentEffects(CharacterProfile p) =>
        p.Cards.SelectMany(c => c.Effects)
            .Concat(p.Relics.SelectMany(r => r.Effects))
            .Concat(p.Potions.SelectMany(x => x.Effects))
            .Concat(p.CustomPowers.SelectMany(cp => cp.Triggers).SelectMany(t => t.Effects))
            .Where(IsSlowPercentEffect);

    /// <summary>需要生成「缓慢」数值助手文件吗。</summary>
    public static bool NeedsSlowPowerHelper(CharacterProfile p) => SlowPercentEffects(p).Any();

    /// <summary>施加完「缓慢」之后，把它的内部数值直接写成 N%（creatureExpr = 目标生物）。</summary>
    internal static void EmitSlowPercentFix(CodeWriter w, EffectSpec e, string creatureExpr)
    {
        if (!IsSlowPercentEffect(e)) return;
        w.Line($"SlowPowerHelper.SetPercent({creatureExpr}, {e.SlowPercentEffective});   // 本体「缓慢」：直接设成 {e.SlowPercentEffective}%（它显示/生效的是每打出一张牌 +10%，跟层数无关）");
    }

    /// <summary>同上，但目标是一群敌人（遗物/药水那条「一次性对全体施加」的写法）。</summary>
    internal static void EmitSlowPercentFixForAll(CodeWriter w, EffectSpec e)
    {
        if (!IsSlowPercentEffect(e)) return;
        w.Open("foreach (Creature __slowFoe in base.Owner.Creature.CombatState.HittableEnemies)");
        w.Line($"SlowPowerHelper.SetPercent(__slowFoe, {e.SlowPercentEffective});   // 本体「缓慢」：直接设成 {e.SlowPercentEffective}%");
        w.Close();
    }

    /// <summary>生成 cs/SlowPowerHelper.cs。</summary>
    public static string SlowPowerHelperSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        return $$"""
        // <auto-generated> 本体「缓慢」的数值助手 </auto-generated>
        namespace {{n.Namespace}};

        /// <summary>
        /// 本体「缓慢」（SlowPower）和别人不一样：状态栏显示的数字、以及实际用来加伤的数字**都不是层数**，
        /// 而是它内部的 DynamicVar「SlowAmount」×10：
        ///   · DisplayAmount => DynamicVars["SlowAmount"].IntValue * 10（状态栏显示的就是它）
        ///   · ModifyDamageMultiplicative => 1 + 0.1 * SlowAmount（每 1 点 = 受到伤害 +10%）
        ///   · AfterCardPlayed => SlowAmount++（本回合每打出一张牌 +10%），敌人回合开始时清零
        /// 所以「施加 30 层缓慢」既看不到 30、也吃不到加成（本体自己施加时也只给 1 层）。
        /// 想让敌人当场「受到伤害 +30%」，就得把 SlowAmount 直接写成 3 —— 那就是这里做的事。
        /// </summary>
        internal static class SlowPowerHelper
        {
            /// <summary>PowerModel.InvokeDisplayAmountChanged 是 protected，只能反射调；调一下状态栏才会立刻刷新。</summary>
            private static readonly System.Reflection.MethodInfo? _refresh =
                HarmonyLib.AccessTools.Method(typeof(PowerModel), "InvokeDisplayAmountChanged");

            /// <summary>
            /// 把目标身上「缓慢」的数值设成 percent%（按 10% 一档，四舍五入）。
            /// 调用前请先施加 SlowPower；身上没有「缓慢」时什么都不做。
            /// </summary>
            internal static void SetPercent(Creature creature, int percent)
            {
                try
                {
                    if (creature is null) return;
                    PowerModel? power = creature.Powers.FirstOrDefault(x => x is SlowPower);
                    if (power is null) return;

                    decimal units = System.Math.Round(System.Math.Max(0, percent) / 10m, System.MidpointRounding.AwayFromZero);
                    power.DynamicVars["SlowAmount"].BaseValue = units;
                    // 悬停提示里的「受到伤害增加 X%」读的是 DisplayAmount 这个变量（AfterCardPlayed 里也是这么同步的）
                    power.DynamicVars["DisplayAmount"].BaseValue = units * 10m;
                    try { _refresh?.Invoke(power, null); } catch { }
                }
                catch (System.Exception ex) { Log.Error("缓慢：设置百分比失败（已忽略）：" + ex.Message); }
            }
        }
        """;
    }

