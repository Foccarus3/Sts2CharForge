    /// <summary>
    /// 获得卡牌奖励。
    ///
    /// 有 CombatRoom 的时候（状态 / 遗物的「战斗胜利后」）走本体那条路：
    /// <c>room.AddExtraReward(player, new CardReward(CardCreationOptions.ForRoom(player, room.RoomType), N, player))</c>
    /// —— 这就是本体「王国资产」（RoyaltiesPower.AfterCombatEnd 发金币）和「猎杀」（TheHunt）的写法：
    /// 奖励挂进本场战斗的结算界面（多一条「选一张卡」），这里不弹选牌界面，也就不依赖 choiceContext。
    /// （实测在战斗结束的钩子里当场弹选牌界面是不行的：日志里连「已加入牌组」都没有，效果等于没跑。）
    ///
    /// 没有 CombatRoom 的时候（战斗中打出的牌）保持原来的做法：当场抽 N 张让玩家选一张加进牌组。
    /// </summary>
    private static void EmitCardReward(CodeWriter w, EffectSpec e, string owner, bool useX = false, string? roomVar = null)
    {
        string n = useX && e.AmountIsX ? XVar : Math.Max(1, (int)e.Amount).ToString();

        // 独立作用域：同一个地方配了两条「获得卡牌奖励」时，里面的局部变量不会重名（重名直接编译不过）
        w.Open("");

        if (roomVar is not null)
        {
            w.Line("// 卡牌奖励：挂进本场战斗的结算奖励里（本体「王国资产」「猎杀」就是这么加的），打赢后多一条「选一张卡」的奖励");
            w.Line("// 注意：选项里不能带 CardCreationFlags（比如 ForNonCombatWithDefaultOdds 会带 NoUpgradeRoll）——");
            w.Line("// 战斗结束存档时 CardReward.ToSerializable 会因此抛 NotImplementedException。ForRoom 不带 flag，是安全的。");
            w.Line($"MegaCrit.Sts2.Core.Runs.CardCreationOptions __rewardOptions = {roomVar}.RoomType == MegaCrit.Sts2.Core.Rooms.RoomType.Event");
            w.Line("    // 事件房本体 ForRoom 会直接抛异常，这里手造一份同样不带 flag 的");
            w.Line($"    ? new MegaCrit.Sts2.Core.Runs.CardCreationOptions(new CardPoolModel[] {{ {owner}.Character.CardPool }}, MegaCrit.Sts2.Core.Runs.CardCreationSource.Other, MegaCrit.Sts2.Core.Runs.CardRarityOddsType.RegularEncounter)");
            w.Line($"    : MegaCrit.Sts2.Core.Runs.CardCreationOptions.ForRoom({owner}, {roomVar}.RoomType);");
            w.Line($"{roomVar}.AddExtraReward({owner}, new MegaCrit.Sts2.Core.Rewards.CardReward(__rewardOptions, {n}, {owner}));");
            w.Line($"Log.Info({Lit.Str("战斗奖励里已加入卡牌奖励（N 选一）：")} + {n});");
            w.Close();
            return;
        }

        w.Line("// 获得卡牌奖励：按本体的奖励卡生成规则抽牌（用你自己角色的卡池），让玩家选一张加进牌组");
        w.Line($"var __rewardOptions = MegaCrit.Sts2.Core.Runs.CardCreationOptions.ForNonCombatWithDefaultOdds(new CardPoolModel[] {{ {owner}.Character.CardPool }});");
        w.Line($"List<CardModel> __rewardCards = MegaCrit.Sts2.Core.Factories.CardFactory.CreateForReward({owner}, {n}, __rewardOptions).Select(r => r.Card).ToList();");
        w.Line($"CardModel? __pickedReward = await CardSelectCmd.FromChooseACardScreen(choiceContext, __rewardCards, {owner}, canSkip: true);");
        w.Line("CardModel __granted = __pickedReward ?? __rewardCards.FirstOrDefault();");
        w.Line("if (__granted is not null) { await CardPileCmd.Add(__granted, PileType.Deck); Log.Info(" + Lit.Str("卡牌奖励已加入牌组：") + " + __granted.Id.Entry); }");
        w.Close();
    }

    /// <summary>
    /// 条件在界面上/卡面描述里的说明（生成注释与本地化都用它）。
    /// resourceName：额外资源量在游戏里的名字（用户自己填的，如「冰附魔」）——传了就把条件里的
    /// 「额外资源量」换成它，否则卡面上会出现「拥有额外资源量至少 4 点」和计数器上的「冰附魔」两个名字。
    /// </summary>
    public static string ConditionText(ConditionSpec c, string? resourceName = null)
    {
        var opt = EffectCatalog.FindCondition(c.Kind);
        if (opt is null || c.IsNone) return "";
        string text = opt.Display;
        if (opt.NeedsAmount) text = text.Replace("N", c.Amount.ToString("0.##", System.Globalization.CultureInfo.InvariantCulture));
        if (opt.NeedsPower) text = text.Replace("某状态", EffectCatalog.PowerName(c.PowerId, "某状态"));
        if (opt.NeedsTarget && !string.Equals(c.Target, "Self", StringComparison.OrdinalIgnoreCase))
            text += $"（{c.TargetZh}）";
        // 条件里说的「额外资源量」= 界面上那个自定义计数器（用户可能给它起了别的名字）
        if (!string.IsNullOrWhiteSpace(resourceName) && resourceName.Trim() != "额外资源量")
            text = text.Replace("额外资源量", resourceName.Trim());
        return text;
    }

    // ==================== 三个池 ====================
    public static string CardPoolSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        var w = new CodeWriter();
        string frame = p.Colors.CardFrameColor is { Length: > 0 } cfc && Profile.CardColorSpec.NormalizeHex(cfc).Length > 0
            ? $"{n.CharSlug}_frame"                                   // 自定义颜色 → 用生成的 hsv 材质
            : (p.Colors.CardFrame is { Length: > 0 } f ? f : "card_frame_red");
        string deckHex = Hex(p.Colors.DeckEntryColor, "D62000");
        string outlineHex = Hex(p.Colors.EnergyOutlineColor, "802020");
        w.Line("// <auto-generated> 卡池 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public sealed class {n.CardPoolClass} : CardPoolModel")
         .Line($"public override string Title => {Lit.Str(n.PoolTitle)};")
         .Line()
         .Line($"public override string EnergyColorName => {Lit.Str(n.EnergyColor)};")
         .Line()
         .Line($"public override string CardFrameMaterialPath => {Lit.Str(frame)};")
         .Line()
         .Line($"public override Color DeckEntryCardColor => new Color({Lit.Str(deckHex)});")
         .Line()
         .Line($"public override Color EnergyOutlineColor => new Color({Lit.Str(outlineHex)});")
         .Line()
         .Line("public override bool IsColorless => false;")
         .Line()
         .Open("protected override CardModel[] GenerateAllCards()")
         .Line("return")
         .Line("[");
        // 注意：卡池 = 「这张卡属于哪个角色」，必须包含全部自有卡（含起始卡组里的）。
        // 否则本体 CardModel.Pool 会抛 InvalidProgramException: Card XXX is not in any card pool!
        // 「是否加入奖励/商店」由下面的 FilterThroughEpochs 过滤，不要在这里过滤。
        // 本体卡引用（打击 / 防御）不进这里：它们本来就属于本体的卡池，卡池里也不能掺本体的卡。
        for (int i = 0; i < p.Cards.Count; i++)
        {
            if (p.Cards[i].IsVanillaCard) continue;
            w.Line($"    ModelDb.Card<{n.CardClassName(p, p.Cards[i])}>(),");
        }
        // 卡池里**绝不掺本体（铁甲战士）的卡**：奖励只出这个角色自己的卡。
        // 本体的硬性要求只有一条：CardFactory.CreateForReward 会「互不重复地抽 N 张」（普通战斗三选一 N=3），
        // 池子不够就会抛 InvalidOperationException → 奖励界面不弹 → 死档。
        // 所以这里不兜底，改成生成前的校验直接拦住（少于 3 张奖励可用的卡就不让生成，见 ProfileValidator）。
        w.Line("];").Close()
         .Line()
         .Line("// 没勾「加入卡池」的卡：仍然属于本角色，但不会出现在奖励/商店里")
         .Open("protected override IEnumerable<CardModel> FilterThroughEpochs(UnlockState unlockState, IEnumerable<CardModel> cards)")
         .Line("var keep = cards.ToList();");
        var excluded = new List<string>();
        for (int i = 0; i < p.Cards.Count; i++)
            if (!p.Cards[i].IsVanillaCard && !p.Cards[i].InCardPool) excluded.Add($"ModelDb.Card<{n.CardClassName(p, p.Cards[i])}>()");
        if (excluded.Count > 0)
        {
            w.Line($"keep.RemoveAll(c => c.Id == {excluded[0]}.Id");
            for (int i = 1; i < excluded.Count; i++)
                w.Line($"    || c.Id == {excluded[i]}.Id");
            w.Line(");");
        }
        w.Line("return keep;").Close()
         .Close();
