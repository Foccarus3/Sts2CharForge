    /// <summary>
    /// 牺牲伙伴：**先算收益、再杀宠物**（顺序绝不能反 —— 宠物死了就取不到它的生命值，
    /// 而且 CalculatedBlock/CalculatedDamage 是在宠物身上算的）。
    /// 收益是格挡：<c>CreatureCmd.GainBlock(主人, 收益, …)</c>；
    /// 收益是伤害：先把收益算成数字存下来，再 <c>CreatureCmd.Kill</c>，最后用 <c>DamageCmd.Attack(数字)</c> 打出去。
    /// </summary>
    private static void EmitPetSacrifice(CodeWriter w, EffectSpec e, CharacterProfile p, string petVar,
        Dictionary<EffectSpec, string>? varMap, bool useX, PetGen.PetDef? petDef = null)
    {
        var def = petDef ?? PetGen.Resolve(p, e.PetSummon);
        if (def is null)
        {
            w.Line($"// ⚠ 这条「牺牲伙伴」没有可用的召唤物{PetMissingHint(e.PetSummon)}"
                + "：到「召唤物」页添加一只并勾上「启用」");
            return;
        }

        bool block = e.PetSacrificeGain != "Damage";
        string what = block ? "格挡" : "伤害";
        string valZh = e.PetSacrificeFormula switch
        {
            "Fixed" => $"固定 {e.Amount:0.##} 点",
            "CurHp" => $"等于{def.DisplayName}的当前生命值",
            _ => $"等于{def.DisplayName}的最大生命 × {e.PetSacrificeMultiplier:0.##}",
        };
        // 「全部召唤物」展开出来的那一份：按生命值算的收益没有计算变量可用（一张牌只有一套固定名字的
        // 计算变量），改成**内联**读这只宠物自己的生命值；固定值那份仍然读共用的 Block/Damage 变量。
        bool inline = IsAllPetsInlineCalc(e);
        w.Line($"// 牺牲{def.DisplayName}换{what}：收益 {valZh}（先算收益、再杀宠物 —— 顺序反了就取不到生命值）"
            + (inline ? "【全部召唤物：每只各自算，卡面不显示具体数字】" : ""));

        // 收益是固定值时不需要计算变量（普通 BlockVar / DamageVar），直接读变量值即可。
        bool fixedFormula = e.PetSacrificeFormula == "Fixed";
        string gainExpr = fixedFormula
            ? "base.DynamicVars[" + Lit.Str(VarNameOf(e, varMap)) + "].BaseValue"
            : inline
                ? (e.PetSacrificeFormula == "CurHp"
                    ? $"(decimal){petVar}.CurrentHp"
                    : $"(decimal){petVar}.MaxHp * {Lit.Dec(e.PetSacrificeMultiplier)}")
                : (block
                    ? "base.DynamicVars.CalculatedBlock.Calculate(cardPlay.Target)"
                    : "base.DynamicVars.CalculatedDamage.Calculate(cardPlay.Target)");

        if (block)
        {
            w.Line($"decimal gain = {gainExpr};");
            w.Line($"await CreatureCmd.Kill({petVar});");
            w.Line("await CreatureCmd.GainBlock(base.Owner.Creature, gain, "
                + ((fixedFormula || inline) ? "ValueProp.Move" : "base.DynamicVars.CalculatedBlock.Props") + ", cardPlay);");
        }
        else
        {
            w.Line($"decimal dmg = {gainExpr};");
            w.Line($"await CreatureCmd.Kill({petVar});");
            w.Line("await DamageCmd.Attack(dmg)")
             .Indent().Line(".FromCard(this, cardPlay)")
             .Line(".Targeting(cardPlay.Target)")
             .Line(".WithHitFx(\"vfx/vfx_attack_blunt\", null, \"blunt_attack.mp3\")")
             .Line(".Execute(choiceContext);").Dedent();
        }
    }

    /// <summary>
    /// 给伙伴施加状态：<c>PowerCmd.Apply&lt;{PowerId}&gt;(choiceContext, pet, 层数, base.Owner.Creature, this)</c>。
    /// 下回合生效时走现有的「延迟状态」类（<c>ForgeDelayed&lt;PowerId&gt;</c>）挂在宠物身上，
    /// 那个类自己的钩子里会把真正的状态施加到**它的主人**（也就是这只宠物）上 —— 和普通「下回合生效」一致。
    /// </summary>
    private static void EmitPetApplyPower(CodeWriter w, CharacterProfile p, EffectSpec e, string petVar, string amt)
    {
        _ = amt;
        // 数值**不**用外面传来的表达式：PetApplyPower 的变量名是 PetPower<PowerId>（不是本体的属性），
        // 这里按名字取 —— 回读也照这一行把数值配回去（升级增量同样生效）。
        string calc = $"base.DynamicVars[{Lit.Str(VarNameOf(e))}].BaseValue";
        if (e.NextTurn)
        {
            w.Line($"await PowerCmd.Apply<{DelayedPowerClassName(e, p)}>(choiceContext, {petVar}, {calc}, base.Owner.Creature, this);");
            return;
        }
        w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, {petVar}, {calc}, base.Owner.Creature, this);");
    }

    /// <summary>
    /// 伙伴替主人承伤 开 / 关：用我们**自己的共用守卫类** <c>ForgePetGuardianPower</c>
    /// （不是本体的 DieForYouPower —— 那个是 Osty 专用；多只宠物共用这一个类、由它自己仲裁谁承担）。
    ///
    /// 这里不再判 <c>HasPower&lt;T&gt;()</c>：宠物已经判活（外面那层 <c>if (pet != null)</c>），
    /// 一只活着的宠物要么已经挂着守卫（PowerStackType.Single 重复 Apply 不会多一个实例），
    /// 要么没挂 —— 直接 Apply / Remove 都是对的，而且生成的代码短一半。
    /// 关的时候用 <c>PowerCmd.Remove&lt;T&gt;(Creature)</c>（本体签名，核实过：<c>PowerCmd.cs:282</c>）。
    /// </summary>
    private static void EmitPetGuard(CodeWriter w, CharacterProfile p, string petVar, bool on)
    {
        string power = Naming.From(p).GuardianPowerClass;
        if (on)
            w.Line($"await PowerCmd.Apply<{power}>(choiceContext, {petVar}, 1m, null, null);"
                + "   // 共用守卫：多只都挂时由它自己仲裁（列表里第一只活着的承担）");
        else
            w.Line($"await PowerCmd.Remove<{power}>({petVar});"
                + "   // 取消替主人承伤：多只都挂着时只摘这一只，剩下那只（若有）继续承担");
    }

    // ==================== 下回合生效的延迟 Power ====================
    internal static string DelayedPowerClassName(EffectSpec e, CharacterProfile? owner = null) =>
        owner is null ? Naming.AmbientDelayedPowerClass(e) : Naming.From(owner).DelayedPowerClass(e);

    public static IEnumerable<EffectSpec> CollectDelayedEffects(CharacterProfile p)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var e in p.Cards.SelectMany(c => c.Effects)
                     .Concat(p.Relics.SelectMany(r => r.Effects))
                     .Concat(p.Potions.SelectMany(s => s.Effects)))
        {
            if (e.Kind != "ApplyPower" || !e.NextTurn) continue;
            if (seen.Add(e.PowerId ?? "")) yield return e;
        }
    }

    public static string DelayedPowersSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 下回合生效用的延迟 Power </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line();

        foreach (var e in CollectDelayedEffects(p))
        {
            string power = e.PowerId ?? "WeakPower";
            string cls = n.DelayedPowerClass(e);
            bool toSelf = e.TargetSide == "Self";

            w.Line($"/// <summary>下回合开始时{(toSelf ? "给自己" : "给所有敌人")}施加 {power}。</summary>")
             .Open($"public sealed class {cls} : PowerModel")
             .Line("public override PowerType Type => PowerType.Buff;")
             .Line()
             .Line("public override PowerStackType StackType => PowerStackType.Counter;")
             .Line()
             .Open("public override async Task AfterPlayerTurnStart(PlayerChoiceContext choiceContext, Player player)")
             .Line("if (player != base.Owner.Player) return;")
             .Line();

            if (toSelf)
                w.Line($"await PowerCmd.Apply<{power}>(choiceContext, base.Owner, base.Amount, base.Owner, null);");
            else
                w.Open("foreach (Creature foe in base.Owner.CombatState.HittableEnemies)")
                 .Line($"await PowerCmd.Apply<{power}>(choiceContext, foe, base.Amount, base.Owner, null);")
                 .Close();

            w.Line()
             .Line("await PowerCmd.Remove(this);")
             .Close()
             .Close()
             .Line();
        }
        return w.ToString();
    }

    // ==================== 遗物 ====================
    public static string RelicSource(CharacterProfile p, RelicSpec r, int index)
    {
        var n = Naming.From(p);
        string cls = n.RelicClassName(r, index);
        var trigger = EffectCatalog.RelicTriggers.FirstOrDefault(t => t.Id == r.Trigger) ?? EffectCatalog.RelicTriggers[0];
        bool hasContext = HasContext(trigger.Id);
        // 「战斗胜利时」的钩子签名里带 CombatRoom：卡牌奖励走本体那套战斗奖励（AddExtraReward）
        string? roomVar = trigger.Id == "CombatVictory" ? "room" : null;

        string signature = trigger.Id switch
        {
            // 战斗开始时用 BeforeSideTurnStart（本体 BagOfMarbles 的做法：这个钩子带 choiceContext）
            "CombatStart" => "public override async Task BeforeSideTurnStart(PlayerChoiceContext choiceContext, CombatSide side, IReadOnlyList<Creature> participants, ICombatState combatState)",
            "PlayerTurnStart" => "public override async Task AfterPlayerTurnStart(PlayerChoiceContext choiceContext, Player player)",
            "PlayerTurnEnd" => "public override async Task AfterSideTurnEnd(PlayerChoiceContext choiceContext, CombatSide side, IEnumerable<Creature> participants)",
            "CombatVictory" => "public override async Task AfterCombatVictory(CombatRoom room)",
            "DamageReceived" => "public override async Task AfterDamageReceived(PlayerChoiceContext choiceContext, Creature target, DamageResult result, ValueProp props, Creature? dealer, CardModel? cardSource)",
            "GoldGained" => "public override async Task AfterGoldGained(Player player)",
            _ => "public override async Task BeforeCombatStart()",
        };

        var w = new CodeWriter();
        w.Line("// <auto-generated> 自定义遗物 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public sealed class {cls} : RelicModel")
         .Line($"public override RelicRarity Rarity => RelicRarity.{r.Rarity};")
         .Line()
         .Line("protected override IEnumerable<DynamicVar> CanonicalVars =>")
         .Line("[");
        var relicVars = VarNamesOf(r.Effects);
        foreach (var e in r.Effects.Where(x => !HasNoDynamicVar(x))) w.Line($"    {VarDeclaration(e, relicVars)},");
        w.Line("];");

        // 鼠标悬停遗物描述里的状态 → 弹出那条说明（自定义状态 / 被改写的本体状态都有）
        w.Raw(HoverTipsOverride(r.Effects, isPublic: false, owner: p));

        // 条件选项：「每场战斗只触发一次」需要一个标记（本体「百年积木」的做法）
        bool hasCond = r.Condition is not null && !r.Condition.IsNone;
        var relicEffectConds = r.Effects.Where(x => x.Condition is not null && !x.Condition.IsNone).ToList();
        bool oncePerCombat = (hasCond && r.Condition.Kind == "OncePerCombat")
                             || relicEffectConds.Any(x => x.Condition.Kind == "OncePerCombat");
        string condExpr = hasCond ? ConditionExpr(r.Condition, CondCtx.Relic) : "true";
        if (oncePerCombat)
        {
            w.Line()
             .Line("// 条件：每场战斗只触发一次（本体「百年积木」的做法：用完打标记，战斗结束清零）")
             .Line("private bool _condUsedThisCombat;");
        }

        w.Line()
         .Line($"// 触发时机：{trigger.Display}")
         .Open(signature);

        switch (trigger.Id)
        {
            case "CombatStart":
                w.Line("// 只在本次战斗自己的第一个回合开始前触发一次");
                w.Line("if (!participants.Contains(base.Owner.Creature) || base.Owner.PlayerCombatState.TurnNumber > 1) return;");
                break;
            case "PlayerTurnStart":
                w.Line("if (player != base.Owner) return;");
                break;
            case "PlayerTurnEnd":
                w.Line("if (side != base.Owner.Creature.Side) return;");
                break;
            case "DamageReceived":
                w.Line("if (target != base.Owner.Creature) return;");
                break;
            case "GoldGained":
                w.Line("if (player != base.Owner) return;");
                break;
        }

        if (hasCond)
        {
            w.Line();
            w.Line($"// 条件（整只遗物）：{ConditionText(r.Condition)}（不满足时不触发）");
            w.Line(ConditionGuard(r.Condition));
            if (r.Condition.Kind == "OncePerCombat") w.Line("_condUsedThisCombat = true;");
        }

        if (r.Effects.Count > 0) w.Line();
        // 概率生效：这只遗物这一次触发里，所有勾了概率的效果共用一次掷骰
        var relicChanceSlices = ChanceSlices(r.Effects);
        if (relicChanceSlices.Count > 0) w.Line(ChanceRollLine());
        int petAllSeq = 0;
        foreach (var e in r.Effects)
        {
            // 每条效果自己的条件：不满足时只跳过这一条
            string? cond = EffectConditionGuard(e, CondCtx.Relic, chanceSlices: relicChanceSlices);
            if (cond is not null)
            {
                w.Line($"// 条件（只对「{EffectCatalog.FindKind(e.Kind).Display}」这条效果）：{ConditionText(e.Condition)}（不满足时这条效果不触发）");
                w.Open(cond);
            }
            // 「全部召唤物」的「召唤伙伴」：给这一组一个组号，回读时把展开的多份合并回一条
            string? petAllGroup = PetGen.IsAll(e.PetSummon) && e.Kind == "SummonPet" ? "r" + petAllSeq++ : null;
            EmitRelicEffect(w, p, e, hasContext, relicVars, roomVar, petAllGroup);
            if (cond is not null) w.Close();
        }
        // 效果级「每场战斗只触发一次」：跑过一次就打标记（整只遗物级的已经在上面打过标记了）
        if (!hasCond || r.Condition.Kind != "OncePerCombat")
            if (relicEffectConds.Any(x => x.Condition.Kind == "OncePerCombat"))
                w.Line("_condUsedThisCombat = true;");

        w.Close();

        // 「每场战斗一次」的重置（战斗结束清零）
        if (oncePerCombat)
        {
            w.Line()
             .Line("/// <summary>战斗结束：把「每场战斗只触发一次」的标记清掉。</summary>")
             .Open("public override Task AfterCombatEnd(CombatRoom room)")
             .Line("_condUsedThisCombat = false;")
             .Line("return Task.CompletedTask;")
             .Close();
        }
        w.Close();
        return w.ToString();
    }

    /// <summary>该触发时机的钩子是否带 choiceContext。</summary>
    internal static bool HasContext(string triggerId) =>
        triggerId is "CombatStart" or "PlayerTurnStart" or "PlayerTurnEnd" or "DamageReceived";

    private static void EmitRelicEffect(CodeWriter w, CharacterProfile p, EffectSpec e, bool hasContext,
        Dictionary<EffectSpec, string>? varMap = null, string? roomVar = null, string? petAllGroup = null) =>
        EmitRepeated(w, e, x => EmitRelicEffectOnce(x, p, e, hasContext, varMap, roomVar, petAllGroup));

    private static void EmitRelicEffectOnce(CodeWriter w, CharacterProfile p, EffectSpec e, bool hasContext,
        Dictionary<EffectSpec, string>? varMap = null, string? roomVar = null, string? petAllGroup = null)
    {
        string amt = VarAccess(e, varMap);
        // 「直接把缓慢设成 N%」：本体做法是只施加 1 层（层数对「缓慢」没有作用），amount 为 0 时本体直接不挂状态
        if (IsSlowPercentEffect(e)) amt = "1m";
        switch (e.Kind)
        {
            case "EndTurn":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，结束回合无法实现）"); break; }
                w.Line("PlayerCmd.EndTurn(base.Owner, canBackOut: false);");
                break;

            case "ExtraTurn":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，额外回合无法实现）"); break; }
                w.Line($"await PowerCmd.Apply<{Naming.From(p).ExtraTurnPowerClass}>(choiceContext, base.Owner.Creature, 1m, base.Owner.Creature, null);");
                break;

            case "GenerateCard":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，生成卡牌无法实现）"); break; }
                EmitGenerateCard(w, e);
                break;

            case "ExhaustCard":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，消耗卡牌无法实现）"); break; }
                EmitExhaustCard(w, e);
                break;

            case "TransformCard":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，变化卡牌无法实现）"); break; }
                EmitTransformCard(w, e);
                break;

            case "TakeFromDraw":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，从抽牌堆拿牌无法实现）"); break; }
                EmitTakeFromPile(w, e, "Draw");
                break;

            case "TakeFromDiscard":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，从弃牌堆拿牌无法实现）"); break; }
                EmitTakeFromPile(w, e, "Discard");
                break;

            // 全局（牌组）类效果不需要 choiceContext，只要拿到 Player 就行（遗物的 base.Owner 就是 Player）
            case "AddCardGlobal":
            case "TransformCardGlobal":
            case "RemoveCardGlobal":
                EmitGlobalCardEffect(w, e, "base.Owner");
                break;

                case "CardReward":
                    EmitCardReward(w, e, "base.Owner", roomVar: roomVar);
                    break;

            case "Damage":
                if (!hasContext) { Warn(w, e); break; }
                if (e.TargetSide == "Self")
                    w.Line($"await CreatureCmd.Damage(choiceContext, base.Owner.Creature, {amt}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, null, null);");
                else
                    w.Line($"await CreatureCmd.Damage(choiceContext, base.Owner.Creature.CombatState.HittableEnemies, {amt}, ValueProp.Move, base.Owner.Creature);");
                break;

            // 「战斗开始时召唤伙伴」= 本体 Byrdpip 那个遗物的写法（遗物里召唤宠物是官方支持的路子）。
            // 不过本体的钩子只有「战斗开始 / 每回合开始 / 每回合结束 / 受到伤害」这四个带 choiceContext，
            // 「战斗胜利 / 获得金币」那两个钩子拿不到 context（宠物召唤要它），所以那两种时机上只能忽略。
            case "SummonPet":
                if (!hasContext)
                {
                    Warn(w, e, "（该触发时机没有 choiceContext，召唤伙伴无法实现；"
                        + "想要「战斗开始时召唤伙伴」请把遗物的触发时机改成「战斗开始时」）");
                    break;
                }
                // 「全部召唤物」：逐只展开（和卡牌一样），回读靠 CET:PetAll 标记合并回一条
                if (PetGen.IsAll(e.PetSummon))
                {
                    var sumDefs = PetGen.ResolveMany(p, e.PetSummon);
                    if (sumDefs.Count == 0) { EmitSummonPet(w, e, p, amt, useX: false); break; }
                    w.Line($"// 【全部召唤物】这一条对 {sumDefs.Count} 只各来一遍："
                        + string.Join("、", sumDefs.Select(d => d.DisplayName)));
                    foreach (var d in sumDefs)
                        EmitSummonPet(w, e, p, amt, useX: false,
                            extraComment: petAllGroup is null ? null : "// CET:PetAll=" + petAllGroup, petDef: d);
                    break;
                }
                EmitSummonPet(w, e, p, amt, useX: false);
                break;

            // 「伙伴攻击」只能用在卡牌上：遗物没有「玩家选中的目标」，宠物该打谁说不清，所以不静默丢掉。
            // 新增的那批宠物效果（治疗/失去生命/最大生命/牺牲/施加状态/守卫开关）技术上只要拿到 Player
            // 就能做，但**本档只支持卡牌**（用户要求宠物类效果这一档只做卡牌）—— 一并给一句说明，不静默丢。
            case "PetAttack":
            case "PetDamageByMaxHp":
            case "PetDamageByCurHp":
            case "PetDamageByMissingHp":
            case "PetHeal":
            case "PetLoseHp":
            case "PetGainMaxHp":
            case "PetSacrifice":
            case "PetApplyPower":
            case "PetGuardOn":
            case "PetGuardOff":
                Warn(w, e, "（遗物没有「玩家选中的目标」，而且这一档的宠物效果只支持卡牌 —— 请把它放到卡牌上）");
                break;

            case "Block":
                if (e.NextTurn)
                {
                    if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，「下回合格挡」无法实现）"); break; }
                    w.Line($"await PowerCmd.Apply<BlockNextTurnPower>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, null);");
                }
                else
                {
                    // Anchor 的写法：不带 context 也能给格挡
                    EmitPerCreature(w, e, useX: false, "base.Owner.Creature", null, "base.Owner.Creature.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.GainBlock({c}, {BlockValueAccess(varMap, e)}, ValueProp.Move, null);");
                }
                break;

            case "Draw":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，抽牌无法实现）"); break; }
                if (e.NextTurn)
                    w.Line($"await PowerCmd.Apply<DrawCardsNextTurnPower>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, null);");
                else
                    w.Line($"await CardPileCmd.Draw(choiceContext, {amt}, base.Owner);");
                break;

            case "Energy":
                w.Line($"await PlayerCmd.GainEnergy({amt}, base.Owner);");
                break;

            case "Heal":
                if (e.Amount < 0)
                {
                    if (!hasContext) { Warn(w, e); break; }
                    EmitPerCreature(w, e, useX: false, "base.Owner.Creature", null, "base.Owner.Creature.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.Damage(choiceContext, {c}, {-e.Amount}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, null, null);");
                }
                else
                    EmitPerCreature(w, e, useX: false, "base.Owner.Creature", null, "base.Owner.Creature.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.Heal({c}, {amt});");
                break;

            case "HpLoss":
                if (!hasContext) { Warn(w, e); break; }
                EmitPerCreature(w, e, useX: false, "base.Owner.Creature", null, "base.Owner.Creature.CombatState.HittableEnemies",
                    c => $"await CreatureCmd.Damage(choiceContext, {c}, {amt}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, null, null);");
                break;

            case "MaxHp":
                if (e.Amount < 0)
                {
                    if (!hasContext) { Warn(w, e); break; }
                    EmitPerCreature(w, e, useX: false, "base.Owner.Creature", null, "base.Owner.Creature.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.LoseMaxHp(choiceContext, {c}, {-e.Amount}, isFromCard: false);");
                }
                else
                    EmitPerCreature(w, e, useX: false, "base.Owner.Creature", null, "base.Owner.Creature.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.GainMaxHp({c}, {amt});");
                break;

            case "Gold":
                w.Line($"await PlayerCmd.GainGold({amt}, base.Owner);");
                break;

            case "ExtraResource":
                // 额外资源量 = 本体的星星资源。遗物/药水没有「费用」概念，负数直接扣（不会扣成负数）。
                // 这里用字面量而不是 DynamicVar：ExtraResource 不声明变量，访问 DynamicVars 会抛 KeyNotFoundException。
                if (e.Amount >= 0)
                    w.Line($"await PlayerCmd.GainStars({Lit.Dec(e.Amount)}, base.Owner);");
                else
                    w.Line($"await PlayerCmd.SetStars(System.Math.Max(0m, (decimal)base.Owner.PlayerCombatState.Stars - {Lit.Dec(-e.Amount)}), base.Owner);");
                break;

            case "ApplyPower":
                if (!hasContext) { Warn(w, e, "（该触发时机没有 choiceContext，施加增益/减益无法实现）"); break; }
                if (e.NextTurn)
                    w.Line($"await PowerCmd.Apply<{DelayedPowerClassName(e, p)}>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, null);");
                else if (e.TargetSide == "Self")
                {
                    w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, null);");
                    EmitSlowPercentFix(w, e, "base.Owner.Creature");
                }
                else
                {
                    w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, base.Owner.Creature.CombatState.HittableEnemies, {amt}, base.Owner.Creature, null);");
                    // 一次性对全体施加（上面那条重载），这里逐个补百分比
                    EmitSlowPercentFixForAll(w, e);
                }
                break;
        }
    }

    private static void Warn(CodeWriter w, EffectSpec e, string extra = "") =>
        w.Line($"// 该触发时机不支持「{EffectCatalog.FindKind(e.Kind).Display}」{extra}，已忽略。");

    // ==================== 药水 ====================
    public static string PotionSource(CharacterProfile p, PotionSpec s, int index)
    {
        var n = Naming.From(p);
        string cls = n.PotionClassName(s, index);

        var w = new CodeWriter();
        w.Line("// <auto-generated> 自定义药水 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public sealed class {cls} : PotionModel")
         .Line($"public override PotionRarity Rarity => PotionRarity.{s.Rarity};")
         .Line()
         .Line($"public override PotionUsage Usage => PotionUsage.{s.Usage};")
         .Line()
         .Line($"public override TargetType TargetType => TargetType.{s.TargetType};")
         .Line()
         .Line("protected override IEnumerable<DynamicVar> CanonicalVars =>")
         .Line("[");
        var potionVars = VarNamesOf(s.Effects);
        foreach (var e in s.Effects.Where(x => !HasNoDynamicVar(x))) w.Line($"    {VarDeclaration(e, potionVars)},");
        w.Line("];")
         .Line();

        // 鼠标悬停药水描述里的状态 → 弹出那条说明（药水的 ExtraHoverTips 基类是 public）
        w.Raw(HoverTipsOverride(s.Effects, isPublic: true, owner: p));

        w.Line()
         .Open("protected override async Task OnUse(PlayerChoiceContext choiceContext, Creature? target)");

        foreach (var e in s.Effects) EmitPotionEffect(w, p, e, s.TargetType, potionVars);

        w.Close().Close();
        return w.ToString();
    }

    /// <summary>是否有配置用到「额外获得一回合」。</summary>
    public static bool UsesExtraTurn(CharacterProfile p) =>
        p.Cards.SelectMany(c => c.Effects).Concat(p.Relics.SelectMany(r => r.Effects))
            .Concat(p.Potions.SelectMany(s => s.Effects)).Any(e => e.Kind == "ExtraTurn");

    /// <summary>额外回合用的 Power（照抄本体 MockExtraTurnPower 的写法）。</summary>
    /// <summary>这个配置里有没有「透支能量」效果（有才生成那个负债 Power；只做卡牌）。</summary>
    public static bool UsesEnergyDebt(CharacterProfile p) =>
        p.Cards.Any(c => c.Effects.Any(e => e.Kind == "OverdraftEnergy"));

    /// <summary>
    /// 「透支能量」用的负债 Power：施加时立刻把 N 点能量给玩家；下回合能量重置后再扣掉 N 点，然后自毁。
    ///
    /// 为什么不直接用本体的 <c>EnergyNextTurnPower</c>（下回合加能量）加一个负数：
    /// 它的 <c>AfterEnergyReset</c> 走的是 <c>PlayerCmd.GainEnergy</c>，而 GainEnergy 第一句就是
    /// <c>if (!(amount &lt;= 0m) &amp;&amp; …)</c> —— **负数直接被忽略**（实测读源码确认）。
    /// 扣能量必须用 <c>PlayerCmd.LoseEnergy</c>，它内部 <c>PlayerCombatState.LoseEnergy</c> 会
    /// <c>Math.Clamp(…, 0, …)</c>，所以不会把能量扣成负数。
    /// </summary>
    public static string EnergyDebtPowerSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 透支能量用的负债 Power </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Line("/// <summary>透支：现在拿到 N 点能量，下回合少 N 点。</summary>")
         .Open($"public sealed class {n.EnergyDebtPowerClass} : PowerModel")
         .Line("public override PowerType Type => PowerType.Debuff;")
         .Line()
         .Line("public override PowerStackType StackType => PowerStackType.Counter;")
         .Line()
         .Line("// 施加时立刻把能量给玩家（透支的「现在拿」那一半）")
         .Open("public override async Task AfterApplied(Creature? applier, CardModel? cardSource)")
         .Line("await PlayerCmd.GainEnergy(base.Amount, base.Owner.Player);")
         .Line("await Task.CompletedTask;")
         .Close()
         .Line()
         .Line("// 下回合能量重置后再扣掉（本体 GainEnergy 忽略负数，所以必须自己 LoseEnergy；它会夹到 0）")
         .Open("public override async Task AfterEnergyReset(Player player)")
         .Open("if (player == base.Owner.Player)")
         .Line("await PlayerCmd.LoseEnergy(base.Amount, player);")
         .Line("await PowerCmd.Remove(this);")
         .Close()
         .Close()
         .Close();
        return w.ToString();
    }

    public static string ExtraTurnPowerSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        return new CodeWriter()
            .Line("// <auto-generated> 额外回合用的 Power </auto-generated>")
            .Line($"namespace {n.Namespace};")
            .Line()
            .Open($"public sealed class {n.ExtraTurnPowerClass} : PowerModel")
            .Line("public override PowerType Type => PowerType.Buff;")
            .Line()
            .Line("public override PowerStackType StackType => PowerStackType.Counter;")
            .Line()
            .Line("public override bool ShouldTakeExtraTurn(Player player) => player == base.Owner.Player;")
            .Line()
            .Open("public override async Task AfterTakingExtraTurn(Player player)")
