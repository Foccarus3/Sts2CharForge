    private static string PileZh(string pile) => pile switch
    {
        "Draw" => "抽牌堆",
        "Discard" => "弃牌堆",
        _ => "手牌",
    };

    /// <summary>奖励至少要有这么些「可用卡」，否则本体三选一抽不出来会崩。</summary>
    public const int MinRewardPool = 3;

    /// <summary>
    /// 奖励可用的卡：进了卡池、且稀有度是奖励会抽的那三档。
    /// （Basic 不参与奖励；本体抽稀有度时只在 Common/Uncommon/Rare 之间循环，
    ///   所以卡池里全是 Basic 的话同样会崩。）
    /// </summary>
    public static List<CardSpec> RewardEligibleCards(CharacterProfile p) =>
        p.Cards.Where(c => !c.IsVanillaCard && c.InCardPool && c.Rarity is "Common" or "Uncommon" or "Rare").ToList();

    /// <summary>
    /// 卡池是否小到本体发奖励时会崩。
    /// 本体 CardFactory.CreateForReward 会「互不重复地抽 N 张」（普通战斗三选一 N=3），
    /// 抽到第 N 张时可用卡被拉黑完了 → 抛 InvalidOperationException → 奖励界面不弹 → 死档。
    /// 注意：**不再**用「本体卡兜底」，而是让生成前的校验直接拦住（用户要求奖励里不能出现铁甲卡）。
    /// </summary>
    public static bool RewardPoolTooSmall(CharacterProfile p) =>
        RewardEligibleCards(p).Count < MinRewardPool;

    /// <summary>还差几张奖励可用的卡（给校验提示用）。</summary>
    public static string RewardPoolStatus(CharacterProfile p)
    {
        var pool = RewardEligibleCards(p);
        int byRarity(string r) => pool.Count(c => c.Rarity == r);
        return $"{pool.Count} 张可用（Common {byRarity("Common")} / Uncommon {byRarity("Uncommon")} / Rare {byRarity("Rare")}）";
    }

    /// <summary>卡牌配色的十六进制值（非法就退回默认）。</summary>
    private static string Hex(string? value, string fallback)
    {
        string ok = Profile.CardColorSpec.NormalizeHex(value);
        return ok.Length > 0 ? ok : fallback;
    }

    /// <summary>
    /// 这些效果不产生 DynamicVar（数值直接写在代码里），所以 CanonicalVars 与 OnUpgrade 都必须跳过它们。
    /// 漏掉 OnUpgrade 会导致升级时 base.DynamicVars["Value"] 抛 KeyNotFoundException，
    /// 而牌组界面会为每张卡调用 UpgradeInternal → 整个牌组界面打不开。
    /// </summary>
    internal static bool HasNoDynamicVar(EffectSpec e) =>
        e.Kind is "EndTurn" or "ExtraTurn" or "GenerateCard" or "ExhaustCard" or "TransformCard"
        // 全局（牌组）类：获得 / 变化 / 删除牌组里的牌 —— 张数是循环次数，也不是动态变量。
        // **必须列在这里**：漏掉的话 VarDeclaration 的兜底会生成两个 new DynamicVar("Value", …)，
        // 本体的 DynamicVarSet 会直接抛 DynamicVarSet contains duplicate key 'Value'
        //（发生在构造卡牌时 → 开新局就崩、黑屏，实测踩过）。
        or "AddCardGlobal" or "TransformCardGlobal" or "RemoveCardGlobal" or "CardReward"
        // 「伙伴替主人承伤」开 / 关：只挂 / 摘一个状态，没有数值 —— **必须列在这里**，
        // 否则 VarDeclaration 的兜底会多写一个 new DynamicVar("Value", 0m)（两条就撞名 → 开新局崩）
        or "PetGuardOn" or "PetGuardOff"
        // 额外资源量：只有「正数获得」才声明变量（花费走 CanonicalStarCost，不占变量）
        || (e.Kind == "ExtraResource" && e.Amount <= 0)
        // 召唤伙伴：数值填 0 = 用「召唤物」页配置的血量（生成时直接读那只的常量，不声明变量）。
        // 注意：这条要和 ProjectRecovery 的 HasVar / SummonPet 回读保持一致 —— 声明了却没有变量可以取，
        // 或者没声明却被回读当成有变量，都会让「生成 → 回读 → 再生成」两边对不上。
        || (e.Kind == "SummonPet" && e.Amount <= 0)
        // 「数值 = X」时数值不存在 DynamicVar 里（直接取 X），所以不声明变量、也不要 OnUpgrade
        || e.AmountIsX
        // 「全部召唤物」+「按生命值算收益」：改用内联计算（每只各自算），没有动态变量可声明，
        // 升级增量也直接写在表达式里（见 IsAllPetsInlineCalc）。
        || IsAllPetsInlineCalc(e);

    /// <summary>
    /// 额外资源量花费：把负数「获得额外资源量」效果（按生效次数放大）累加成这张牌需要消耗的额外资源量。
    /// 0 表示这张牌不花额外资源量。
    /// </summary>
    internal static int StarCostOf(CardSpec c)
    {
        decimal need = 0m;
        foreach (var e in c.Effects)
        {
            if (e.Kind != "ExtraResource" || e.Amount >= 0) continue;
            need += (-e.Amount) * Math.Max(1, e.Times);
        }
        return need <= 0m ? 0 : (int)decimal.Ceiling(need);
    }

    /// <summary>
    /// 按「生效次数」包一层循环：整条效果重复生效 N 次。
    ///
    /// 注意：body 外面**永远再包一层作用域 {}**：
    /// 同一条效果里可能内嵌自己的循环（随机目标 / 随机消耗 / 全局加牌…），
    /// 这些循环变量和临时变量（foes / hits / pick / other）如果和外面重名，C# 会直接 CS0136 编译不过
    /// （用户实测：一张「生效次数 = 3」的随机打敌人牌，生成出两层 for (int i…) 就炸了）。
    /// 注意 C# 不允许内层作用域重复声明外层的同名局部变量，所以内层的循环变量也全部用了 __ 前缀的名字。
    /// </summary>
    private static void EmitRepeated(CodeWriter w, EffectSpec e, Action<CodeWriter> body, bool useX = false)
    {
        if (useX && e.TimesIsX)
        {
            w.Open($"for (int i = 0; i < {XVar}; i++)");
            w.Open("");
            body(w);
            w.Close();
            w.Close();
            return;
        }
        int times = Math.Max(1, e.Times);
        if (times > 1) w.Open($"for (int i = 0; i < {times}; i++)");
        w.Open("");
        body(w);
        w.Close();
        if (times > 1) w.Close();
    }

    private static void EmitCardEffect(CodeWriter w, CharacterProfile p, EffectSpec e, bool useX = false,
        Dictionary<EffectSpec, string>? varMap = null, string? petVar = null, PetGen.PetDef? petDef = null,
        string? effectComment = null) =>
        EmitRepeated(w, e, x =>
        {
            // 宠物类效果：在这条效果的**第一行**写一行标记（单行，回读按它认种类与公式，见 MarkerText）
            if (IsPetKindForMarker(e.Kind))
                x.Line($"// CET:PetEffect={MarkerText(e)}");
            EmitCardEffectOnce(x, p, e, useX, varMap, petVar, petDef, effectComment);
        }, useX);

    /// <summary>
    /// 「全部召唤物」+「按生命值算收益」的宠物效果：改用**内联计算**（<c>(decimal)pet.MaxHp</c> 这种）。
    ///
    /// 为什么不能继续用本体那套计算变量：<c>CalculatedDamage / CalculatedBlock / CalculationBase</c>
    /// 名字是固定的（本体按名字取），一张牌只有一套 —— 而「全部召唤物」是每只各算一次，
    /// 各自的倍率来源都不同，一套变量装不下。所以这一档既不声明动态变量，卡面也不显示具体数字
    /// （见 LocalizationGen：描述里写明「各自按自己的生命值算」）。
    /// 升级增量也直接写成 <c>(base.IsUpgraded ? N : 0m)</c>（和 CalculationBase 的加值等价）。
    /// </summary>
    internal static bool IsAllPetsInlineCalc(EffectSpec e) =>
        PetGen.IsAll(e.PetSummon) && PetFormula(e) is not null and not "fixed";

    /// <summary>
    /// 卡面描述里该用的动态变量名 —— 必须是 <c>CanonicalVars</c> 里**真实声明**的那个键。
    ///
    /// 为什么不能直接用 <see cref="VarNameOf"/>：三个「按生命值算的伙伴攻击」和「牺牲伙伴（按生命值算）」
    /// 声明的是本体那套**固定名字**的计算变量（<c>CalculatedDamage</c> / <c>CalculatedBlock</c>，
    /// 见 <see cref="CalcDamageVars"/> / <see cref="PetSacrificeVarDecl"/>），
    /// 而 <see cref="VarNameOf"/> 给它们起的名字（PetMaxHpDamage 这种）只是**我们自己内部**用来去重的。
    /// 用错名字的后果：卡面上直接原样印出 <c>{PetMissingHpDamage:diff()}</c>
    /// （用户实测截图报过：已损失生命值 / 最大生命值那两种、以及牺牲伙伴的收益都是这样）——
    /// 因为本地化文本里的 <c>{名字:diff()}</c> 在本体的 DynamicVars 里找不到同名变量。
    /// </summary>
    public static string DisplayVarNameOf(EffectSpec e, Dictionary<EffectSpec, string>? map = null) =>
        PetFormula(e) is not null and not "fixed"
            ? (e.Kind == "PetSacrifice" && e.PetSacrificeGain != "Damage" ? "CalculatedBlock" : "CalculatedDamage")
            : VarNameOf(e, map);

    /// <summary>
    /// 生成后自检：这份源码里有没有「引用了、但 CanonicalVars 里没声明」的动态变量。
    /// 返回缺失的变量名（空列表 = 没问题；**认不出来的变量类型会跳过整张卡的自检**，宁可漏报不误报）。
    ///
    /// 为什么必须查：本体的 <c>DynamicVars</c> 是**按名字取**的，取不到就抛 <c>KeyNotFoundException</c>。
    /// 这个异常发生在「卡牌被升级 / 牌组界面预览升级（『查看升级』）/ 卡面渲染」时，
    /// 表现是**牌组界面整个打不开、一片空白**（用户实测报过：牺牲伙伴选「固定 N」又填了升级增量，
    /// 升级增量被写到没声明的 CalculationBase 上，一开牌组就看不到牌）。
    /// 只有游戏里才会暴露，所以生成完就自己查一遍，把它当成生成错误拦住。
    /// </summary>
    public static IReadOnlyList<string> MissingDynamicVars(string source)
    {
        var m = System.Text.RegularExpressions.Regex.Match(source, @"CanonicalVars\s*=>\s*\[(.*?)\];",
            System.Text.RegularExpressions.RegexOptions.Singleline);
        var declared = new HashSet<string>(StringComparer.Ordinal);
        if (m.Success)
        {
            foreach (string item in SplitTopLevel(m.Groups[1].Value))
            {
                string s = item.Trim();
                if (s.Length == 0) continue;
                // 1) 起了名字的（new DynamicVar("PetHp", 0m) / new BlockVar("PetSacrificeBlock", 6m, …)）
                var named = System.Text.RegularExpressions.Regex.Match(s, "\"([^\"]+)\"");
                if (named.Success) { declared.Add(named.Groups[1].Value); continue; }
                // 2) 没起名字的：按变量类型的默认键名（和本体一致）
                var ty = System.Text.RegularExpressions.Regex.Match(s, @"new\s+([A-Za-z0-9_]+)");
                if (!ty.Success) continue;
                string tn = ty.Groups[1].Value;
                if (tn == "PowerVar")
                {
                    var pw = System.Text.RegularExpressions.Regex.Match(s, @"PowerVar<(\w+)>");
                    if (!pw.Success) return Array.Empty<string>();      // 认不出来 → 放弃这张卡的检查
                    declared.Add(pw.Groups[1].Value);
                    continue;
                }
                string? def = tn switch
                {
                    "DamageVar" => "Damage",
                    "BlockVar" => "Block",
                    "CardsVar" => "Cards",
                    "EnergyVar" => "Energy",
                    "HealVar" => "Heal",
                    "HpLossVar" => "HpLoss",
                    "MaxHpVar" => "MaxHp",
                    "GoldVar" => "Gold",
                    "StarsVar" => "Stars",
                    "CalculationBaseVar" => "CalculationBase",
                    "CalculationExtraVar" => "CalculationExtra",
                    "ExtraDamageVar" => "ExtraDamage",
                    "CalculatedDamageVar" => "CalculatedDamage",
                    "CalculatedBlockVar" => "CalculatedBlock",
                    _ => null,
                };
                if (def is null) return Array.Empty<string>();          // 认不出来 → 放弃这张卡的检查
                declared.Add(def);
            }
        }

        var refs = new HashSet<string>(StringComparer.Ordinal);
        foreach (System.Text.RegularExpressions.Match r in System.Text.RegularExpressions.Regex.Matches(
                     source, @"base\.DynamicVars\.([A-Za-z0-9_]+)"))
            refs.Add(r.Groups[1].Value);
        foreach (System.Text.RegularExpressions.Match r in System.Text.RegularExpressions.Regex.Matches(
                     source, @"base\.DynamicVars\[""([^""]+)""\]"))
            refs.Add(r.Groups[1].Value);
        return refs.Where(x => !declared.Contains(x)).OrderBy(x => x, StringComparer.Ordinal).ToList();
    }

    /// <summary>按**顶层**逗号切分（跳过括号 / 方括号里的逗号）—— 用来拆 CanonicalVars 的每一项。</summary>
    private static IEnumerable<string> SplitTopLevel(string s)
    {
        int depth = 0, start = 0;
        for (int i = 0; i < s.Length; i++)
        {
            char c = s[i];
            if (c is '(' or '[' or '<') depth++;
            else if (c is ')' or ']' or '>') depth--;
            else if (c == ',' && depth <= 0)
            {
                yield return s.Substring(start, i - start);
                start = i + 1;
            }
        }
        if (start < s.Length) yield return s.Substring(start);
    }

    /// <summary>要不要写 <c>// CET:PetEffect=…</c> 标记（新增的那批宠物效果都要，SummonPet / PetAttack 保持原样）。</summary>
    internal static bool IsPetKindForMarker(string kind) =>
        kind is "PetDamageByMaxHp" or "PetDamageByCurHp" or "PetDamageByMissingHp"
            or "PetHeal" or "PetLoseHp" or "PetGainMaxHp" or "PetSacrifice" or "PetApplyPower"
            or "PetGuardOn" or "PetGuardOff";

    private static void EmitCardEffectOnce(CodeWriter w, CharacterProfile p, EffectSpec e, bool useX = false,
        Dictionary<EffectSpec, string>? varMap = null, string? petVar = null, PetGen.PetDef? petDef = null,
        string? effectComment = null)
    {
        string amt = AmountExpr(e, useX, varMap);
        // 「直接把缓慢设成 N%」：本体的做法就是只施加 1 层（层数对「缓慢」没有作用），
        // 而且 amount == 0 时 PowerCmd.Apply 会直接 return（状态根本不会挂上），所以必须给 1。
        if (IsSlowPercentEffect(e)) amt = "1m";
        switch (e.Kind)
        {
            case "EndTurn":
                w.Line("PlayerCmd.EndTurn(base.Owner, canBackOut: false);");
                break;

            case "ExtraTurn":
                w.Line($"await PowerCmd.Apply<{Naming.From(p).ExtraTurnPowerClass}>(choiceContext, base.Owner.Creature, 1m, base.Owner.Creature, this);");
                break;

            case "GenerateCard":
                EmitGenerateCard(w, e, useX);
                break;

            case "ExhaustCard":
                EmitExhaustCard(w, e, useX);
                break;

            case "TransformCard":
                EmitTransformCard(w, e, useX);
                break;

            case "TakeFromDraw":
                EmitTakeFromPile(w, e, "Draw", useX);
                break;

            case "TakeFromDiscard":
                EmitTakeFromPile(w, e, "Discard", useX);
                break;

            case "AddCardGlobal":
            case "TransformCardGlobal":
            case "RemoveCardGlobal":
                EmitGlobalCardEffect(w, e, "base.Owner", useX);
                break;

                case "CardReward":
                    EmitCardReward(w, e, "base.Owner", useX);
                    break;

            case "Damage":
                EmitAttack(w, e, amt, useX);
                break;

            // ===== 召唤伙伴（本体的通用宠物 API，不需要补丁）=====
            case "SummonPet":
                EmitSummonPet(w, e, p, amt, useX, effectComment, petDef);
                break;

            case "PetAttack":
                EmitPetAttack(w, e, p, petVar ?? "__pet", amt, useX, petDef);
                break;

            // ===== 新增的那批宠物效果（都要「已经召唤出来的那只」，外面已经包了 if (pet != null)）=====
            // 三个按生命值算的伙伴攻击：用本体攻击链 + 计算变量三件套；attacker 换成宠物。
            case "PetDamageByMaxHp":
            case "PetDamageByCurHp":
            case "PetDamageByMissingHp":
                EmitPetCalculatedAttack(w, e, p, petVar ?? "__pet", useX, petDef);
                break;

            case "PetHeal":
                EmitPetHeal(w, e, petVar ?? "__pet", amt);
                break;

            case "PetLoseHp":
                EmitPetLoseHp(w, e, petVar ?? "__pet", amt);
                break;

            case "PetGainMaxHp":
                EmitPetGainMaxHp(w, e, petVar ?? "__pet", amt);
                break;

            case "PetSacrifice":
                EmitPetSacrifice(w, e, p, petVar ?? "__pet", varMap, useX, petDef);
                break;

            case "PetApplyPower":
                EmitPetApplyPower(w, p, e, petVar ?? "__pet", amt);
                break;

            case "PetGuardOn":
                EmitPetGuard(w, p, petVar ?? "__pet", on: true);
                break;

            case "PetGuardOff":
                EmitPetGuard(w, p, petVar ?? "__pet", on: false);
                break;

            // ===== 透支能量：现在拿 N 点，下回合少 N 点（走生成的负债 Power）=====
            case "OverdraftEnergy":
                w.Line($"await PowerCmd.Apply<{Naming.From(p).EnergyDebtPowerClass}>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, this);"
                    + "   // 透支：施加时立刻给能量，下回合能量重置后再扣掉（本体 GainEnergy 忽略负数，所以必须自己扣）");
                break;

            case "Block":
                if (e.NextTurn)
                    w.Line($"await PowerCmd.Apply<BlockNextTurnPower>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, this);");
                else if (useX && e.AmountIsX)
                    // 格挡 = X：BlockVar 那条重载只能吃固定值，X 要走 decimal 重载
                    EmitPerCreature(w, e, useX, "base.Owner.Creature", "cardPlay.Target", "base.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.GainBlock({c}, x, ValueProp.Move, cardPlay);");
                else
                    EmitPerCreature(w, e, useX, "base.Owner.Creature", "cardPlay.Target", "base.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.GainBlock({c}, {BlockValueAccess(varMap, e)}, ValueProp.Move, cardPlay);");
                break;

            case "Draw":
                if (e.NextTurn)
                    w.Line($"await PowerCmd.Apply<DrawCardsNextTurnPower>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, this);");
                else
                    w.Line($"await CardPileCmd.Draw(choiceContext, {amt}, base.Owner);");
                break;

            case "Energy":
                if (e.NextTurn)
                    w.Line($"await PowerCmd.Apply<EnergyNextTurnPower>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, this);");
                else
                    w.Line($"await PlayerCmd.GainEnergy({amt}, base.Owner);");
                break;

            case "Heal":
                if (e.Amount < 0 && !(useX && e.AmountIsX))
                    EmitPerCreature(w, e, useX, "base.Owner.Creature", "cardPlay.Target", "base.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.Damage(choiceContext, {c}, {-e.Amount}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, this, null);");
                else
                    EmitPerCreature(w, e, useX, "base.Owner.Creature", "cardPlay.Target", "base.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.Heal({c}, {amt});");
                break;

            case "HpLoss":
                EmitPerCreature(w, e, useX, "base.Owner.Creature", "cardPlay.Target", "base.CombatState.HittableEnemies",
                    c => $"await CreatureCmd.Damage(choiceContext, {c}, {amt}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, this, null);");
                break;

            case "MaxHp":
                if (e.Amount < 0 && !(useX && e.AmountIsX))
                    EmitPerCreature(w, e, useX, "base.Owner.Creature", "cardPlay.Target", "base.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.LoseMaxHp(choiceContext, {c}, {-e.Amount}, isFromCard: true);");
                else
                    EmitPerCreature(w, e, useX, "base.Owner.Creature", "cardPlay.Target", "base.CombatState.HittableEnemies",
                        c => $"await CreatureCmd.GainMaxHp({c}, {amt});");
                break;

            case "Gold":
                w.Line($"await PlayerCmd.GainGold({amt}, base.Owner);");
                break;
            case "ExtraResource":
                // 额外资源量 = 本体的星星资源。
                // 正数：声明一个 StarsVar（canonical 变量），打出时按它的 BaseValue 立即获得，
                //       升级增量写在 OnUpgrade 里（UpgradeValueBy），卡面描述用 {Stars:diff()} 跟着变。
                // 负数（花费）：不在这里扣，而是通过 CanonicalStarCost 声明成卡牌费用，
                //       本体自带的判定会让「资源不够就打不出去」，并且卡面会显示红色的费用数字。
                if (e.Amount > 0)
                {
                    // 有 StarsVar 就用它（升级增量由 OnUpgrade 的 UpgradeValueBy 处理），
                    // 卡面描述里的 {Stars:diff()} 也会跟着变 —— 以前用「IsUpgraded 三目」写死，描述永远显示原值。
                    string gain = useX && e.AmountIsX
                        ? XVar
                        : VarAccess(e, varMap);
                    w.Line($"await PlayerCmd.GainStars({gain}, base.Owner);");
                }
                break;

            case "ApplyPower":
                if (e.NextTurn)
                {
                    w.Line($"await PowerCmd.Apply<{DelayedPowerClassName(e, p)}>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, this);");
                    break;
                }
                switch (e.TargetSide)
                {
                    case "Self":
                        w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, this);");
                        EmitSlowPercentFix(w, e, "base.Owner.Creature");
                        break;
                    case "AllEnemies":
                        w.Open("foreach (Creature foe in base.CombatState.HittableEnemies)")
                         .Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, foe, {amt}, base.Owner.Creature, this);");
                        EmitSlowPercentFix(w, e, "foe");
                        w.Close();
                        break;
                    case "RandomEnemies":
                        w.Line("List<Creature> foes = base.CombatState.HittableEnemies.ToList();")
                         .Open($"for (int __foeIdx = 0; __foeIdx < {RepeatExpr(e, useX)} && foes.Count > 0; __foeIdx++)")
                         .Line("Creature foe = base.Owner.RunState.Rng.CombatTargets.NextItem(foes);");
                        if (!e.AllowDuplicates) w.Line("foes.Remove(foe);");
                        w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, foe, {amt}, base.Owner.Creature, this);");
                        EmitSlowPercentFix(w, e, "foe");
                        w.Close();
                        break;
                    default:
                        w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, cardPlay.Target, {amt}, base.Owner.Creature, this);");
                        EmitSlowPercentFix(w, e, "cardPlay.Target");
                        break;
                }
                break;
        }
    }

    private static void EmitAttack(CodeWriter w, EffectSpec e, string amt, bool useX = false)
    {
        switch (e.TargetSide)
        {
            case "Self":
                w.Line($"await CreatureCmd.Damage(choiceContext, base.Owner.Creature, {amt}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, this, null);");
                break;
            case "AllEnemies":
                w.Line($"await DamageCmd.Attack({amt})")
                 .Indent().Line(".FromCard(this, cardPlay)").Line(".TargetingAllOpponents(base.CombatState)")
                 .Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent().Line();
                break;
            case "RandomEnemies":
                if (e.AllowDuplicates)
                {
                    // 允许重复命中同一个敌人：次数照填（本体回旋镖就是默认允许重复）
                    w.Line($"await DamageCmd.Attack({amt})")
                     .Indent().Line(".FromCard(this, cardPlay)")
                     .Line(".TargetingRandomOpponents(base.CombatState, allowDuplicates: true)")
                     .Line($".WithHitCount({RepeatExpr(e, useX)})")
                     .Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent().Line();
                }
                else
                {
                    // 不允许重复选中：命中次数要收敛到「当前可打的敌人数」，
                    // 否则本体找不到足够多互不相同的目标会一直等 → 卡牌卡住
                    w.Line($"int hits = {RepeatExpr(e, useX)};")
                     .Line("if (hits > base.CombatState.HittableEnemies.Count) hits = base.CombatState.HittableEnemies.Count;")
                     .Open("if (hits > 0)")
                     .Line($"await DamageCmd.Attack({amt})")
                     .Indent().Line(".FromCard(this, cardPlay)")
                     .Line(".TargetingRandomOpponents(base.CombatState, allowDuplicates: false)")
                     .Line(".WithHitCount(hits)")
                     .Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent()
                     .Close();
                }
                break;
            default:
                // 单体目标：命中次数 > 1（或 = X）时也要写成多段命中，
                // 本体「旋风斩 / 天际钻头」就是 .WithHitCount(...) 打同一个目标。
                string singleHits = RepeatExpr(e, useX);
                bool multi = (useX && e.RepeatIsX) || e.RepeatCount > 1;
                if (multi)
                {
                    w.Line($"await DamageCmd.Attack({amt})")
                     .Indent().Line(".FromCard(this, cardPlay)").Line(".Targeting(cardPlay.Target)")
                     .Line($".WithHitCount({singleHits})")
                     .Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent().Line();
                }
                else
                {
                    w.Line($"await DamageCmd.Attack({amt})")
                     .Indent().Line(".FromCard(this, cardPlay)").Line(".Targeting(cardPlay.Target)")
                     .Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent().Line();
                }
                break;
        }
    }

    // ==================== 召唤伙伴（无需补丁） ====================
    //
    // 为什么不走 OstyCmd.Summon：那个是奥斯提专用包装，内部硬编码 Osty 类型，非 Osty 会抛异常。
    // 本体真正通用的是 PlayerCmd.AddPet<T>(player)（Byrdpip / Pael's Legion 用的就是它），
    // 所以生成的是「每只召唤物一个宠物类 + 一个命令助手」，召唤 = 助手.Summon(choiceContext, owner, hp)。
    // 也**不要**用 MinionPower（那是给敌方小怪打的标记）。

    /// <summary>
    /// 「伙伴攻击」在 OnPlay 里那个局部变量名（按宠物类名取，一张牌指向多只宠物时互不覆盖）。
    /// 用 <c>__</c> 前缀：和生成代码里其它临时变量（<c>__foeIdx</c> / <c>__pickIdx</c>…）保持一致的风格。
    /// </summary>
    internal static string PetAttackVarName(string petClassName) =>
        petClassName.Length == 0 ? "__pet" : "__" + char.ToLowerInvariant(petClassName[0]) + petClassName.Substring(1);

    /// <summary>
    /// 召唤伙伴的两种语义用**注释标记**区分，方便「从工程恢复存档」原样认回来：
    ///   · 数值 0（用「召唤物」页配置的血量）→ <c>// CET:PetHp=configured</c>
    ///   · 按这条效果填的数值 → <c>// CET:PetHp=var</c>
    /// 为什么要标记：两种情况生成出来的调用一模一样（配置血量是多少就写多少 m），
    /// 不标记的话「填了 9」和「留空用配置的 9」恢复出来无法区分。
    /// </summary>
    private static string PetHpComment(bool configured) => configured ? " // CET:PetHp=configured" : " // CET:PetHp=var";

    /// <summary>「这只召唤物还没选 / 选的那只不存在」时生成的兜底说明（校验器会先把这种配置拦住）。</summary>
    private static string PetMissingHint(string? id) =>
        (string.IsNullOrWhiteSpace(id) ? "（还没选召唤物）" : $"（找不到召唤物「{id!.Trim()}」）");

    /// <summary>
    /// 「召唤伙伴」。数值 &gt; 0 = 按填的生命召唤；数值 = 0 = 用「召唤物」页里配置的血量。
    /// 助手内部的 Summon 已经处理了「已经在场就加最大生命、不重复召唤」，所以这里直接调一次就行。
    ///
    /// 哪一只由 <see cref="EffectSpec.PetSummon"/>（稳定标识 = 宠物类名）决定；留空（老存档）时
    /// <see cref="PetGen.Resolve"/> 会退回第一只启用的召唤物 —— 和上一版单只召唤物的行为一致。
    /// </summary>
    private static void EmitSummonPet(CodeWriter w, EffectSpec e, CharacterProfile p, string amt, bool useX,
        string? extraComment = null, PetGen.PetDef? petDef = null)
    {
        // 「全部召唤物」：展开时逐只传进来（那时 e.PetSummon 是 "*"，Resolve 认不出来）
        var def = petDef ?? PetGen.Resolve(p, e.PetSummon);
        if (def is null)
        {
            // 校验器会拦住这种配置（生成会被中止），这里只保证万一跑到了也不生成编译不过的代码
            w.Line($"// ⚠ 这条「召唤伙伴」没有可用的召唤物{PetMissingHint(e.PetSummon)}：到「召唤物」页添加一只并勾上「启用」");
            return;
        }

        bool useConfigured = !useX && e.Amount <= 0;
        string hp = useConfigured ? $"{def.Hp}m" : amt;
        string cmd = def.ClassName + "Cmd";
        w.Line(useConfigured
            ? $"// 数值 0 = 用「召唤物」页里配置的血量（{def.DisplayName} {def.Hp} 点生命）"
            : $"// 按这条效果填的生命召唤{def.DisplayName}（已经在场就加最大生命，本体 OstyCmd 的做法）");
        w.Line($"await {cmd}.Summon(choiceContext, base.Owner, {hp});"
            + PetHpComment(useConfigured) + (extraComment is null ? "" : " " + extraComment));
    }

    /// <summary>
    /// 「伙伴攻击」：attacker 是**宠物**（不是玩家）。
    ///
    /// 为什么不能写 <c>FromMonster(pet.Monster)</c>（上一版就是这么写的，用户实测「攻击不生效」）：
    ///   · <c>FromMonster</c>（本体 AttackCommand.cs:257-267）把来源标成 <c>SourceType.Monster</c>，而
    ///     <c>GetPossibleTargets()</c>（:163-182）在 <c>_sourceType == Monster</c> 时硬编码返回
    ///     <c>_combatState.PlayerCreatures</c> —— 玩家侧的宠物会去打玩家自己人；
    ///   · 它还顺手 <c>TargetingAllOpponents</c>（:266）把 <c>_combatState</c> 设上，
    ///     于是 <c>Targeting</c>（:273-286）抛 "Already set to target opponents of attacker"；
    ///     反过来先 <c>Targeting</c> 再 <c>FromMonster</c>，<c>TargetingAllOpponents</c> 又抛 "Targets already set."。
    /// 正确形状 = 本体 <c>FromOsty</c>（:238-251）那套：攻击者换成宠物，但来源仍标成 Card —— 于是
    /// <c>GetPossibleTargets()</c> 走 <c>:179 GetOpponentsOf(Attacker)</c>（宠物是玩家侧 → 拿到敌人），
    /// <c>Execute</c> 里 <c>dealer: Attacker</c> / <c>cardSource: ModelSource as CardModel</c>（:669）也对。
    /// <c>FromOsty</c> 硬校验 <c>osty.Monster is Osty</c>，用不了；所以先走 <c>FromCard</c>，
    /// 再用我们自己的扩展方法 <c>FromPetAttacker</c> 反射把 <c>Attacker</c> 换成宠物（**不需要补丁**）。
    ///
    /// 注意：宠物必须活着（血量 &gt; 0）才打得出伤害 —— <c>Execute</c> 开头 <c>if (Attacker.IsDead) return this;</c>
    /// 会静默早退，所以调用处要先判「这只宠物在不在场」，血量也由召唤命令保证 &gt; 0。
    /// </summary>
    private static void EmitPetAttack(CodeWriter w, EffectSpec e, CharacterProfile p, string petVar, string amt,
        bool useX, PetGen.PetDef? petDef = null)
    {
        var def = petDef ?? PetGen.Resolve(p, e.PetSummon);
        if (def is null)
        {
            w.Line($"// ⚠ 这条「伙伴攻击」没有可用的召唤物{PetMissingHint(e.PetSummon)}：到「召唤物」页添加一只并勾上「启用」");
            return;
        }

        string hits = RepeatExpr(e, useX);
        bool multi = (useX && e.RepeatIsX) || e.RepeatCount > 1;

        switch (e.TargetSide)
        {
            case "AllEnemies":
                w.Line($"await DamageCmd.Attack({amt})")
                 .Indent().Line(".FromCard(this, cardPlay)          // 来源 = 这张牌（攻击历史与 hook 都正常）")
                 .Line(".TargetingAllOpponents(base.CombatState)")
                 .Line($".FromPetAttacker({petVar})          // 攻击者换成{def.DisplayName}")
                 .Line(".WithAttackerAnim(\"Attack\", 0.3f)   // 宠物自己的攻击动画（没有就退化成不动，无副作用）");
                if (multi) w.Line($".WithHitCount({hits})");
                w.Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent().Line();
                break;

            case "RandomEnemies":
                w.Line($"await DamageCmd.Attack({amt})")
                 .Indent().Line(".FromCard(this, cardPlay)")
                 .Line($".TargetingRandomOpponents(base.CombatState, allowDuplicates: {(e.AllowDuplicates ? "true" : "false")})")
                 .Line($".FromPetAttacker({petVar})")
                 .Line(".WithAttackerAnim(\"Attack\", 0.3f)")
                 .Line($".WithHitCount({hits})")
                 .Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent().Line();
                break;

            default:
                w.Line($"await DamageCmd.Attack({amt})")
                 .Indent().Line(".FromCard(this, cardPlay)")
                 .Line(".Targeting(cardPlay.Target)")
                 .Line($".FromPetAttacker({petVar})");
                if (multi) w.Line($".WithHitCount({hits})");
                w.Line(".WithAttackerAnim(\"Attack\", 0.3f)")
                 .Line(".WithHitFx(\"vfx/vfx_attack_slash\")").Line(".Execute(choiceContext);").Dedent().Line();
                break;
        }
    }

    // ==================== 新增的那批宠物效果（不需要任何补丁） ====================
    //
    // 共同点：都要求「宠物已经召唤出来且活着」—— 调用处外面已经包了 if (pet != null)，
    // 所以这里不再重复判空（也**不能**再写一行 `Creature? pet = …`：那会和外面的同名变量冲突 → CS0136）。
    // 「需要已召唤宠物」的整张牌还会生成 IsPlayable / ShouldGlowRedInternal（见 CardSource）。

    /// <summary>
    /// 三个「按生命值算的伙伴攻击」：<c>DamageCmd.Attack(base.DynamicVars.CalculatedDamage)</c>。
    ///
    /// 为什么传 CalculatedDamageVar 而不是先算出数字：走这条路本体的 ModifyDamage / 力量 / 虚弱 /
    /// 附魔都会照常作用在**宠物**身上（Attacker 已经被 FromPetAttacker 换成宠物）。
    /// 为什么不用 <c>.FromCard(this, cardPlay)</c> 之后直接 Attacker？—— FromCard 会把 Attacker 设成玩家，
    /// 必须再用 FromPetAttacker 盖掉，次序不能反（本体 AttackCommand.cs:216-223 校验 Attacker 已设置就抛）。
    /// </summary>
    private static void EmitPetCalculatedAttack(CodeWriter w, EffectSpec e, CharacterProfile p, string petVar,
        bool useX, PetGen.PetDef? petDef = null)
    {
        var def = petDef ?? PetGen.Resolve(p, e.PetSummon);
        if (def is null)
        {
            w.Line($"// ⚠ 这条「{EffectCatalog.FindKind(e.Kind).Display}」没有可用的召唤物{PetMissingHint(e.PetSummon)}"
                + "：到「召唤物」页添加一只并勾上「启用」");
            return;
        }

        // 「全部召唤物」展开出来的那一份：没有计算变量可用（一张牌只有一套固定名字的计算变量），
        // 直接按**这只自己的**生命值算 —— 见 IsAllPetsInlineCalc 的说明。
        bool inline = IsAllPetsInlineCalc(e);
        string damage = inline ? InlinePetDamageExpr(e, petVar) : "base.DynamicVars.CalculatedDamage";

        string formulaZh = e.Kind switch
        {
            "PetDamageByCurHp" => "当前生命值",
            "PetDamageByMissingHp" => "已损失的生命值",
            _ => "最大生命值",
        };
        string hits = RepeatExpr(e, useX);
        bool multi = (useX && e.RepeatIsX) || e.RepeatCount > 1;
        w.Line(inline
            ? $"// 伤害 = 伙伴{def.DisplayName}自己的{formulaZh}（「全部召唤物」：每只各自算，卡面不显示具体数字）"
            : $"// 伤害 = 伙伴{def.DisplayName}的{formulaZh}（由 CalculatedDamage 这个计算变量在本体里算）");

        switch (e.TargetSide)
        {
            case "AllEnemies":
                w.Line($"await DamageCmd.Attack({damage})")
                 .Indent().Line(".FromCard(this, cardPlay)          // 来源 = 这张牌（攻击历史与 hook 都正常）")
                 .Line(".TargetingAllOpponents(base.CombatState)")
                 .Line($".FromPetAttacker({petVar})          // 攻击者换成{def.DisplayName}")
                 .Line(".WithAttackerAnim(\"Attack\", 0.3f)");
                if (multi) w.Line($".WithHitCount({hits})");
                w.Line(".WithHitFx(\"vfx/vfx_attack_blunt\", null, \"blunt_attack.mp3\")")
                 .Line(".Execute(choiceContext);").Dedent().Line();
                break;

            case "RandomEnemies":
                w.Line($"await DamageCmd.Attack({damage})")
                 .Indent().Line(".FromCard(this, cardPlay)")
                 .Line($".TargetingRandomOpponents(base.CombatState, allowDuplicates: {(e.AllowDuplicates ? "true" : "false")})")
                 .Line($".FromPetAttacker({petVar})")
                 .Line(".WithAttackerAnim(\"Attack\", 0.3f)")
                 .Line($".WithHitCount({hits})")
                 .Line(".WithHitFx(\"vfx/vfx_attack_blunt\", null, \"blunt_attack.mp3\")")
                 .Line(".Execute(choiceContext);").Dedent().Line();
                break;

            default:
                w.Line($"await DamageCmd.Attack({damage})")
                 .Indent().Line(".FromCard(this, cardPlay)")
                 .Line(".Targeting(cardPlay.Target)")
                 .Line($".FromPetAttacker({petVar})");
                if (multi) w.Line($".WithHitCount({hits})");
                w.Line(".WithAttackerAnim(\"Attack\", 0.3f)")
                 .Line(".WithHitFx(\"vfx/vfx_attack_blunt\", null, \"blunt_attack.mp3\")")
                 .Line(".Execute(choiceContext);").Dedent().Line();
                break;
        }
    }

    /// <summary>
    /// 「全部召唤物」那一档的伤害表达式：直接用**这只宠物自己**的生命值算（内联，不走计算变量）。
    /// 三种倍率与本体 CalculatedDamageVar 的 lambda 完全一致（最大生命 / 当前生命 / 已损失），
    /// 升级增量按 <c>(base.IsUpgraded ? N : 0m)</c> 加在最后 —— 等价于原来抬 CalculationBase 的做法。
    /// </summary>
    private static string InlinePetDamageExpr(EffectSpec e, string petVar)
    {
        string v = e.Kind switch
        {
            "PetDamageByCurHp" => $"(decimal){petVar}.CurrentHp",
            "PetDamageByMissingHp" => $"(decimal)({petVar}.MaxHp - {petVar}.CurrentHp)",
            _ => $"(decimal){petVar}.MaxHp",
        };
        if (e.UpgradeAmount != 0m)
            v = $"({v} + (base.IsUpgraded ? {Lit.Dec(e.UpgradeAmount)} : 0m))";
        return v;
    }

