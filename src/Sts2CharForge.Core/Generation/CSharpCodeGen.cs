    /// <summary>是否需要生成「额外资源量外观」补丁（配了名字或自定义图标才需要）。</summary>
    public static bool HasExtraResourceUi(CharacterProfile p)
    {
        if (!p.ExtraResource.Enabled) return false;
        return !string.IsNullOrWhiteSpace(p.ExtraResource.Name)
               || !string.IsNullOrWhiteSpace(p.ExtraResource.Icon);
    }

