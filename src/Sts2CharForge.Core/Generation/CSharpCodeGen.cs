    /// <summary>
    /// 一个模型（卡牌 / 遗物 / 药水）里，每条效果对应的动态变量名。
    ///
    /// **为什么必须唯一**：本体的 <c>DynamicVarSet</c> 用变量名当键，重名会直接抛
    /// <c>ArgumentException: DynamicVarSet contains duplicate key 'Damage'</c>；
    /// 这个异常发生在 <c>CardModel.DynamicVars</c> 构造时（创建卡牌就炸），
    /// 会把整场战斗的回合循环打断 —— 表现就是「抽不了牌、结束不了回合」。
    /// 用户实测踩过：起始遗物开战生成「刀」，而「刀」有两张 DamageVar。
    ///
    /// 规则：同一种变量第二次出现起叫 <c>Damage2</c> / <c>Block2</c> / <c>PoisonPower2</c> …，
    /// 生成代码里的声明、取值、升级、描述占位符都用这个名字。
    /// </summary>
    internal static Dictionary<EffectSpec, string> VarNamesOf(IEnumerable<EffectSpec> effects)
    {
        var seen = new Dictionary<string, int>(StringComparer.Ordinal);
        var map = new Dictionary<EffectSpec, string>();
        foreach (var e in effects)
        {
            if (HasNoDynamicVar(e)) continue;
            string baseName = VarNameOf(e);
            int n = seen.TryGetValue(baseName, out int c) ? c + 1 : 1;
            seen[baseName] = n;
            map[e] = n == 1 ? baseName : baseName + n.ToString(System.Globalization.CultureInfo.InvariantCulture);
        }
        return map;
    }

    /// <summary>某个效果在它所属模型里的变量名（没登记就退回默认名）。</summary>
    public static string VarNameOf(EffectSpec e, Dictionary<EffectSpec, string>? map) =>
        map is not null && map.TryGetValue(e, out string? name) ? name : VarNameOf(e);

    /// <summary>
    /// 这个模型的动态变量「基础名」清单（用来校验有没有同种变量出现多次）。
    /// 本体 DynamicVarSet 用变量名当键，重名会直接抛异常 → 整场战斗的回合循环死掉
    /// （表现：抽不了牌、结束不了回合 —— 用户实测踩过）。生成时会自动给第二个起别名。
    /// </summary>
    public static IReadOnlyList<string> VarKeysOf(IEnumerable<EffectSpec> effects) =>
        effects.Where(e => !HasNoDynamicVar(e)).Select(VarNameOf).ToList();

    internal static string VarAccess(EffectSpec e, Dictionary<EffectSpec, string>? map = null)
    {
        string name = VarNameOf(e, map);
        // 只有本体确实有同名属性的变量才能用属性写法（Damage / Block / Cards / Energy / Stars）；
        // 起了别名（Damage2 这种）或只有索引器的（Power / PetHp / PetDamage）一律用 ["名字"]。
        // PetHp / PetDamage 是**我们自己起的名字**，本体 DynamicVars 上当然没有这两个属性 → 必须走索引器。
        bool hasProperty = e.Kind is "Damage" or "Block" or "Draw" or "Energy" or "ExtraResource";
        return hasProperty && name == VarPropertyOf(e)
            ? $"base.DynamicVars.{VarPropertyOf(e)}.BaseValue"
            : $"base.DynamicVars[{Lit.Str(name)}].BaseValue";
    }

    /// <summary>X 费用卡牌里 X 的变量名（在 OnPlay 开头取一次）。</summary>
    internal const string XVar = "x";

    /// <summary>取数值：X 费用卡牌上「数值 = X」就用 X，否则用固定数值。</summary>
    internal static string AmountExpr(EffectSpec e, bool useX, Dictionary<EffectSpec, string>? map = null) =>
        useX && e.AmountIsX ? XVar : VarAccess(e, map);

    /// <summary>取命中次数 / 对群数：X 费用卡牌上可以填 X（本体旋风斩 / 天际钻头）。</summary>
    internal static string RepeatExpr(EffectSpec e, bool useX) =>
        useX && e.RepeatIsX ? XVar : Math.Max(1, e.RepeatCount).ToString();

    /// <summary>
    /// 格挡数值。统一用 decimal 那条重载（BlockVar 重载内部也只是转发 BaseValue + Props），
    /// 这样起了别名的变量（Block2）也能直接用 —— 索引器返回的是 DynamicVar，转不成 BlockVar。
    /// </summary>
    internal static string BlockValueAccess(Dictionary<EffectSpec, string>? map = null, EffectSpec? e = null)
    {
        if (e is null) return "base.DynamicVars.Block.BaseValue";
        return VarAccess(e, map);
    }

    internal static string VarDeclaration(EffectSpec e, Dictionary<EffectSpec, string>? map = null)
    {
        string name = VarNameOf(e, map);
        bool named = name != VarNameOf(e);
        string prefix = named ? Lit.Str(name) + ", " : "";
        return e.Kind switch
        {
            "Damage" => $"new DamageVar({prefix}{Lit.Dec(e.Amount)}, ValueProp.Move)",
            "Block" => $"new BlockVar({prefix}{Lit.Dec(e.Amount)}, ValueProp.Move)",
            "Draw" => $"new CardsVar({prefix}{Lit.Int(e.Amount)})",
            "Energy" => $"new EnergyVar({prefix}{Lit.Int(e.Amount)})",
            // 透支能量：同样用 EnergyVar（数值 = 透支的点数；升级增量 / 别名都照常）
            "OverdraftEnergy" => $"new EnergyVar({prefix}{Lit.Int(e.Amount)})",
            "Heal" => $"new HealVar({prefix}{Lit.Dec(e.Amount)})",
            "HpLoss" => $"new HpLossVar({prefix}{Lit.Dec(e.Amount)})",
            "MaxHp" => $"new MaxHpVar({prefix}{Lit.Dec(e.Amount)})",
            "Gold" => $"new GoldVar({prefix}{Lit.Int(e.Amount)})",
            // 额外资源量：用本体的 StarsVar，这样卡面描述 {Stars:diff()} 会随升级变（用户报过「升级后还显示 2」）
            "ExtraResource" => $"new StarsVar({prefix}{Lit.Int(e.Amount)})",
            "ApplyPower" => $"new PowerVar<{e.PowerId}>({prefix}{Lit.Dec(e.Amount)})",
            // 召唤伙伴：本体没有「宠物生命 / 宠物伤害」这两种变量类型，用带名字的普通 DynamicVar
            // （名字是 PetHp / PetDamage，卡面描述里的 {…:diff()} 与升级增量都按它走）
            "SummonPet" => $"new DynamicVar({Lit.Str(name)}, {Lit.Dec(e.Amount)})",
            "PetAttack" => $"new DynamicVar({Lit.Str(name)}, {Lit.Dec(e.Amount)})",
            // ===== 新增的那批宠物效果 =====
            // 「按生命值算的伙伴攻击」：必须用本体的**计算三件套**（见 CalcDamageVars），
            // 缺任何一件都会在 CalculatedVar.GetExtraVar() 处抛 KeyNotFoundException。
            "PetDamageByMaxHp" => CalcDamageVars(PetHpExpr("MaxHp")),
            "PetDamageByCurHp" => CalcDamageVars(PetHpExpr("CurrentHp")),
            "PetDamageByMissingHp" => CalcDamageVars(PetHpExpr("MissingHp")),
            "PetHeal" => $"new HealVar({prefix}{Lit.Dec(e.Amount)})",
            "PetLoseHp" => $"new HpLossVar({prefix}{Lit.Dec(e.Amount)})",
            "PetGainMaxHp" => $"new MaxHpVar({prefix}{Lit.Dec(e.Amount)})",
            "PetSacrifice" => PetSacrificeVarDecl(e, name),
            // 给伙伴施加状态：和普通「施加增益/减益」同名会撞（DynamicVarSet 按名字去重，重名直接抛异常），
            // 所以这里的变量名是 PetPower<PowerId>（回读也按这个名字把数值配回去）。
            "PetApplyPower" => $"new PowerVar<{e.PowerId}>({Lit.Str(name)}, {Lit.Dec(e.Amount)})",
            // 兜底：不认识的种类也用**唯一别名**（不能写死 "Value"，否则两条这种效果就会撞名 →
            // 本体 DynamicVarSet 抛 duplicate key 'Value' → 开新局直接崩（黑屏））
            _ => $"new DynamicVar({Lit.Str(name)}, {Lit.Dec(e.Amount)})",
        };
    }

    // ==================== 宠物效果（新增的那批）的动态变量 ====================

    /// <summary>
    /// 「伙伴的生命值」在**倍率 lambda 里**的写法（lambda 的第二参数就是那只宠物）。
    ///
    /// 为什么用 <c>pet</c> 这个名字：生成出来的 lambda 形如
    /// <c>delegate(CardModel card, Creature? _) { Creature? pet = &lt;Pet&gt;Cmd.Get(card.Owner); return (pet != null) ? pet.MaxHp : 0; }</c>，
    /// 三处（最大生命 / 当前生命 / 已损失）只有最后那个 <c>return</c> 表达式不同 —— 回读时也是按它区分三种 Kind。
    /// </summary>
    internal static string PetHpExpr(string mode) => mode switch
    {
        "CurrentHp" => "(decimal)pet.CurrentHp",
        "MissingHp" => "(decimal)(pet.MaxHp - pet.CurrentHp)",
        _ => "(decimal)pet.MaxHp",
    };

    /// <summary>三个「按生命值算的伙伴攻击」用的计算三件套：CalculationBase + ExtraDamage + CalculatedDamage。</summary>
    internal static string CalcDamageVars(string petValueExpr) =>
        "new CalculationBaseVar(0m), new ExtraDamageVar(1m), "
        + "new CalculatedDamageVar(ValueProp.Move).WithMultiplier(" + PetMultiplierLambda(petValueExpr) + ")";

    /// <summary>牺牲伙伴按生命值算格挡时的计算三件套：CalculationBase + CalculationExtra + CalculatedBlock。</summary>
    internal static string CalcBlockVars(string petValueExpr) =>
        "new CalculationBaseVar(0m), new CalculationExtraVar(1m), "
        + "new CalculatedBlockVar(ValueProp.Move).WithMultiplier(" + PetMultiplierLambda(petValueExpr) + ")";

    /// <summary>
    /// 倍率 lambda。**必须是静态的**：本体 <c>CalculatedVar.cs:50-53</c> 一发现
    /// <c>multiplierCalc.Target is AbstractModel</c> 就抛 <c>InvalidOperationException("Multiplier calc must be static!")</c>；
    /// 写成匿名方法 <c>delegate(CardModel card, Creature? _)</c> 就不会捕获实例（<c>this</c>）→ Target 是 null。
    /// 里面只用参数 <paramref name="petValueExpr"/> 里的 <c>card</c>（那只宠物用 <c>&lt;Pet&gt;Cmd.Get(card.Owner)</c> 查），
    /// **绝不能**捕获任何局部变量 / 字段。
    /// </summary>
    internal static string PetMultiplierLambda(string petValueExpr) =>
        "delegate(CardModel card, Creature? _) { "
        + "Creature? pet = " + PetCmdExpr + ".Get(card.Owner); "
        + "return (pet != null) ? " + petValueExpr + " : 0; }";

    /// <summary>
    /// 倍率 lambda 里的宠物类名占位。写进 CanonicalVars 那一刻并不知道是哪只，
    /// 所以先写占位符，最后用 <see cref="PatchPetPlaceholder"/> 按**这条效果自己的**召唤物替换
    /// （一张牌可以指多只宠物，所以必须逐条替换，不能全文替换）。
    /// </summary>
    internal const string PetCmdPlaceholder = "__PETCMD__";

    private const string PetCmdExpr = PetCmdPlaceholder;

    /// <summary>把占位符换成真正的那只宠物的命令助手（<c>&lt;Pet&gt;Cmd</c>）。</summary>
    internal static string PatchPetPlaceholder(string code, string? petClassName)
    {
        if (!code.Contains(PetCmdPlaceholder, StringComparison.Ordinal)) return code;
        string cmd = string.IsNullOrWhiteSpace(petClassName) ? "" : petClassName.Trim() + "Cmd";
        return code.Replace(PetCmdPlaceholder, cmd.Length == 0 ? "PetCmd" : cmd);
    }

    /// <summary>牺牲伙伴的收益变量：固定值走普通 BlockVar / DamageVar，按生命值算走计算三件套。</summary>
    private static string PetSacrificeVarDecl(EffectSpec e, string name)
    {
        bool block = e.PetSacrificeGain != "Damage";
        if (e.PetSacrificeFormula == "Fixed")
            return block
                ? $"new BlockVar({Lit.Str(name)}, {Lit.Dec(e.Amount)}, ValueProp.Move)"
                : $"new DamageVar({Lit.Str(name)}, {Lit.Dec(e.Amount)}, ValueProp.Move)";
        string petExpr = e.PetSacrificeFormula == "CurHp"
            ? PetHpExpr("CurrentHp")
            : "(decimal)pet.MaxHp * " + Lit.Dec(e.PetSacrificeMultiplier);
        return block ? CalcBlockVars(petExpr) : CalcDamageVars(petExpr);
    }

    /// <summary>
    /// 这条效果「按生命值算收益」时用的是哪一套计算变量 —— 固定值返回 null。
    /// 生成时写进注释标记（<c>// CET:PetFormula=…</c>），回读时照着认回来，
    /// 不用去猜 lambda 里的表达式（宠物类名 / 公式都能认，宠物死了也照样认得出）。
    /// </summary>
    public static string? PetFormula(EffectSpec e)    {
        if (e.Kind is "PetDamageByMaxHp" or "PetDamageByCurHp" or "PetDamageByMissingHp")
            return PetFormulaOfKind(e.Kind);
        if (e.Kind != "PetSacrifice") return null;
        return e.PetSacrificeFormula switch
        {
            "Fixed" => "fixed",
            "CurHp" => "curhp",
            _ => "maxhp",
        };
    }

    private static string PetFormulaOfKind(string kind) => kind switch
    {
        "PetDamageByCurHp" => "curhp",
        "PetDamageByMissingHp" => "missinghp",
        _ => "maxhp",
    };

    /// <summary>
    /// 这条效果的生成代码标记（回读用）。写在这条效果的**第一行**上（单行，回读好抓）。
    ///
    /// 为什么要标记：三个「按生命值算的伙伴攻击」的生成代码几乎一模一样（只有倍率 lambda 里
    /// <c>pet.MaxHp</c> / <c>pet.CurrentHp</c> / <c>pet.MaxHp - pet.CurrentHp</c> 不同），
    /// 「牺牲伙伴」的收益公式（固定 / 最大生命×倍率 / 当前生命）也藏在 CanonicalVars 里 ——
    /// 回读时**不同步改就会静默丢配置**（本项目最容易踩的坑），所以生成时直接把这些信息写进注释。
    /// </summary>
    public static string MarkerText(EffectSpec e)
    {        string? formula = PetFormula(e);
        string kind = KindMarker(e);
        if (formula is null)
            // 给伙伴施加状态：把 PowerId 也写进标记（回读时不用去猜 Apply<T> 里的 T；
            // 下回合生效时会写成 ForgeDelayed<T>，也只认我们标记里的这个）
            return e.Kind == "PetApplyPower" && !string.IsNullOrWhiteSpace(e.PowerId)
                ? $"{kind} CET:PetPower={e.PowerId!.Trim()}"
                : kind;
        string mul = e.Kind == "PetSacrifice" && e.PetSacrificeFormula == "MaxHp"
            ? " CET:PetMul=" + Lit.Dec(e.PetSacrificeMultiplier)
            : "";
        return $"{kind} CET:PetFormula={formula}{mul}";
    }

    /// <summary>回读用的效果种类标记名（几种变体各自一个，回读时一对一还原）。</summary>
    internal static string KindMarker(EffectSpec e) => e.Kind switch
    {
        "PetDamageByMaxHp" or "PetDamageByCurHp" or "PetDamageByMissingHp" => "PetCalcAttack",
        "PetSacrifice" => e.PetSacrificeGain == "Damage" ? "PetSacrificeDamage" : "PetSacrificeBlock",
        _ => e.Kind,
    };

    /// <summary>把这些效果里「按生命值算收益」的那条找出来（一张牌最多一条：本体的计算变量名是固定的）。</summary>
    internal static EffectSpec? CalculatedPetEffect(IEnumerable<EffectSpec> effects) =>
        effects.FirstOrDefault(x => PetFormula(x) is not null);

    /// <summary>这个效果的 CanonicalVars 声明里会不会出现宠物命令（&lt;Pet&gt;Cmd）—— 只有「按生命值算」的那几种会。</summary>
    /// <remarks>
    /// <c>"fixed"</c>（牺牲伙伴选「固定 N」）**不算**：那种收益声明的是普通 BlockVar / DamageVar
    /// （<c>new BlockVar("PetSacrificeBlock", 6m, …)</c>），既没有宠物命令、也**没有 CalculationBase** ——
    /// 把它算成「按生命值算」会让升级增量被写到 <c>base.DynamicVars.CalculationBase.UpgradeValueBy(…)</c> 上，
    /// 而那个变量根本没声明 → 本体的 DynamicVars 按名字取 → 抛 KeyNotFoundException。
    /// 这个异常发生在「卡牌被升级 / 牌组界面预览升级」时，表现是**牌组界面一片空白打不开**
    /// （用户实测报过：牺牲伙伴固定伤害 + 升级增量的卡，一开牌组就看不到牌）。
    /// </remarks>
    internal static bool CanonicalVarNeedsPetCmd(EffectSpec e) => PetFormula(e) is not null and not "fixed";

    /// <summary>
    /// 这条效果「需要**已经召唤出来**的那只宠物」：宠物不在场时它整条跳过（生成 <c>if (__pet is not null)</c>），
    /// 而且整张牌跟着打不出去 / 描红框。
    ///
    /// <c>SummonPet</c> **不算** —— 它自己就会召（没有也能打，Summon 内部新建一只）。
    /// </summary>
    internal static bool NeedsExistingPet(EffectSpec e) =>
        e.Kind is "PetAttack"
            or "PetDamageByMaxHp" or "PetDamageByCurHp" or "PetDamageByMissingHp"
            or "PetHeal" or "PetLoseHp" or "PetGainMaxHp" or "PetSacrifice" or "PetApplyPower"
            or "PetGuardOn" or "PetGuardOff";

    /// <summary>
    /// 把「对某个生物做一件事」按作用对象展开（格挡 / 回复生命 / 失去生命 / 最大生命 现在支持打敌人）。
    /// Self = 自己；Enemy = 这张牌指定的目标（遗物/药水没有目标时退回「可打的第一个敌人」）；
    /// AllEnemies = 所有可打的敌人；RandomEnemies = 随机 N 个（N 可以 = X）。
    /// </summary>
    private static void EmitPerCreature(CodeWriter w, EffectSpec e, bool useX,
        string selfExpr, string? cardTargetExpr, string enemiesExpr, Func<string, string> body)
    {
        switch (e.TargetSide)
        {
            case "AllEnemies":
                w.Open($"foreach (Creature foe in {enemiesExpr})");
                w.Line(body("foe"));
                w.Close();
                break;

            case "RandomEnemies":
                w.Line($"List<Creature> foes = {enemiesExpr}.ToList();")
                 // 循环变量用 __ 前缀：外面可能还套着「生效次数」的 for (int i…)，同名会 CS0136
                 .Open($"for (int __foeIdx = 0; __foeIdx < {RepeatExpr(e, useX)} && foes.Count > 0; __foeIdx++)")
                 .Line("Creature foe = base.Owner.RunState.Rng.CombatTargets.NextItem(foes);");
                if (!e.AllowDuplicates) w.Line("foes.Remove(foe);");
                w.Line(body("foe"));
                w.Close();
                break;

            case "Enemy" when cardTargetExpr is not null:
                // 卡牌：用玩家选中的那个目标；没选（不该发生）就什么都不做
                w.Open($"if ({cardTargetExpr} is not null)")
                 .Line(body(cardTargetExpr))
                 .Close();
                break;

            case "Enemy":
                // 遗物 / 药水：没有「玩家选的目标」，取可打的第一个敌人
                w.Open("")
                 .Line($"Creature? foe = {enemiesExpr}.FirstOrDefault();")
                 .Open("if (foe is not null)")
                 .Line(body("foe"))
                 .Close()
                 .Close();
                break;

            default:
                w.Line(body(selfExpr));
                break;
        }
    }

    /// <summary>
    /// 这套「伙伴攻击」打的是**敌人**（attacker 是宠物），所以卡牌要变成需要选目标的那种。
    /// 三个按生命值算的伙伴攻击同样如此（Targeting(cardPlay.Target) / TargetingAllOpponents）。
    /// </summary>
    internal static bool PetAttackKind(string kind) =>
        kind is "PetAttack" or "PetDamageByMaxHp" or "PetDamageByCurHp" or "PetDamageByMissingHp";

    private static bool NeedsTargetNullCheck(CardSpec c) =>
        c.Effects.Any(e => e.TargetSide == "Enemy"
            && (e.Kind is "Damage" or "ApplyPower" or "Block" or "Heal" or "HpLoss" or "MaxHp"
                || PetAttackKind(e.Kind)
                || (e.Kind == "PetSacrifice" && e.PetSacrificeGain == "Damage")));

    // ==================== 卡牌 ====================
    /// <summary>
    /// 一张卡的 C# 源码。
    /// <paramref name="index"/> 只用于「按列表下标」的老式编号，**不要**用它算类名 ——
    /// 初始的打击 / 防御固定排在列表最前面，列表下标和「自有卡序号」会差 2
    /// （用户报过：没填类名的卡，文件叫 SevenCard9.cs 里却声明成 SevenCard11，
    ///  卡池引用的 SevenCard9 找不到 → 编译报 CS0246）。统一走
    /// <see cref="Naming.CardClassName(CharacterProfile, CardSpec)"/>，和文件名 / 卡池 / 本地化一致。
    /// </summary>
    public static string CardSource(CharacterProfile p, CardSpec c, int index)
    {
        _ = index;
        var n = Naming.From(p);
        string cls = n.CardClassName(p, c);
        string targetType = ResolveTargetType(c);

        var w = new CodeWriter();
        w.Line("// <auto-generated> 自定义卡牌 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public sealed class {cls} : CardModel")
         .Line("protected override IEnumerable<DynamicVar> CanonicalVars =>")
         .Line("[");
        var cardVars = VarNamesOf(c.Effects);
        // 「按生命值算」的宠物效果：倍率 lambda 里要写 <Pet>Cmd.Get(card.Owner)，但 CanonicalVars
        // 声明那一刻还不知道是哪只（一张牌可以同时指向两只不同的宠物）→ 先写占位符，
        // 这里按**每条效果自己的**召唤物逐个替换（不能全文替换，否则多只宠物会串）。
        bool needsPetCmd = c.Effects.Any(x => !HasNoDynamicVar(x) && CanonicalVarNeedsPetCmd(x));
        bool anyPetCmdMissing = false;
        foreach (var e in c.Effects.Where(x => !HasNoDynamicVar(x)))
        {
            string decl = VarDeclaration(e, cardVars);
            if (decl.Contains(PetCmdPlaceholder, StringComparison.Ordinal))
            {
                string? petCls = PetGen.Resolve(p, e.PetSummon)?.ClassName;
                anyPetCmdMissing |= petCls is null;
                decl = PatchPetPlaceholder(decl, petCls);
            }
            w.Line($"    {decl},");
        }
        w.Line("];");
        if (needsPetCmd && anyPetCmdMissing)
            w.Line("// ⚠ 上面这条「按生命值算」的宠物效果没有可用的召唤物：到「召唤物」页添加一只并勾上「启用」"
                + "（校验器会把这种配置拦住，不会真的生成出来）");

        // 本体卡标签（CardTag）：行为无关的元数据，别的模型拿它查牌。
        // 最关键的就是 Strike / Defend —— 本体那些「升级你的初始打击 / 防御」「只对打击牌生效」的
        // 遗物 / 事件 / 卡牌都是按 CardTag 找牌的（妮欧的护符 NeowsTalisman、叶敷剂 LeafyPoultice、
        // 大胶囊 LargeCapsule、幽灵种子 GhostSeed、完美打击 PerfectedStrike…），不标它们就找不到你的牌。
        if (c.TagList.Count > 0)
        {
            w.Line()
             .Line("// 本体卡标签（CardTag）：别的模型按它查牌（例：升级初始打击 / 防御的遗物）")
             .Line($"protected override HashSet<CardTag> CanonicalTags => new HashSet<CardTag> {{ {string.Join(", ", c.TagList.Select(t => "CardTag." + t))} }};");
        }
        // 本体的「防御」牌都有这个（本体用它判断挡格相关的表现）
        if (c.TagList.Contains("Defend"))
            w.Line("public override bool GainsBlock => true;");

        // 卡牌关键字：消耗 / 虚无 / 固有 / 保留 / 不能被打出 / 奇巧
        var keywords = c.KeywordList;
        if (keywords.Count > 0)
        {
            string kw = string.Join(", ", keywords.Select(k => "CardKeyword." + k));
            w.Line()
             .Line("// 卡牌关键字（本体 CardKeyword）")
             .Line($"public override IEnumerable<CardKeyword> CanonicalKeywords => [{kw}];");
        }

        // X 费用（本体储君「天际钻头」/ 亡灵契约师「挽歌」这种）：本体用 HasEnergyCostX 表示，
        // 构造函数里费用写 0，实际消耗由本体结算，X 值用 ResolveEnergyXValue() 取。
        bool usesX = c.Effects.Any(e => e.UsesX);
        bool xIsStar = c.StarCostIsX && !c.CostIsX;
        if (c.CostIsX || c.StarCostIsX || usesX)
        {
            w.Line();
            if (c.CostIsX)
                w.Line("// 费用为 X：打出时消耗全部能量，X = 消耗掉的能量（本体 Whirlwind / 天际钻头 的做法）")
                 .Line("protected override bool HasEnergyCostX => true;");
            if (c.StarCostIsX)
                w.Line("// 额外资源量费用为 X：打出时消耗全部额外资源量，X = 消耗掉的资源量（本体 Stardust 的做法）")
                 .Line("public override bool HasStarCostX => true;");
        }

        // 额外资源量花费：负数效果 = 打出这张牌需要的额外资源量。
        // 直接复用本体的星星费用机制，本体就会在资源不足时禁止打出
        // （UnplayableReason.StarCostTooHigh），并把卡面费用数字显示成红色。
        int starCost = StarCostOf(c);
        if (starCost > 0 && !c.StarCostIsX)
        {
            w.Line()
             .Line("// 额外资源量花费（本体星星费用：不够时本体自带判定禁止打出）")
             .Line($"public override int CanonicalStarCost => {starCost};");
        }

        // 条件选项（每一条效果各自一份）：
        // 「不满足时打不出去」→ 汇进本体 IsPlayable（Clash / GrandFinale 的做法），这些条件全都满足才能打；
        // 「能打出但这条效果不生效」→ 只把这一条效果包在 if 里，别的效果照常执行。
        // 老存档用的是「整张牌一个条件」（c.Condition），也一起算进来（只能有一个 IsPlayable，所以必须合并写）。
        var gateConds = new List<string>();
        var glowConds = new List<string>();
        // 宠物类效果：一张卡只要有「需要已召唤宠物」的效果（SummonPet 不算 —— 它自己会召），
        // 就生成两句守卫：没伙伴时这张牌打不出去 + 描红框提示（本体 Osty 的牌就是这么做的：
        // BoneShards / Poke / Sacrifice … 全是 ShouldGlowRedInternal => base.Owner.IsOstyMissing）。
        // 这里的「有没有伙伴」= <Pet>Cmd.Get(base.Owner) != null（Get 会判活，死了也算没有）。
        var petNeeds = new List<string>();
        foreach (var e in c.Effects)
        {
            if (!NeedsExistingPet(e)) continue;
            var defs = PetGen.ResolveMany(p, e.PetSummon);
            if (defs.Count == 0) continue;   // 校验器会拦住（找不到召唤物），这里不生成取不到的类名
            // 「全部召唤物」：只要**任意一只**在场，这张牌就能打（每只各自再判一次在场，见逐只展开那里）
            string need = defs.Count == 1
                ? $"{defs[0].ClassName}Cmd.Get(base.Owner) != null"
                : "(" + string.Join(" || ", defs.Select(d => $"{d.ClassName}Cmd.Get(base.Owner) != null")) + ")";
            if (!petNeeds.Contains(need, StringComparer.Ordinal)) petNeeds.Add(need);
        }
        // 条件都用「满足才算数」的写法（c.Condition 生成出来的就是「满足」表达式），
        // 所以伙伴守卫也用 != null，一起 && 起来即可：没伙伴 → 打不出去 / 描红框。
        gateConds.AddRange(petNeeds);
        glowConds.AddRange(petNeeds);
        // 「指定敌人」这种条件要等玩家选了目标才知道结果，写不进 IsPlayable / 描金边（那时还没选目标）。
        // 这类条件只在效果那一层生效（包住对应的效果）。
        static bool NeedsPlayTarget(ConditionSpec? c) =>
            c is not null && c.NeedsTarget && string.Equals(c.Target, "Enemy", StringComparison.OrdinalIgnoreCase);
        if (c.Condition is not null && !c.Condition.IsNone)
        {
            string legacy = ConditionExpr(c.Condition, CondCtx.Card);
            if (NeedsPlayTarget(c.Condition))
                w.Line($"// 条件：{ConditionText(c.Condition)}（作用对象是「指定敌人」→ 只能用在效果上，打不出判定/描金边里忽略）");
            else
            {
                glowConds.Add(legacy);
                if (c.Condition.UnplayableWhenUnmet) gateConds.Add(legacy);
                w.Line($"// 条件：{ConditionText(c.Condition)}（老存档的「整张牌」条件；"
                     + (c.Condition.UnplayableWhenUnmet ? "不满足时这张牌打不出去）" : "不满足时整张牌的效果都不生效）"));
            }
        }
        foreach (var e in c.Effects)
        {
            if (e.Condition is null || e.Condition.IsNone) continue;
            bool needsPlayTarget = NeedsPlayTarget(e.Condition);
            string expr = ConditionExpr(e.Condition, CondCtx.Card, inOnPlay: true);
            if (!needsPlayTarget)
            {
                glowConds.Add(ConditionExpr(e.Condition, CondCtx.Card));
                if (e.Condition.UnplayableWhenUnmet) gateConds.Add(ConditionExpr(e.Condition, CondCtx.Card));
            }
            w.Line($"// 条件（只对「{EffectCatalog.FindKind(e.Kind).Display}」这条效果）：{ConditionText(e.Condition)}"
                 + (needsPlayTarget
                        ? " → 打出的目标满足才算（写不进「打不出去」，只能包住这条效果）"
                        : e.Condition.UnplayableWhenUnmet ? " → 不满足时这张牌打不出去" : " → 不满足时这条效果不生效"));
        }
        if (glowConds.Count > 0)
        {
            if (gateConds.Count > 0)
                w.Line($"protected override bool IsPlayable => {string.Join(" && ", gateConds.Select(x => $"({x})"))};");
            // 条件都满足时给牌描金边（本体「取回 / 死亡之门」就是这么提示玩家的）
            w.Line($"protected override bool ShouldGlowGoldInternal => {string.Join(" && ", glowConds.Select(x => $"({x})"))};");
        }
        // 缺伙伴时描红框提示（本体的 Osty 牌全是这个写法：base.Owner.IsOstyMissing）
        if (petNeeds.Count > 0)
            w.Line($"protected override bool ShouldGlowRedInternal => {string.Join(" || ", petNeeds.Select(x => $"!({x})"))};");

        // 鼠标悬停卡面描述里的状态 → 弹出本体 powers 表里那条说明（本体状态改写后就是新的名字 + 新的描述）
        // 自定义关键词也走这一段（文本来自我们写进本体 card_keywords 表的键）
        w.Raw(HoverTipsOverride(c.Effects, isPublic: false, isCard: true,
            extraTips: KeywordGen.TipsFor(p, c.CustomKeywordList), owner: p));

        w.Line()
         .Line($"public {cls}() : base({(c.CostIsX ? 0 : c.Cost)}, CardType.{c.CardType}, CardRarity.{c.Rarity}, TargetType.{targetType}) {{ }}")
         .Line()
         .Open("protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)");

        // X 值：整张牌里只取一次，后面的效果都用这个变量
        if (usesX)
        {
            if (c.CostIsX || xIsStar)
            {
                string call = xIsStar ? "ResolveStarXValue()" : "ResolveEnergyXValue()";
                string plus = c.XPlusOnUpgrade ? " + (base.IsUpgraded ? 1 : 0)" : "";
                w.Line($"// X = {(xIsStar ? "打出时消耗掉的额外资源量" : "打出时消耗掉的能量")}{(c.XPlusOnUpgrade ? "（升级后 X + 1）" : "")}");
                w.Line($"int x = {call}{plus};");
            }
            else
            {
                w.Line("// 这张牌的费用不是 X，所以 X 按 0 处理（界面上会给出警告）");
                w.Line("int x = 0;");
            }
            w.Line();
        }

        if (NeedsTargetNullCheck(c))
        {
            w.Line("ArgumentNullException.ThrowIfNull(cardPlay.Target, \"cardPlay.Target\");");
            w.Line();
        }
        // 「能打出但效果不生效」：老存档的整张牌条件不满足时整段效果都跳过
        bool wrapEffects = c.Condition is not null && !c.Condition.IsNone && !c.Condition.UnplayableWhenUnmet;
        if (wrapEffects)
        {
            w.Open($"if ({ConditionExpr(c.Condition, CondCtx.Card)})");
        }
        // 召唤 / 伙伴攻击要「先找到宠物」：找到一次，整张牌后面的召唤、伙伴攻击都用这个变量。
        // 为什么要守卫：宠物不在场（没召唤 / 已经死了）时，伙伴攻击不该让整张牌报错 ——
        // 攻击者不存在的话 AttackCommand 直接抛 InvalidOperationException。
        // 现在是**列表**：一张牌的效果可以分别指向不同的召唤物，所以按「这张牌用到的每一只」各查一次，
        // 变量名按宠物类名取（__<宠物类名首字母小写>）。
        // 注意：只有「需要已经召唤出来的那只」的效果才需要这个变量（见 NeedsExistingPet）；
        // 纯召唤牌不声明它（否则生成代码里会留一个没用到的局部变量，白挨一条编译警告）。
        var petLookup = new Dictionary<string, string>(StringComparer.Ordinal);      // 宠物类名 → 局部变量名
        foreach (var e in c.Effects.Where(NeedsExistingPet))
        {
            // 「全部召唤物」会把这张牌用到的**每一只**都查一遍（各占一个 __xxx 变量）
            foreach (var d in PetGen.ResolveMany(p, e.PetSummon))
                if (!petLookup.ContainsKey(d.ClassName)) petLookup[d.ClassName] = PetAttackVarName(d.ClassName);
        }
        bool hasPetAction = c.Effects.Any(e => e.PetAction);
        if (hasPetAction)
        {
            w.Line();
            w.Open("if (base.Owner.PlayerCombatState is not null)");
            if (petLookup.Count > 0)
            {
                w.Line("// 宠物可能还没召唤（或上一场战斗结束时被本体清掉了）：每只先找一次，后面所有伙伴攻击都用它");
                foreach (var kv in petLookup)
                    w.Line($"Creature? {kv.Value} = {kv.Key}Cmd.Get(base.Owner);");
            }
            else
            {
                w.Line("// 召唤伙伴：不需要先查宠物 —— Summon 内部会自己找（活着就加血、没有就新召一只）");
            }
        }
        // 每条效果各自的条件：不满足只跳过这一条（WrapInIf 里的效果本身不能带条件）
        // 概率生效：整张牌所有勾了概率的效果**共用一次掷骰**（合并概率，用户要求）
        var cardChanceSlices = ChanceSlices(c.Effects);
        if (cardChanceSlices.Count > 0) w.Line(ChanceRollLine());
        int petAllGroup = 0;
        foreach (var e in c.Effects)
        {
            string? cond = EffectConditionGuard(e, CondCtx.Card, inOnPlay: true, chanceSlices: cardChanceSlices);
            bool hasGuard = cond is not null;

            // 「全部召唤物」（PetGen.AllId）：按**已启用的那几只**逐只展开成多份代码（生成时就定死，
            // 不是运行时遍历）—— 每只自己判在场，不在场的那只整段跳过。
            // 展开出来的每一份都会写一行「// CET:PetAll=<组号>」，回读时靠它把多份合并回一条「全部召唤物」。
            if (PetGen.IsAll(e.PetSummon) && EffectCatalog.IsPetKind(e.Kind))
            {
                var allDefs = PetGen.ResolveMany(p, e.PetSummon);
                if (hasGuard) w.Open(cond!);
                if (allDefs.Count == 0)
                {
                    // 兜底：校验器会把「一只都没启用」拦住，这里只保证万一跑到了也生成得出能编译的代码
                    EmitCardEffect(w, p, e, usesX, cardVars, null);
                }
                else
                {
                    w.Line($"// 【全部召唤物】这一条对 {allDefs.Count} 只各来一遍："
                        + string.Join("、", allDefs.Select(d => d.DisplayName)) + "（不在场的那只自动跳过）");
                    string group = "g" + petAllGroup++;
                    foreach (var d in allDefs)
                    {
                        w.Line($"// CET:PetAll={group}");
                        bool needPet = NeedsExistingPet(e);
                        string pv = petLookup.GetValueOrDefault(d.ClassName) ?? PetAttackVarName(d.ClassName);
                        if (needPet) w.Open($"if ({pv} is not null)");
                        EmitCardEffect(w, p, e, usesX, cardVars, needPet ? pv : null, d);
                        if (needPet) w.Close();
                    }
                }
                if (hasGuard) w.Close();
                continue;
            }

            string? petVar = NeedsExistingPet(e) && PetGen.Resolve(p, e.PetSummon) is { } pd
                ? petLookup.GetValueOrDefault(pd.ClassName)
                : null;
            bool petGuard = petVar is not null;
            if (hasGuard || petGuard)
            {
                // 外层是效果自己的条件、内层是「宠物在不在场」；两者都要满足才执行这条
                if (hasGuard) w.Open(cond!);
                if (petGuard) w.Open($"if ({petVar} is not null)");
            }
            EmitCardEffect(w, p, e, usesX, cardVars, petVar);
            if (petGuard) w.Close();
            if (hasGuard) w.Close();
        }
        // 关闭最外层的「PlayerCombatState 不为 null」守卫 —— 只要这张牌有召唤/伙伴攻击就开过它
        // （注意：不能用 petLookup 判断 —— 纯召唤牌不开宠物查询变量，但守卫一样要关，否则生成的代码缺一个 }）
        if (hasPetAction) w.Close();
        if (wrapEffects) w.Close();
        w.Close();

        var upgradeable = c.Effects.Where(e => e.UpgradeAmount != 0 && !HasNoDynamicVar(e)).ToList();
        int? targetCost = c.UpgradeCost;
        bool costChange = targetCost is not null && targetCost.Value != c.Cost && !c.CostIsX;
        var kwAdd = c.UpgradeKeywords?.Added ?? (IReadOnlyList<string>)Array.Empty<string>();
        var kwDel = c.UpgradeKeywords?.Removed ?? (IReadOnlyList<string>)Array.Empty<string>();
        if (upgradeable.Count > 0 || costChange || kwAdd.Count > 0 || kwDel.Count > 0)
        {
            w.Line()
             .Open("protected override void OnUpgrade()");
            // 「按生命值算」的宠物效果（三个伙伴攻击 / 牺牲伙伴）的升级增量要写到 **CalculationBase** 上：
            // 它们的 CanonicalVars 里那个 CalculatedDamage/CalculatedBlock 是**固定名字**的（本体的
            // DynamicVars.CalculatedDamage 是按名字取的），升级只能抬 CalculationBase（框架会自动重算预览）。
            // 一张牌最多一条这种效果（校验器会拦住第二条），但求稳还是把增量**累加**起来写一次。
            decimal calcBaseDelta = 0m;
            foreach (var e in upgradeable)
            {
                if (CanonicalVarNeedsPetCmd(e)) { calcBaseDelta += e.UpgradeAmount; continue; }
                w.Line($"base.DynamicVars[{Lit.Str(VarNameOf(e, cardVars))}].UpgradeValueBy({Lit.Dec(e.UpgradeAmount)});");
            }
            if (calcBaseDelta != 0m)
                w.Line($"base.DynamicVars.CalculationBase.UpgradeValueBy({Lit.Dec(calcBaseDelta)});"
                    + "   // 「按生命值算」的宠物效果：升级加的是固定加值（最大生命/当前生命那部分照旧跟着宠物走）");
            if (costChange)
            {
                // 改费用用的是本体自己的办法：OnUpgrade 里调用 EnergyCost.UpgradeBy(增量)
                int delta = targetCost!.Value - c.Cost;
                w.Line($"base.EnergyCost.UpgradeBy({delta});   // 升级后费用 {targetCost.Value}（原 {c.Cost}）");
            }
            // 升级后的关键字：本体「残影 / 幻影 / 寒冰」就是这么写的
            foreach (string kw in kwAdd)
                w.Line($"AddKeyword(CardKeyword.{kw});   // 升级后获得「{Profile.KeywordUpgradeSpec.Zh(kw)}」");
            foreach (string kw in kwDel)
                w.Line($"RemoveKeyword(CardKeyword.{kw});   // 升级后失去「{Profile.KeywordUpgradeSpec.Zh(kw)}」");
            w.Close();
        }
        w.Close();
        return w.ToString();
    }

    private static string ResolveTargetType(CardSpec c)
    {
        // 能打敌人的效果（伤害 / 状态 / 格挡 / 回血 / 掉血 / 最大生命）决定这张牌的 TargetType
        // 「伙伴攻击」同理：打的是敌人（attacker 是宠物），卡牌也要变成需要选目标的那种。
        // 「牺牲伙伴」收益是伤害时同理（生成的是 .Targeting(cardPlay.Target)），收益是格挡时不算。
        static bool HitsEnemy(EffectSpec e) =>
            e.Kind is "Damage" or "ApplyPower" or "Block" or "Heal" or "HpLoss" or "MaxHp"
            || PetAttackKind(e.Kind)
            || (e.Kind == "PetSacrifice" && e.PetSacrificeGain == "Damage");

        if (c.Effects.Any(e => HitsEnemy(e) && e.TargetSide == "Enemy")) return "AnyEnemy";
        if (c.Effects.Any(e => HitsEnemy(e) && e.TargetSide == "AllEnemies")) return "AllEnemies";
        if (c.Effects.Any(e => HitsEnemy(e) && e.TargetSide == "RandomEnemies")) return "RandomEnemy";
        return "Self";
    }

    /// <summary>
    /// 生成卡牌。照本体的官方做法用 CardPileCmd.AddToCombatAndPreview：
    /// 它会 CreateCard → AddGeneratedCardToCombat（记进战斗历史）→ 按牌堆类型弹预览。
    /// 之前用 AddGeneratedCardsToCombat 直接塞进抽牌堆/弃牌堆，界面上牌堆查看会出问题。
    /// </summary>
    private static void EmitGenerateCard(CodeWriter w, EffectSpec e, bool useX = false)
    {
        string card = string.IsNullOrWhiteSpace(e.SpawnCardId) ? "Shiv" : e.SpawnCardId!.Trim();
        string n = useX && e.AmountIsX ? XVar : Math.Max(1, (int)e.Amount).ToString();
        string pile = e.SpawnToPile;
        w.Line($"// 生成 {n} 张 {card} 放进{PileZh(pile)}");
        w.Line($"await CardPileCmd.AddToCombatAndPreview<{card}>(base.Owner.Creature, PileType.{pile}, {n}, base.Owner);");
    }

    /// <summary>选牌用的那一摞牌（本体写法：PileType.X.GetPile(player)）。</summary>
    private static string PileExpr(EffectSpec e, string player = "base.Owner") =>
        e.SelectPile switch
        {
            "Draw" => $"PileType.Draw.GetPile({player})",
            "Discard" => $"PileType.Discard.GetPile({player})",
            _ => $"PileType.Hand.GetPile({player})",
        };

    /// <summary>
    /// 消耗卡牌（参考铁甲战士的「坚毅」TrueGrit）：自选用 CardSelectCmd，随机用 Rng 抓牌。
    /// 「从哪里选牌」支持手牌 / 抽牌堆 / 弃牌堆：
    ///   手牌走本体 CardSelectCmd.FromHand；抽牌堆 / 弃牌堆走 CardSelectCmd.FromCombatPile
    ///   （本体「充能 / 净化」选抽牌堆、「全息影像 / 头槌」选弃牌堆都是这么写的）。
    /// </summary>
    private static void EmitExhaustCard(CodeWriter w, EffectSpec e, bool useX = false)
    {
        string n = useX && e.AmountIsX ? XVar : Math.Max(1, (int)e.Amount).ToString();
        string pileZh = EffectCatalog.SelectPileZh(e.SelectPile);
        if (e.CardPick == "Chosen")
        {
            w.Line($"// 自己从{pileZh}选 {n} 张消耗");
            if (e.SelectPile == "Hand")
                w.Line($"var toExhaust = (await CardSelectCmd.FromHand(context: choiceContext, player: base.Owner, prefs: new CardSelectorPrefs(CardSelectorPrefs.ExhaustSelectionPrompt, {n}), filter: null, source: this)).ToList();");
            else
                w.Line($"var toExhaust = (await CardSelectCmd.FromCombatPile(choiceContext, {PileExpr(e)}, base.Owner, new CardSelectorPrefs(CardSelectorPrefs.ExhaustSelectionPrompt, {n}))).ToList();");
            w.Line("foreach (CardModel c in toExhaust) await CardCmd.Exhaust(choiceContext, c);");
        }
        else
        {
            w.Line($"// 随机从{pileZh}消耗 {n} 张");
            w.Open($"for (int __pickIdx = 0; __pickIdx < {n}; __pickIdx++)");
            w.Line($"CardModel? pick = base.Owner.RunState.Rng.CombatCardSelection.NextItem({PileExpr(e)}.Cards);");
            w.Line("if (pick is null) break;");
            w.Line("await CardCmd.Exhaust(choiceContext, pick);");
            w.Close();
        }
    }

    /// <summary>
    /// 变化卡牌（参考储君的「下去」Begone）：
    /// 指定了目标卡 → CardCmd.Transform(原卡, 新卡)；没指定 → CardCmd.TransformToRandom（随机变化）。
    /// 「从哪里选牌」同消耗卡牌：手牌 / 抽牌堆 / 弃牌堆（本体「降灵 Seance / 充能 Charge」就是选抽牌堆变化）。
    /// </summary>
    private static void EmitTransformCard(CodeWriter w, EffectSpec e, bool useX = false)
    {
        string n = useX && e.AmountIsX ? XVar : Math.Max(1, (int)e.Amount).ToString();
        string? target = string.IsNullOrWhiteSpace(e.SpawnCardId) ? null : e.SpawnCardId!.Trim();
        string pileZh = EffectCatalog.SelectPileZh(e.SelectPile);

        if (e.CardPick == "Chosen")
        {
            w.Line($"// 自己从{pileZh}选 {n} 张变化");
            if (e.SelectPile == "Hand")
                w.Line($"var toTransform = (await CardSelectCmd.FromHand(context: choiceContext, player: base.Owner, prefs: new CardSelectorPrefs(CardSelectorPrefs.TransformSelectionPrompt, {n}), filter: null, source: this)).ToList();");
            else
                w.Line($"var toTransform = (await CardSelectCmd.FromCombatPile(choiceContext, {PileExpr(e)}, base.Owner, new CardSelectorPrefs(CardSelectorPrefs.TransformSelectionPrompt, {n}))).ToList();");
            w.Line("foreach (CardModel c in toTransform)");
            w.Open("");
            w.Line(target is null
                ? "await CardCmd.TransformToRandom(c, base.Owner.RunState.Rng.CombatCardSelection);"
                : $"await CardCmd.Transform(c, base.CombatState.CreateCard<{target}>(base.Owner));");
            w.Close();
        }
        else
        {
            w.Line($"// 随机从{pileZh}变化 {n} 张");
            w.Open($"for (int __pickIdx = 0; __pickIdx < {n}; __pickIdx++)");
            w.Line($"CardModel? pick = base.Owner.RunState.Rng.CombatCardSelection.NextItem({PileExpr(e)}.Cards);");
            w.Line("if (pick is null) break;");
            w.Line(target is null
                ? "await CardCmd.TransformToRandom(pick, base.Owner.RunState.Rng.CombatCardSelection);"
                : $"await CardCmd.Transform(pick, base.CombatState.CreateCard<{target}>(base.Owner));");
            w.Close();
        }
    }

    /// <summary>
    /// 从抽牌堆 / 弃牌堆挑牌拿到手牌（本体「搜寻 SecretWeapon / 全息影像 Hologram / 挖掘 Dredge」那种）：
    /// <c>CardSelectCmd.FromCombatPile(...)</c> + <c>CardPileCmd.Add(选中, PileType.Hand)</c>。
    /// 选牌界面的提示语用 <c>base.SelectionScreenPrompt</c>（本体每条卡牌 / 遗物 / 药水自己的那条，
    /// 本地化键是 &lt;ENTRY&gt;.selectionScreenPrompt，生成时会一起写出来）。
    /// </summary>
    private static void EmitTakeFromPile(CodeWriter w, EffectSpec e, string pile, bool useX = false)
    {
        string n = useX && e.AmountIsX ? XVar : Math.Max(1, (int)e.Amount).ToString();
        string pileZh = pile == "Draw" ? "抽牌堆" : "弃牌堆";
        string expr = $"PileType.{pile}.GetPile(base.Owner)";
