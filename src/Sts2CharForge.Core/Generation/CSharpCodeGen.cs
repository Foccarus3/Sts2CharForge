    internal static string? EffectConditionGuard(EffectSpec e, CondCtx ctx, bool inOnPlay = false,
        Dictionary<EffectSpec, (double Start, double End)>? chanceSlices = null)
    {
        string player = ctx == CondCtx.Power ? "base.Owner.Player" : "base.Owner";
        var parts = new List<string>();
        if (e.Condition is not null && !e.Condition.IsNone) parts.Add(ConditionExpr(e.Condition, ctx, inOnPlay));
        // 概率生效：本体自己也是这么掷的（例：Orobas 的 base.Rng.NextFloat() < 0.333f）。
        // 这里用 run 的通用随机数（Rng.Niche），保证同一局里可复现、也不跟抽牌/选目标抢随机序列。
        if (chanceSlices is not null && chanceSlices.TryGetValue(e, out var slice))
            parts.Add($"__chanceRoll >= {slice.Start.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture)} && __chanceRoll < {slice.End.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture)}");
        else if (e.ChanceEnabled)
            // 没传区间（单独调用）时退回「自己掷一次」的老写法
            parts.Add($"{player}.RunState.Rng.Niche.NextDouble() * 100.0 < {e.ChancePercent.ToString("0.####", System.Globalization.CultureInfo.InvariantCulture)}");
        if (parts.Count == 0) return null;
        return $"if ({string.Join(" && ", parts)})";
    }

