            .Line("await PowerCmd.Decrement(this);")
            .Close()
            .Close()
            .Close()
            .ToString();
    }

    private static void EmitPotionEffect(CodeWriter w, CharacterProfile p, EffectSpec e, string potionTarget,
        Dictionary<EffectSpec, string>? varMap = null) =>
        EmitRepeated(w, e, x => EmitPotionEffectOnce(x, p, e, potionTarget, varMap));

    /// <summary>药水：按「药水作用目标」展开（自己 / 指定敌人 / 全体敌人）。</summary>
    private static void EmitPotionPerCreature(CodeWriter w, string potionTarget, string allEnemies, Func<string, string> body)
    {
        if (potionTarget == "AllEnemies")
            w.Open($"foreach (Creature foe in {allEnemies})")
             .Line(body("foe"))
             .Close();
        else if (potionTarget == "AnyEnemy")
        {
            w.Open("if (target is not null)")
             .Line(body("target"))
             .Close();
        }
        else
            w.Line(body("base.Owner.Creature"));
    }

    private static void EmitPotionEffectOnce(CodeWriter w, CharacterProfile p, EffectSpec e, string potionTarget,
        Dictionary<EffectSpec, string>? varMap = null)
    {
        string amt = VarAccess(e, varMap);
        // 「直接把缓慢设成 N%」：本体做法是只施加 1 层（层数对「缓慢」没有作用）
        if (IsSlowPercentEffect(e)) amt = "1m";
        string allEnemies = "base.Owner.Creature.CombatState.HittableEnemies";
        switch (e.Kind)
        {
            case "EndTurn":
                w.Line("PlayerCmd.EndTurn(base.Owner, canBackOut: false);");
                break;

            case "ExtraTurn":
                w.Line($"await PowerCmd.Apply<{Naming.From(p).ExtraTurnPowerClass}>(choiceContext, base.Owner.Creature, 1m, base.Owner.Creature, null);");
                break;

            case "GenerateCard":
                EmitGenerateCard(w, e);
                break;

            case "ExhaustCard":
                EmitExhaustCard(w, e);
                break;

            case "TransformCard":
                EmitTransformCard(w, e);
                break;

            case "TakeFromDraw":
                EmitTakeFromPile(w, e, "Draw");
                break;

            case "TakeFromDiscard":
                EmitTakeFromPile(w, e, "Discard");
                break;

            // 全局（牌组）类效果：药水的 base.Owner 也是 Player
            case "AddCardGlobal":
            case "TransformCardGlobal":
            case "RemoveCardGlobal":
                EmitGlobalCardEffect(w, e, "base.Owner");
                break;

                case "CardReward":
                    EmitCardReward(w, e, "base.Owner");
                    break;

            case "Damage":
                if (potionTarget == "AllEnemies")
                    w.Line($"await CreatureCmd.Damage(choiceContext, {allEnemies}, {amt}, ValueProp.Move, base.Owner.Creature);");
                else if (potionTarget == "AnyEnemy")
                    w.Line($"await CreatureCmd.Damage(choiceContext, target, {amt}, ValueProp.Move, base.Owner.Creature);");
                else
                    w.Line("// 目标是自己的药水不会造成伤害");
                break;
            case "Block":
                EmitPotionPerCreature(w, potionTarget, allEnemies,
                    c => $"await CreatureCmd.GainBlock({c}, {BlockValueAccess(varMap, e)}, ValueProp.Move, null);");
                break;
            case "Draw":
                w.Line($"await CardPileCmd.Draw(choiceContext, {amt}, base.Owner);");
                break;
            case "Energy":
                w.Line($"await PlayerCmd.GainEnergy({amt}, base.Owner);");
                break;
            case "Heal":
                if (e.Amount < 0)
                    EmitPotionPerCreature(w, potionTarget, allEnemies,
                        c => $"await CreatureCmd.Damage(choiceContext, {c}, {-e.Amount}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, null, null);");
                else
                    EmitPotionPerCreature(w, potionTarget, allEnemies, c => $"await CreatureCmd.Heal({c}, {amt});");
                break;
            case "HpLoss":
                EmitPotionPerCreature(w, potionTarget, allEnemies,
                    c => $"await CreatureCmd.Damage(choiceContext, {c}, {amt}, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, null, null);");
                break;
            case "MaxHp":
                if (e.Amount < 0)
                    EmitPotionPerCreature(w, potionTarget, allEnemies,
                        c => $"await CreatureCmd.LoseMaxHp(choiceContext, {c}, {-e.Amount}, isFromCard: false);");
                else
                    EmitPotionPerCreature(w, potionTarget, allEnemies, c => $"await CreatureCmd.GainMaxHp({c}, {amt});");
                break;
            case "Gold":
                w.Line($"await PlayerCmd.GainGold({amt}, base.Owner);");
                break;
            case "ExtraResource":
                // 额外资源量 = 本体的星星资源。药水没有费用概念，负数直接扣（不会扣成负数）。
                if (e.Amount >= 0)
                    w.Line($"await PlayerCmd.GainStars({Lit.Dec(e.Amount)}, base.Owner);");
                else
                    w.Line($"await PlayerCmd.SetStars(System.Math.Max(0m, (decimal)base.Owner.PlayerCombatState.Stars - {Lit.Dec(-e.Amount)}), base.Owner);");
                break;
            case "ApplyPower":
                if (potionTarget == "AllEnemies")
                {
                    w.Open($"foreach (Creature foe in {allEnemies})")
                     .Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, foe, {amt}, base.Owner.Creature, null);");
                    if (IsSlowPercentEffect(e))
                        w.Line($"SlowPowerHelper.SetPercent(foe, {e.SlowPercentEffective});   // 本体「缓慢」：直接设成 {e.SlowPercentEffective}%");
                    w.Close();
                }
                else if (potionTarget == "AnyEnemy")
                {
                    w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, target, {amt}, base.Owner.Creature, null);");
                    EmitSlowPercentFix(w, e, "target");
                }
                else
                {
                    w.Line($"await PowerCmd.Apply<{e.PowerId}>(choiceContext, base.Owner.Creature, {amt}, base.Owner.Creature, null);");
                    EmitSlowPercentFix(w, e, "base.Owner.Creature");
                }
                break;

            // ===== 召唤伙伴：药水不支持 =====
            // 药水的 base.Owner 也是 Player，技术上能召唤；但本工具**故意不做**（用户要求本档只支持卡牌 + 遗物触发），
            // 所以这里必须留一行注释而不是让 switch 静默落空 —— 否则用户配了「喝药水召唤伙伴」会以为生效了。
            case "SummonPet":
                Warn(w, e, "（「召唤伙伴」只支持卡牌与遗物触发；药水不支持 —— 请改用卡牌或遗物）");
                break;

            case "PetAttack":
            case "PetDamageByMaxHp":
            case "PetDamageByCurHp":
            case "PetDamageByMissingHp":
            case "PetHeal":
            case "PetLoseHp":
            case "PetGainMaxHp":
            case "PetSacrifice":
            case "PetApplyPower":
            case "PetGuardOn":
            case "PetGuardOff":
                Warn(w, e, "（这一档的宠物效果只支持卡牌 —— 药水没有「玩家选中的目标」，请改用卡牌）");
                break;
        }
    }
