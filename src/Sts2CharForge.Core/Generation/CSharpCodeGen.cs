    public static string RelicPoolSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        var w = new CodeWriter();
        w.Line("// <auto-generated> 遗物池 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public sealed class {n.RelicPoolClass} : RelicPoolModel")
         .Line($"public override string EnergyColorName => {Lit.Str(n.EnergyColor)};")
         .Line()
         .Line("public override Color LabOutlineColor => StsColors.red;")
         .Line()
         .Open("protected override IEnumerable<RelicModel> GenerateAllRelics()")
         .Line("return")
         .Line("[");
