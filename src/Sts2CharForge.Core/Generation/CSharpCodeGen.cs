        for (int i = 0; i < p.Relics.Count; i++)
            w.Line($"    ModelDb.Relic<{n.RelicClassName(p.Relics[i], i)}>(),");
        // 额外资源量的隐藏起始遗物也必须进池：
        // 本体 RelicModel.Pool 是 First(...) 查找，找不到就抛 InvalidOperationException ——
        // 实测症状是「在选人界面点这个角色就报错，然后游戏继续用铁甲战士开局」。
        // 它是 Starter 稀有度，奖励只会抽 Common/Uncommon/Rare/Shop，所以不会被当成奖励发出来。
        if (p.ExtraResource.Enabled)
        {
            w.Line();
            w.Line("    // 额外资源量的载体（隐藏起始遗物）：必须在池里，否则本体查 Pool 会抛异常");
            w.Line($"    ModelDb.Relic<{Naming.From(p).ExtraResourceRelicClass}>(),");
        }
        w.Line("];").Close()
         .Line()
         .Line("// 没勾「加入遗物池」的：仍属于本角色，但不会出现在奖励/商店里")
         .Open("public override IEnumerable<RelicModel> GetUnlockedRelics(UnlockState unlockState)")
         .Line("var keep = base.GetUnlockedRelics(unlockState).ToList();");
        var rexcl = new List<string>();
        for (int i = 0; i < p.Relics.Count; i++)
            if (!p.Relics[i].InRelicPool) rexcl.Add($"ModelDb.Relic<{n.RelicClassName(p.Relics[i], i)}>()");
        if (rexcl.Count > 0)
        {
            w.Line($"keep.RemoveAll(r => r.Id == {rexcl[0]}.Id");
            for (int i = 1; i < rexcl.Count; i++)
                w.Line($"    || r.Id == {rexcl[i]}.Id");
            w.Line(");");
        }
        w.Line("return keep;").Close()
         .Close();
        return w.ToString();
    }

