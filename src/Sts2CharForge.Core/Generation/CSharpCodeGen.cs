    // ==================== 角色类 ====================
    public static string CharacterSource(CharacterProfile p)
    {
        var n = Naming.From(p);

        var deck = new List<string>();
        string outlineHex = Hex(p.Colors.EnergyOutlineColor, "802020");
        // 本体卡引用（卡牌页里那两条「打击 ×5 / 防御 ×5」）：直接写本体的英文类名。
        // 它们不生成自己的卡类（同名会和本体撞 ModelId → DuplicateModelException），只出现在初始卡组里。
        foreach (var vc in p.Cards.Where(c => c.IsVanillaCard))
        {
            string cls = (vc.ClassName ?? "").Trim();
            if (cls.Length == 0) continue;
            for (int k = 0; k < Math.Max(1, vc.StartingCopies); k++)
                deck.Add($"ModelDb.Card<{cls}>()");
        }
        for (int i = 0; i < p.Cards.Count; i++)
        {
            var c = p.Cards[i];
            if (c.IsVanillaCard) continue;
            if (!c.InStartingDeck) continue;
            for (int k = 0; k < Math.Max(1, c.StartingCopies); k++)
                deck.Add($"ModelDb.Card<{n.CardClassName(p, c)}>()");
        }

        var relics = new List<string>();
        for (int i = 0; i < p.Relics.Count; i++)
            if (p.Relics[i].IsStartingRelic) relics.Add($"ModelDb.Relic<{n.RelicClassName(p.Relics[i], i)}>()");
        // 额外资源量：加一个隐藏的起始遗物，负责开场发放初始数量 / 记录跨战斗继承
        if (p.ExtraResource.Enabled) relics.Add($"ModelDb.Relic<{n.ExtraResourceRelicClass}>()");
        // 不再给「没有自定义起始遗物」的角色兜底塞本体燃烧之血（用户要求：不用考虑是否携带初始遗物）

        var w = new CodeWriter();
        w.Line("// <auto-generated> 角色类 </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Open($"public sealed class {n.CharClass} : CharacterModel")
         .Line($"public const string energyColorName = {Lit.Str(n.EnergyColor)};")
         .Line()
         .Line($"public override CharacterGender Gender => CharacterGender.{p.Gender};")
         .Line();

        if (string.IsNullOrWhiteSpace(p.UnlockAfter))
        {
            w.Line("// null = 无需前置角色，一开始就能选");
            w.Line("protected override CharacterModel? UnlocksAfterRunAs => null;");
        }
        else
        {
            w.Line($"// 通关 {p.UnlockAfter} 之后解锁");
            w.Line($"protected override CharacterModel? UnlocksAfterRunAs => ModelDb.Character<{Naming.Pascal(p.UnlockAfter!)}>();");
        }

        w.Line()
         .Line("public override Color NameColor => StsColors.red;")
         .Line()
         .Line("// 左侧能量计数器里数字的描边色（NEnergyCounter 用的是角色上的这个属性，")
         .Line("// 和卡牌上的 EnergyOutlineColor 不是同一个，所以两边都要给）")
         .Line($"public override Color EnergyLabelOutlineColor => new Color(\"{outlineHex}\");");

        if (p.ExtraResource.Enabled && p.ExtraResource.AlwaysShowCounter)
        {
            w.Line()
             .Line("// 额外资源量：始终显示血条下面那一排里的资源计数器（本体默认不显示）")
             .Line("public override bool ShouldAlwaysShowStarCounter => true;");
        }

        w.Line()
         .Line($"public override int StartingHp => {p.StartingHp};")
         .Line()
         .Line($"public override int StartingGold => {p.StartingGold};")
         .Line()
         .Line($"public override CardPoolModel CardPool => ModelDb.CardPool<{n.CardPoolClass}>();")
         .Line()
         .Line($"public override PotionPoolModel PotionPool => ModelDb.PotionPool<{n.PotionPoolClass}>();")
         .Line()
         .Line($"public override RelicPoolModel RelicPool => ModelDb.RelicPool<{n.RelicPoolClass}>();")
         .Line()
         .Line("public override IEnumerable<CardModel> StartingDeck =>")
         .Line("[")
         .Line("    " + string.Join(",\n    ", deck))
         .Line("];")
         .Line()
         .Line("public override IReadOnlyList<RelicModel> StartingRelics =>")
         .Line("[")
         .Line("    " + string.Join(", ", relics))
         .Line("];")
         .Line()
         .Line($"public override float AttackAnimDelay => {Lit.Float(p.AttackAnimDelay)};")
         .Line()
         .Line($"public override float CastAnimDelay => {Lit.Float(p.CastAnimDelay)};")
         .Line()
         .Line("// 音效复用铁甲战士（自定义角色没有自己的 FMOD 资源）")
         .Line("public override string CharacterSelectSfx => ModelDb.Character<Ironclad>().CharacterSelectSfx;")
         .Line()
         .Line("public override string CharacterTransitionSfx => \"event:/sfx/ui/wipe_ironclad\";")
         .Line()
         .Line("public override List<string> GetArchitectAttackVfx() =>")
         .Line("[")
         .Line("    \"vfx/vfx_attack_blunt\",")
         .Line("    \"vfx/vfx_heavy_blunt\",")
         .Line("    \"vfx/vfx_attack_slash\",")
         .Line("    \"vfx/vfx_bloody_impact\",")
         .Line("    \"vfx/vfx_rock_shatter\"")
         .Line("];")
         .Close();
        return w.ToString();
    }

    // ==================== 额外资源量 ====================
    /// <summary>
    /// 额外资源量的载体（一个隐藏的起始遗物）。
    /// 本体没有「自定义资源」这种扩展点，所以额外资源量做在本体已有的「星星」资源上：
    /// 它同样是一个计数器，显示在血条下方、和状态同一行（本体储君用的就是它）。
    /// </summary>
    public static string ExtraResourceSource(CharacterProfile p)
    {
        var n = Naming.From(p);
        var x = p.ExtraResource;
        int initial = x.Initial;

        var w = new CodeWriter();
        w.Line("// <auto-generated> 额外资源量（做在本体的星星资源上） </auto-generated>")
         .Line($"namespace {n.Namespace};")
         .Line()
         .Line("/// <summary>")
         .Line("/// 额外资源量：和能量一样是个计数器，显示在角色血条下方、与状态同一行。")
         .Line("/// 本体没有自定义资源的扩展点，所以它复用本体的「星星」资源（PlayerCombatState.Stars）。")
         .Line("/// 这个遗物是起始遗物，只负责开场发放数量 / 记录跨战斗继承，不占用遗物栏的玩法位置。")
         .Line("/// </summary>")
         .Open($"public sealed class {n.ExtraResourceRelicClass} : RelicModel")
         .Line("public override RelicRarity Rarity => RelicRarity.Starter;")
         .Line()
         .Line($"/// <summary>每场战斗开始时发放的初始数量。</summary>")
         .Line($"private const int InitialAmount = {initial};")
         .Line()
         .Line("/// <summary>是否跨战斗继承：true = 开场数量 = 初始数量 + 上一场剩下的。</summary>")
         .Line($"private const bool CarryOver = {(x.CarryOver ? "true" : "false")};")
         .Line()
         .Line("/// <summary>上一场战斗结束时剩下的数量（只有开启继承时才会被记下来）。</summary>")
         .Line("private static int _carried;")
         .Line()
         .Line("/// <summary>照抄本体 DivineDestiny（储君的起始遗物 +7 星）的写法：每场战斗第一回合开始时发一次。</summary>")
         .Open("public override async Task AfterSideTurnStart(CombatSide side, IReadOnlyList<Creature> participants, ICombatState combatState)")
         .Line("if (!participants.Contains(base.Owner.Creature)) return;")
         .Line("if (base.Owner.PlayerCombatState == null || base.Owner.PlayerCombatState.TurnNumber > 1) return;")
         .Line()
         .Line("// 每场战斗开始时星星都是 0（PlayerCombatState 是新造的），所以这里发多少就是开场有多少。")
         .Line("int amount = CarryOver ? InitialAmount + _carried : InitialAmount;")
         .Line("if (amount <= 0) return;")
         .Line("await PlayerCmd.GainStars(amount, base.Owner);")
         .Close()
         .Line()
         .Line("/// <summary>战斗结束：记下余量给下一场用（关闭继承时清零，等于每场都从初始数量开始）。</summary>")
         .Open("public override Task AfterCombatEnd(CombatRoom room)")
         .Line("_carried = CarryOver ? (base.Owner.PlayerCombatState?.Stars ?? 0) : 0;")
         .Line("return Task.CompletedTask;")
         .Close()
         .Close();
        return w.ToString();
    }

    /// <summary>名字条高度（计数器底部留给名字的像素）。</summary>
