    /// kind = 这条效果属于什么（卡牌 / 遗物 / 自定义状态），决定「自己 / 战斗状态」怎么取。
    /// </summary>
    /// <summary>
    /// 「概率生效」的**合并**规则（用户要求）：同一张牌 / 同一只遗物 / 同一个触发时机里，所有勾了概率的
    /// 效果**共用一次掷骰**，各自占一段区间（按它们在列表里的顺序）。
    /// 例：第一条 40%、第二条 60% → 掷出 0~39.999 只跑第一条，40~99.999 只跑第二条
    ///（也就是「第一条没生效时，第二条必然生效」）。
    /// 总和不足 100 时，剩下的概率是「什么都不发生」；总和超过 100 时按比例缩放（校验器会提醒）。
    /// </summary>
    internal static Dictionary<EffectSpec, (double Start, double End)> ChanceSlices(IEnumerable<EffectSpec> effects)
    {
        var list = effects.Where(e => e.ChanceEnabled && e.ChancePercent > 0m).ToList();
        var map = new Dictionary<EffectSpec, (double, double)>();
        if (list.Count == 0) return map;
        double sum = (double)list.Sum(e => e.ChancePercent);
        double scale = sum > 100.0 ? 100.0 / sum : 1.0;
        double cursor = 0;
        foreach (var e in list)
        {
            double len = (double)e.ChancePercent * scale;
            if (len > 100.0) len = 100.0;
            map[e] = (cursor, Math.Min(100.0, cursor + len));
            cursor += len;
        }
        return map;
    }

