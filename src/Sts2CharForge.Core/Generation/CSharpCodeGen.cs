/// <summary>
/// 血条下方那个资源计数器：
///   · 图标换成你上传的那张图，并隐藏本体星星自带的两层旋转光效
///   · 在计数器下方显示你填的中文名
/// 本体在 Initialize(Player) 里告诉我们这个计数器是谁的，不是我们的角色就一点都不改。
/// </summary>
[HarmonyLib.HarmonyPatch(typeof(MegaCrit.Sts2.Core.Nodes.Combat.NStarCounter), nameof(MegaCrit.Sts2.Core.Nodes.Combat.NStarCounter._Ready))]
public static class ExtraResourceCounterPatch
{
    /// <summary>本体建好节点之后才轮到我们（Postfix）。</summary>
    [HarmonyLib.HarmonyPostfix]
    private static void AfterReady(MegaCrit.Sts2.Core.Nodes.Combat.NStarCounter __instance)
    {
        try
        {
            if (__instance.HasMeta(ExtraResourceUiConst.MineMeta)) ExtraResourceUi.Apply(__instance);
        }
        catch (Exception e)
        {
            // 界面补丁出问题绝不能把战斗搞崩：只记日志，保持本体原样
            Log.Error("额外资源量：计数器外观应用失败（已忽略）：" + e.Message);
        }
    }
}

/// <summary>计数器归谁：本体在 Initialize 里说得很清楚，不是我们的角色就一点都不改。</summary>
[HarmonyLib.HarmonyPatch(typeof(MegaCrit.Sts2.Core.Nodes.Combat.NStarCounter), nameof(MegaCrit.Sts2.Core.Nodes.Combat.NStarCounter.Initialize))]
public static class ExtraResourceCounterOwnerPatch
{
    [HarmonyLib.HarmonyPostfix]
    private static void AfterInitialize(MegaCrit.Sts2.Core.Nodes.Combat.NStarCounter __instance, Player player)
    {
        try
        {
            if (player?.Character is {{n.CharClass}})
            {
                __instance.SetMeta(ExtraResourceUiConst.MineMeta, true);
                ExtraResourceUi.Apply(__instance);
            }
            else
            {
                __instance.RemoveMeta(ExtraResourceUiConst.MineMeta);
            }
        }
        catch (Exception e)
        {
            Log.Error("额外资源量：判断资源计数器归属失败（已忽略）：" + e.Message);
        }
    }
}

/// <summary>
/// 卡面上的资源费用图标（本体也是那颗星星）：换成同一张自定义图，
/// 这样卡面费用和计数器看起来是同一种资源。只改我们自己卡池里的卡。
/// </summary>
[HarmonyLib.HarmonyPatch(typeof(MegaCrit.Sts2.Core.Nodes.Cards.NCard), nameof(MegaCrit.Sts2.Core.Nodes.Cards.NCard._Ready))]
public static class ExtraResourceCardIconPatch
{
    [HarmonyLib.HarmonyPostfix]
    private static void AfterReady(MegaCrit.Sts2.Core.Nodes.Cards.NCard __instance)
    {
        try
        {
            // 卡牌的 Model 可能在 _Ready 之后才挂上，所以跟着 ModelChanged 再刷一次
            __instance.ModelChanged += _ => ApplyCardIcon(__instance);
            ApplyCardIcon(__instance);
        }
        catch (Exception e)
        {
            Log.Error("额外资源量：卡面资源图标替换失败（已忽略）：" + e.Message);
        }
    }

    private static void ApplyCardIcon(MegaCrit.Sts2.Core.Nodes.Cards.NCard card)
    {
        try
        {
            if (ExtraResourceUiConst.IconPath.Length == 0) return;
            // 别的角色（本体储君等）的星星费用不要跟着变：只认我们自己卡池的卡
            if (card.Model?.Pool is not {{n.CardPoolClass}}) return;

            Texture2D? tex = ExtraResourceUi.LoadIcon();
            if (tex is null) return;

            foreach (TextureRect target in ExtraResourceUi.StarIconTargets(card, "%StarIcon", "%UnplayableStarIcon"))
                target.Texture = tex;
        }
        catch (Exception e)
        {
            Log.Error("额外资源量：卡面资源图标替换失败（已忽略）：" + e.Message);
        }
    }
}

/// <summary>真正改界面的地方（计数器）。</summary>
internal static class ExtraResourceUi
{
    private static Texture2D? _icon;
    private static bool _iconTried;

    /// <summary>本体那颗星星的贴图名（节点名万一和本体版本对不上时，靠贴图本身认）。</summary>
    private const string VanillaStarTexture = "energy_star";

    /// <summary>加载自定义图标；没配 / 加载不出来都返回 null（界面保持本体原样）。</summary>
    internal static Texture2D? LoadIcon()
    {
        if (_iconTried) return _icon;
        _iconTried = true;
        if (ExtraResourceUiConst.IconPath.Length == 0) return null;
        try
        {
            // 这里特意不用 ResourceLoader.Exists 做前置判断：模组 pck 是运行时挂载的，
            // 某些情况下 Exists 对刚挂载的资源会返回 false —— 那样图标会「静默不生效」，
            // 玩家看到的就是本体的星星，而日志里一条错都没有。直接 Load + 打日志更可靠。
            _icon = GD.Load<Texture2D>(ExtraResourceUiConst.IconPath);
        }
        catch (Exception e)
        {
            Log.Error("额外资源量：图标加载失败（已忽略）：" + e.Message);
        }
        if (_icon is null)
            Log.Warn("额外资源量：图标没加载出来，计数器保持本体外观：" + ExtraResourceUiConst.IconPath);
        return _icon;
    }

    /// <summary>
    /// 找出所有要换成自定义图的 TextureRect：
    ///   1. 先按本体节点名找（计数器是 "Icon"，卡面是 %StarIcon / %UnplayableStarIcon）
    ///   2. 再按「贴图就是本体那颗星星」在整个子树里扫一遍兜底
    /// 本体哪天改了节点名/结构，第 2 步也能兜住，不会再出现「图标静默不生效」。
    /// </summary>
    internal static List<TextureRect> StarIconTargets(Node root, params string[] nodePaths)
    {
        var targets = new List<TextureRect>();
        foreach (string path in nodePaths)
        {
            TextureRect? named = root.GetNodeOrNull<TextureRect>(path);
            if (named is not null && !targets.Contains(named)) targets.Add(named);
        }
        var found = new List<TextureRect>();
        CollectStarTextures(root, found);
        foreach (TextureRect tr in found)
            if (!targets.Contains(tr)) targets.Add(tr);
        return targets;
    }

    private static void CollectStarTextures(Node node, List<TextureRect> found)
    {
        if (node is TextureRect tr && tr.Texture is not null
            && (tr.Texture.ResourcePath ?? "").Contains(VanillaStarTexture, StringComparison.Ordinal))
        {
            found.Add(tr);
        }
        foreach (Node child in node.GetChildren())
            CollectStarTextures(child, found);
    }

    internal static void Apply(MegaCrit.Sts2.Core.Nodes.Combat.NStarCounter counter)
    {
        if (counter.HasMeta(ExtraResourceUiConst.AppliedMeta)) return;
        counter.SetMeta(ExtraResourceUiConst.AppliedMeta, true);

        Texture2D? tex = LoadIcon();
        if (tex is not null)
        {
            List<TextureRect> targets = StarIconTargets(counter, "Icon");
            EnsureIcon(counter);

            if (targets.Count == 0)
                Log.Warn("额外资源量：计数器里没找到星星贴图节点，图标没能换掉（本体结构可能变了）");
            else
                Log.Info("额外资源量：计数器图标已替换，命中 " + targets.Count + " 个节点");
        }

        AddNameLabel(counter);
    }

    private const string NameLabelMeta = "forge_extra_resource_name";

    /// <summary>
    /// 在计数器最下面那条加一句「资源名」（复制本体的数字标签，字体 / 描边都跟着本体）。
    /// 幂等：一个节点只加一次；找不到 %CountLabel（比如传进来的是卡牌节点）就什么都不做。
    /// </summary>
    internal static bool AddNameLabel(Node root)
    {
        if (ExtraResourceUiConst.DisplayName.Length == 0) return false;
